#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-11-02.
Aging test of the vertex-position CRSISF (q=6.7): is the decay from a late time origin slower
than from the first record? Uses the all-pairs two-time F_s that vertex_position_fs_kscan.py
stores for every production and vtx state, for junction and label tracking.

Physics:
  A run is equilibrated for t_w from a T=0.1 fluid and recorded for a window W = t_w, with
  records log-spaced from the window start. Origin record k has age t_w + t_k. In equilibrium
  F_s(t_k -> t_k + dt) does not depend on k.
  tau0: 1/e time of the replica-mean curve from the first record (age t_w).
  Late origins: records with t_k >= W/4 whose lags reach dt = tau0 (first lag <= tau0 <= W - t_k);
  if there are none, t_k >= W/16 ("mid"). Per replica i, d_i = <F_k,i(tau0) - F_0,i(tau0)>_late,
  paired within each replica. Both are log-linear in lag on origin k's lags (F_0 is first
  sampled on them), so the coarse lag grid of a late origin does not bias d.
  d = mean_i d_i, sem = std_i d_i / sqrt(n). ln(tau_late/tau0) ~ d / s +- sem / s,
  s = -dF_0/d ln dt at tau0 (replica mean).
  Verdict: aging if d > 2 sem, faster if d < -2 sem, else no detectable aging;
  n/a if no 1/e crossing in the window or no late origin reaches tau0.

Writes vertexModel_vertexPositionFsKScan/:
  aging_summary.csv     p0, T, kind, t_w, then per tracking (jn, label): tau0, tw_over_tau0,
                        group, age_late_over_tw, n_origins, d, d_sem, tau_ratio,
                        ln_tau_ratio_sem, verdict
  aging_tau_ratio.png   tau_late/tau0 vs t_w/tau0, junction and label, all states

Usage:
  python3 plot_vertex_position_fs_aging.py
"""

from __future__ import annotations

import math
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.ticker import NullFormatter, ScalarFormatter

from measure_and_plot_tau_alpha import INV_E
from plot_vertex_production_fs import P0_ORDER
from vertex_position_fs_kscan import out_dir as kscan_dir

HERE = Path(__file__).resolve().parent
OUTDIR = HERE / "vertexModel_vertexPositionFsKScan"
TRACKING = {"jn": "fs_pair_jn", "label": "fs_pair"}
LATE_FRAC, MID_FRAC = 0.25, 1.0 / 16.0
DLN = 0.15  # half step in ln(dt) of the slope -dF/d ln dt
Z_SIG = 2.0
P0_COLORS = dict(zip(P0_ORDER, ("#2a78d6", "#1baf7a", "#eda100", "#eb6834", "#e87ba4", "#6a4fb0")))


def interp_ln(lag: np.ndarray, f: np.ndarray, x: float) -> float:
    """f at lag x, linear in ln(lag)."""
    return float(np.interp(math.log(x), np.log(lag), f))


def tau_1e(lag: np.ndarray, f: np.ndarray) -> float:
    i = np.flatnonzero((f[:-1] >= INV_E) & (f[1:] < INV_E))
    if not i.size:
        return math.nan
    i = int(i[-1])
    return float(np.exp(np.interp(INV_E, [f[i + 1], f[i]], [np.log(lag[i + 1]), np.log(lag[i])])))


def age_test(t: np.ndarray, t_w: float, P: np.ndarray) -> dict:
    """P: (nrep, nrec, nrec) two-time F_s, [i, k, j] from record k to record j."""
    nrep = P.shape[0]
    W = t[-1]
    lag0 = t[1:]
    f0 = P[:, 0, 1:]
    tau0 = tau_1e(lag0, f0.mean(axis=0))
    out = {"tau0": tau0, "tw_over_tau0": t_w / tau0 if tau0 > 0 else math.nan, "group": "",
           "age_late_over_tw": math.nan, "n_origins": 0, "d": math.nan, "d_sem": math.nan,
           "tau_ratio": math.nan, "ln_tau_ratio_sem": math.nan, "verdict": "n/a"}
    if not math.isfinite(tau0):
        out["verdict"] = "n/a (no 1/e crossing)"
        return out
    members, group = [], ""
    for name, frac in (("late", LATE_FRAC), ("mid", MID_FRAC)):
        members = [k for k in range(1, t.size - 1)
                   if t[k] >= frac * W and t[k + 1] - t[k] <= tau0 <= W - t[k]]
        if members:
            group = name
            break
    if not members:
        out["verdict"] = "n/a (no late origin reaches tau0)"
        return out
    # the first-record curve is sampled on each origin's own (coarser) lags before the same
    # interpolation to tau0, so both sides carry the same interpolation error
    d_i = np.zeros(nrep)
    for k in members:
        lag_k = t[k + 1:] - t[k]
        for i in range(nrep):
            ref_k = np.interp(np.log(lag_k), np.log(lag0), f0[i])
            d_i[i] += interp_ln(lag_k, P[i, k, k + 1:], tau0) - interp_ln(lag_k, ref_k, tau0)
    d_i /= len(members)
    d, d_sem = float(d_i.mean()), float(d_i.std(ddof=1) / math.sqrt(nrep))
    fm = f0.mean(axis=0)
    s = -(interp_ln(lag0, fm, tau0 * math.exp(DLN)) - interp_ln(lag0, fm, tau0 * math.exp(-DLN))) / (2 * DLN)
    verdict = ("aging" if d > Z_SIG * d_sem else
               "faster" if d < -Z_SIG * d_sem else "no detectable aging")
    out.update(group=group, age_late_over_tw=float(1.0 + np.mean(t[members]) / t_w),
               n_origins=len(members), d=d, d_sem=d_sem, tau_ratio=math.exp(d / s),
               ln_tau_ratio_sem=d_sem / s, verdict=verdict)
    return out


def main() -> None:
    rows = []
    for path in sorted(kscan_dir().glob("kscan_*.npz")):
        z = np.load(path)
        t, t_w = z["t"], float(z["waiting_time"])
        row = {"p0": round(float(z["p0"]), 3), "T": float(z["T"]), "kind": str(z["kind"]), "t_w": t_w}
        for tr, name in TRACKING.items():
            for key, val in age_test(t, t_w, z[name]).items():
                row[f"{key}_{tr}"] = val
        rows.append(row)
    df = pd.DataFrame(rows).sort_values(["p0", "T"], ascending=[True, False])
    OUTDIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUTDIR / "aging_summary.csv", index=False)
    print(f"wrote {OUTDIR / 'aging_summary.csv'} ({len(df)} states)")

    fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.6), sharey=True, constrained_layout=True)
    for ax, (tr, title) in zip(axes, (("jn", "junction tracking"), ("label", "label tracking"))):
        for p0 in P0_ORDER:
            g = df[(df.p0 == p0) & np.isfinite(df[f"tau_ratio_{tr}"])]
            for kind, mk, fc in (("production", "o", None), ("vtx", "s", "none")):
                h = g[g.kind == kind]
                if h.empty:
                    continue
                c = P0_COLORS[p0]
                r = h[f"tau_ratio_{tr}"].to_numpy()
                e = h[f"ln_tau_ratio_sem_{tr}"].to_numpy()
                ax.errorbar(h[f"tw_over_tau0_{tr}"], r, yerr=[r - r * np.exp(-e), r * np.exp(e) - r], fmt=mk, ms=6,
                            color=c, mfc=c if fc is None else "none", mew=1.4, capsize=2, lw=1,
                            label=f"$p_0={p0:.3f}$" if kind == "production" else None)
        ax.axhline(1.0, color="#8a8985", lw=1, ls="--")
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.yaxis.set_major_formatter(ScalarFormatter())
        ax.yaxis.set_minor_formatter(ScalarFormatter())
        ax.xaxis.set_minor_formatter(NullFormatter())
        ax.set_xlabel(r"$t_w/\tau_0$ (equilibration time in units of $\tau_0$)")
        ax.set_title(title)
        ax.grid(alpha=0.3, which="both")
    axes[0].set_ylabel(r"$\tau_{\rm late}/\tau_0$ (late origins vs first record)")
    axes[0].legend(fontsize=8, title="filled: production, open: vtx", title_fontsize=8)
    fig.savefig(OUTDIR / "aging_tau_ratio.png", dpi=150)
    print(f"wrote {OUTDIR / 'aging_tau_ratio.png'}")


if __name__ == "__main__":
    main()
