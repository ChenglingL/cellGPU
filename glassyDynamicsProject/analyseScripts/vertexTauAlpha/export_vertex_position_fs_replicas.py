#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-10-27.
Export the per-replica vertex-position CRSISF of every analysed state, so fits can be
redone without scratch access.

Physics:
  F_s^CR(q, dt) = (1/N_v) sum_j J_0(q |dr_j^CR|), tracer = vertex position, q=6.7.
  One curve per (p0, T, idx), on its own log-spaced dt grid (dt = simulation time),
  read from the timeVertexCRSISF_*.nc files on scratch. Same states and q as
  combine_vertex_position_fs.py; Fs_combined_mean.csv is the replica mean of these
  curves interpolated onto a common grid.

Writes vertexModel_vertexPositionFs/Fs_replicas.csv.gz
  columns p0, T, q, idx, waitingTime, t, Fs (gzip; pandas reads it directly).

Usage:
  python3 export_vertex_position_fs_replicas.py
"""

from __future__ import annotations

import pandas as pd

from combine_vertex_position_fs import resolve_q
from measure_and_plot_tau_alpha import read_two_values
from plot_vertex_position_fs import CSV_VTX, OUTDIR, VERTEX_FS_NAME, scratch_fs
from plot_vertex_production_fs import load_state_points, match_p0


def main() -> None:
    q_use = resolve_q(None)
    expected = load_state_points((CSV_VTX,))
    rows: list[pd.DataFrame] = []
    for nc in sorted(scratch_fs().glob("p*/timeVertexCRSISF_*.nc")):
        m = VERTEX_FS_NAME.search(nc.name)
        if not m or abs(float(m.group("k")) - q_use) > 0.02:
            continue
        p0 = match_p0(float(m.group("p0")))
        T = float(m.group("T"))
        if p0 is None or not any(abs(p0 - p) < 1e-4 and abs(T - Tt) / Tt < 1e-5 for p, Tt in expected):
            continue
        dt, fs = read_two_values(nc)
        rows.append(pd.DataFrame({"p0": p0, "T": T, "q": q_use, "idx": int(m.group("idx")),
                                  "waitingTime": float(m.group("tw")), "t": dt, "Fs": fs}))
    df = pd.concat(rows).sort_values(["p0", "T", "idx", "t"])
    out = OUTDIR / "Fs_replicas.csv.gz"
    # mtime=0: identical bytes on a rerun
    df.to_csv(out, index=False, float_format="%.10g", compression={"method": "gzip", "mtime": 0})
    n_state = df.groupby(["p0", "T"]).ngroups
    print(f"wrote {out} ({len(df)} rows, {len(rows)} replicas, {n_state} state points, q={q_use:g})")


if __name__ == "__main__":
    main()
