"""
Generated by Claude Code. 2026-11-02.
tau_KWW(T) of the vertex-position CRSISF, label vs junction tracking, at q=6.7 and at the
S(q) peak k_max, next to the cell-centroid tau_KWW, one panel per p0 (log-log and Arrhenius).

Physics:
  tau_KWW: global Bayesian KWW fit of the replica-mean tails, mu(t) = A exp(-(t/tau)^beta),
  shared A and beta, one tau per (p0, T) (fit_vertex_fs_kww_hmc.py --share global --tail last_rise
  --hot-peak 0.32 --hot-fs-max 0.1 --hot-extra 3 on Fs_combined_mean_<variant>.csv).
  Label: the vertex array label is followed (vertexPositionFs.cpp). Junction: the label that holds
  the t0 cell triplet, which undoes the label swap of a T1 and its reverse T1
  (vertex_position_fs_kscan.py). Centroid: cell-centroid CRSISF, round-2 fit (production only).
  junction_q6.700_perp0 (csv only): the same junction curves with one (A, beta) per p0.
  Window W: last lag of the replica-mean curve (W = t_w = 10 tau_block).
  Flags (';'-joined): tau_gt_window (tau_KWW > W), fs_end_gt_0.2 (F_s(W) > 0.2: the curve has not
  reached ~A/e), no_1e_crossing (the curve never crosses 1/e). A flagged tau is the KWW form
  extrapolated past the data; it is drawn with a cross. An up-caret marks junction q=6.7 states
  whose decay from late time origins is slower than from the first record (aging_summary.csv,
  plot_vertex_position_fs_aging.py): there tau is still growing, a lower bound.
  Cold end (printed): each vtx tau over the line ln tau = a + b/T through the three coldest
  production states of its p0 and variant.

Writes vertexModel_vertexPositionFsKScan/:
  tau_kww_vs_T_variants.png      tau vs T, log-log
  tau_kww_vs_invT_variants.png   tau (log) vs 1/T, with the three-coldest-production lines (q=6.7)
  tau_kww_variants.csv           p0, T, kind, variant, tau, tau_std, flags

Usage:
  python3 plot_vertex_position_fs_kscan_tau.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.lines import Line2D

from plot_vertex_production_fs import P0_ORDER
from vertex_position_fs_kscan import vertex_states

HERE = Path(__file__).resolve().parent
KS = HERE / "vertexModel_vertexPositionFsKScan"
CENTROID = HERE / "vertexModel_productionFs"
# variant: (tau table, replica-mean F_s it was fitted on)
VARIANTS = {
    "centroid": (CENTROID / "round2" / "kww_global_tau.csv", CENTROID / "Fs_combined_mean.csv"),
    "label_q6.700": (KS / "kww_label_q6.700" / "kww_global_tau.csv", KS / "Fs_combined_mean_label_q6.700.csv"),
    "label_kmax": (KS / "kww_label_kmax" / "kww_global_tau.csv", KS / "Fs_combined_mean_label_kmax.csv"),
    "junction_q6.700": (KS / "kww_junction_q6.700" / "kww_global_tau.csv",
                        KS / "Fs_combined_mean_junction_q6.700.csv"),
    "junction_kmax": (KS / "kww_junction_kmax" / "kww_global_tau.csv", KS / "Fs_combined_mean_junction_kmax.csv"),
    "junction_q6.700_perp0": (KS / "kww_junction_q6.700_perp0" / "kww_per_p0_tau.csv",
                              KS / "Fs_combined_mean_junction_q6.700.csv"),
}
# drawn variants, back to front: legend label, color, marker, marker size, line style
STYLE = {
    "centroid": ("centroid (cells)", "#898781", "D", 5.0, "-"),
    "label_q6.700": (r"vertex label, $q=6.7$ (baseline)", "#1c5cab", "o", 6.5, "-"),
    "label_kmax": (r"vertex label, $k_{\max}$", "#5598e7", "o", 4.0, "--"),
    "junction_q6.700": (r"vertex junction, $q=6.7$", "#a8401a", "s", 6.5, "-"),
    "junction_kmax": (r"vertex junction, $k_{\max}$", "#eb6834", "s", 4.0, "--"),
}
EXTRAP_LINES = ("label_q6.700", "junction_q6.700")
AGING_CSV = KS / "aging_summary.csv"  # plot_vertex_position_fs_aging.py
AGING_VARIANT = "junction_q6.700"
FS_END_MAX = 0.2
INK = "#0b0b0b"
INK2 = "#52514e"
GRID = "#e1e0d9"

FS_TITLE = 17
FS_LABEL = 16
FS_TICK = 13
FS_LEGEND = 12


def state_kind() -> dict[tuple[float, float], str]:
    return {(p0, T): kind for p0, T, kind in vertex_states()}


def kind_of(kinds: dict, p0: float, T: float) -> str:
    for (p, t), k in kinds.items():
        if abs(p - p0) < 1e-4 and abs(t - T) / T < 1e-5:
            return k
    raise KeyError(f"p0={p0} T={T} is not a production or vtx state")


def load_variant(name: str, kinds: dict) -> pd.DataFrame:
    tau_csv, fs_csv = VARIANTS[name]
    tau = pd.read_csv(tau_csv)
    fs = pd.read_csv(fs_csv)
    rows = []
    for r in tau.itertuples(index=False):
        g = fs[np.isclose(fs["p0"], r.p0) & np.isclose(fs["T"], r.T)].sort_values("t")
        W, fs_end = float(g["t"].iloc[-1]), float(g["Fs_mean"].iloc[-1])
        flags = [f for f, on in (("tau_gt_window", r.tau_kww > W), ("fs_end_gt_0.2", fs_end > FS_END_MAX),
                                 ("no_1e_crossing", r.crossed_1e == 0)) if on]
        rows.append({"p0": round(float(r.p0), 3), "T": float(r.T), "kind": kind_of(kinds, r.p0, r.T),
                     "variant": name, "tau": float(r.tau_kww), "tau_std": float(r.tau_kww_std),
                     "flags": ";".join(flags)})
    return pd.DataFrame(rows)


def coldest_line(sub: pd.DataFrame) -> tuple[float, float, float]:
    """ln tau = a + b/T through the three coldest production states; returns a, b, their max 1/T."""
    prod = sub[sub["kind"] == "production"].nsmallest(3, "T")
    x = 1.0 / prod["T"].to_numpy()
    b, a = np.polyfit(x, np.log(prod["tau"].to_numpy()), 1)
    return a, b, float(x.max())


def extrapolation_table(df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for (name, p0), sub in df.groupby(["variant", "p0"]):
        vtx = sub[sub["kind"] == "vtx"]
        if vtx.empty:
            continue
        a, b, _ = coldest_line(sub)
        for r in vtx.itertuples(index=False):
            rows.append({"p0": p0, "T": r.T, "variant": name, "ratio": r.tau / np.exp(a + b / r.T)})
    return pd.DataFrame(rows).pivot_table(index=["p0", "T"], columns="variant", values="ratio")


def style_axes(ax) -> None:
    ax.tick_params(labelsize=FS_TICK, colors=INK2)
    ax.grid(True, which="major", color=GRID, lw=0.6, zorder=0)


def draw(df: pd.DataFrame, x_of, xlog: bool, xlabel: str, out: Path) -> None:
    fig = plt.figure(figsize=(14.0, 9.9))
    gs = fig.add_gridspec(2, 3, left=0.07, right=0.985, top=0.96, bottom=0.215, wspace=0.24, hspace=0.30)
    for i, p0 in enumerate(P0_ORDER):
        row, col = divmod(i, 3)
        ax = fig.add_subplot(gs[row, col])
        style_axes(ax)
        ax.set_yscale("log")
        if xlog:
            ax.set_xscale("log")
        for name, (_, color, marker, ms, ls) in STYLE.items():
            sub = df[(df["variant"] == name) & (df["p0"] == p0)].sort_values("T")
            if sub.empty:
                continue
            x = x_of(sub["T"].to_numpy())
            ax.plot(x, sub["tau"], color=color, ls=ls, lw=1.3, zorder=2)
            ax.errorbar(x, sub["tau"], yerr=sub["tau_std"], fmt="none", ecolor=color, elinewidth=1.0, zorder=2)
            for kind, face in (("production", color), ("vtx", "white")):
                m = (sub["kind"] == kind).to_numpy()
                ax.plot(x[m], sub["tau"][m], ls="", marker=marker, ms=ms, mfc=face, mec=color, mew=1.3, zorder=3)
            m = (sub["flags"] != "").to_numpy()
            ax.plot(x[m], sub["tau"][m], ls="", marker="x", ms=ms + 4, color=color, mew=1.6, zorder=4)
            if name == AGING_VARIANT:
                m = sub["aging"].to_numpy(bool)
                ax.plot(x[m], sub["tau"][m] * 1.6, ls="", marker=6, ms=9, color=color, zorder=4)
        if not xlog:
            # the three-coldest-production line, carried to the coldest state, as the cold-end reference
            lim = ax.get_ylim()
            for name in EXTRAP_LINES:
                sub = df[(df["variant"] == name) & (df["p0"] == p0)]
                if (sub["kind"] == "vtx").any():
                    a, b, x0 = coldest_line(sub)
                    xx = np.linspace(x0, x_of(sub["T"].min()), 50)
                    ax.plot(xx, np.exp(a + b * xx), color=STYLE[name][1], ls=":", lw=1.4, zorder=1)
            ax.set_ylim(lim)
        ax.set_title(rf"$p_0={p0:.3f}$", fontsize=FS_TITLE, color=INK, pad=4)
        if row == 1:
            ax.set_xlabel(xlabel, fontsize=FS_LABEL, color=INK)
        if col == 0:
            ax.set_ylabel(r"$\tau_{\mathrm{KWW}}$", fontsize=FS_LABEL, color=INK)
    handles = [Line2D([], [], color=c, ls=ls, lw=1.3, marker=mk, ms=ms, mfc=c, mec=c, label=lab)
               for lab, c, mk, ms, ls in STYLE.values()]
    handles += [
        Line2D([], [], ls="", marker="o", ms=6.5, mfc=INK2, mec=INK2, label="filled: production state"),
        Line2D([], [], ls="", marker="o", ms=6.5, mfc="white", mec=INK2, mew=1.3,
               label=r"open: vtx state ($t_w$ from the label $\tau$)"),
        Line2D([], [], ls="", marker="x", ms=10, color=INK2, mew=1.6,
               label=r"$\times$: $\tau>$ window or $F_s(W)>0.2$ (extrapolated)"),
        Line2D([], [], ls="", marker=6, ms=9, color=STYLE[AGING_VARIANT][1],
               label=r"$\blacktriangle$: junction $\tau$ still growing in the window (aging)"),
    ]
    if not xlog:
        handles.append(Line2D([], [], color=INK2, ls=":", lw=1.4,
                              label=r"$\ln\tau$ linear in $1/T$ through the 3 coldest production states"))
    fig.legend(handles=handles, ncol=3, loc="lower center", bbox_to_anchor=(0.5, 0.0), fontsize=FS_LEGEND,
               frameon=False, columnspacing=1.4, handletextpad=0.5)
    fig.savefig(out, dpi=150)
    plt.close(fig)
    print(f"wrote {out}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.parse_args()
    kinds = state_kind()
    df = pd.concat([load_variant(name, kinds) for name in VARIANTS], ignore_index=True)
    df = df.sort_values(["variant", "p0", "T"]).reset_index(drop=True)
    aging = pd.read_csv(AGING_CSV)
    is_aging = {(round(r.p0, 3), r.T): r.verdict_jn == "aging" for r in aging.itertuples(index=False)}
    df["aging"] = [
        next((v for (p, t), v in is_aging.items() if p == r.p0 and abs(t - r.T) / r.T < 1e-5), False)
        for r in df.itertuples(index=False)
    ]
    csv_path = KS / "tau_kww_variants.csv"
    df.to_csv(csv_path, index=False)
    print(f"wrote {csv_path} ({len(df)} rows)")
    print(df[df["flags"] != ""].to_string(index=False))

    draw(df, lambda T: np.asarray(T, float), True, r"$T$", KS / "tau_kww_vs_T_variants.png")
    draw(df, lambda T: 1.0 / np.asarray(T, float), False, r"$1/T$", KS / "tau_kww_vs_invT_variants.png")
    print("vtx tau / (ln tau linear in 1/T through the three coldest production states):")
    print(extrapolation_table(df).to_string(float_format=lambda v: f"{v:.3g}"))


if __name__ == "__main__":
    main()
