#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-09-30.
Cells get closer to regular hexagons at lower T and p0, but not all the way:
cell snapshots and edge-length distributions around s_hex.

Physics (mean cell area A0=1, N=4096): a regular hexagon of area 1 has side
  s_hex = sqrt(2/(3 sqrt 3)) ~ 0.620,
so a perfect honeycomb would give P(ell) = delta(ell - s_hex). Edges are the
unique 3-valent mesh edges of the production trajectories, last record of each
idx=0..9 (same frames as plot_vertex_hexagonality.py).

Output (vertexModel_edgeRegularity/):
  edge_snapshots.png      cells coloured by number of sides (no annotations)
  edge_distributions.png  P(ell) on cooling, P(ell) across p0 at fixed T,
                          fraction of edges within +-10% of s_hex vs T
  edge_hist.csv           P(ell) of the six plotted states
  edge_summary.csv        <ell>, sigma_ell, fraction within +-10%, all states

Usage:
  python3 plot_vertex_edge_regularity.py
Needs vertexModel_hexagonality/hex_metrics.csv with the edge columns
(python3 plot_vertex_hexagonality.py --recompute).
"""

from __future__ import annotations

import csv
import math

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch

from plot_vertex_hexagonality import (
    HERE, INK, INK2, METRICS, MUTED, P0_COLOR, P0_ORDER, P_SERIES, S_HEX, T_COLOR, T_SERIES, Z_COLOR,
    build_tissue, by_p0, draw_tissue, edge_sample, read_frame, style_axes, traj_paths,
)

OUTDIR = HERE / "vertexModel_edgeRegularity"
BINS = np.linspace(0.0, 1.4, 113)
NEAR = 0.10  # "close to s_hex" = within +-10%

FS_TITLE = 15
FS_LABEL = 15
FS_LEGEND = 10
FS_NOTE = 11


def load_metrics() -> list[dict]:
    with METRICS.open() as f:
        rows = [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]
    if "ell_std" not in rows[0]:
        raise SystemExit("hex_metrics.csv has no edge columns; run plot_vertex_hexagonality.py --recompute")
    return rows


def fig_snapshots() -> None:
    fig, axes = plt.subplots(2, 3, figsize=(13.2, 9.2))
    fig.subplots_adjust(left=0.07, right=0.99, top=0.9, bottom=0.03, wspace=0.06, hspace=0.14)
    for row, series, label in (
        (0, T_SERIES, rf"cooling at $p_0={T_SERIES[0][0]:.3f}$"),
        (1, P_SERIES, r"fixed $T\approx 0.012$, raising $p_0$"),
    ):
        for col, (p0, T) in enumerate(series):
            ax = axes[row, col]
            draw_tissue(ax, build_tissue(read_frame(traj_paths(p0, T)[0])), 14.0, 14.0, 20.0)
            ax.set_title(rf"$p_0={p0:.3f}$,  $T={T:.4g}$", fontsize=FS_TITLE, color=INK, pad=5)
        axes[row, 0].set_ylabel(label, fontsize=FS_LABEL, color=INK, labelpad=10)
    handles = [Patch(facecolor=Z_COLOR[k], edgecolor="#6f6e69", label=lab)
               for k, lab in ((4, r"$\leq 4$"), (5, "5"), (6, "6"), (7, "7"), (8, r"$\geq 8$"))]
    fig.legend(handles=handles, title="sides", loc="upper center", ncol=5, frameon=False,
               fontsize=FS_LEGEND + 2, title_fontsize=FS_LEGEND + 2, bbox_to_anchor=(0.53, 0.995))
    fig.savefig(OUTDIR / "edge_snapshots.png", dpi=150)
    plt.close(fig)


def near_frac(ell: np.ndarray) -> float:
    return float(np.mean(np.abs(ell / S_HEX - 1.0) < NEAR))


def draw_hist_panel(ax, series, colors, labels, title) -> list[dict]:
    style_axes(ax)
    ax.axvspan(S_HEX * (1 - NEAR), S_HEX * (1 + NEAR), color="#f0efec", zorder=0)
    ax.axvline(S_HEX, color=MUTED, lw=0.9, ls=(0, (4, 3)), zorder=1)
    ax.text(S_HEX * (1 - NEAR) - 0.015, 2.6, r"$s_{\mathrm{hex}}\pm10\%$", color=INK2, fontsize=FS_NOTE, ha="right")
    out = []
    for (p0, T), color, lab in zip(series, colors, labels):
        ell = edge_sample(p0, T)
        dens, _ = np.histogram(ell, bins=BINS, density=True)
        ax.stairs(dens, BINS, color=color, lw=1.8,
                  label=rf"{lab}: $\sigma_\ell={ell.std():.2f}$, {100 * near_frac(ell):.0f}% near $s_{{\mathrm{{hex}}}}$")
        out.append({"p0": p0, "T": T, "dens": dens, "ell_mean": float(ell.mean()), "ell_std": float(ell.std()),
                    "f_near": near_frac(ell), "n_edges": int(ell.size)})
    ax.set_xlim(0.0, 1.4)
    ax.set_ylim(0, 2.75)
    ax.set_xlabel(r"edge length $\ell$", fontsize=FS_LABEL, color=INK)
    ax.set_ylabel(r"$P(\ell)$", fontsize=FS_LABEL, color=INK)
    ax.set_title(title, fontsize=FS_TITLE, color=INK, loc="left")
    ax.legend(fontsize=FS_LEGEND - 1, frameon=False, loc="upper right")
    return out


def fig_distributions(rows: list[dict]) -> list[dict]:
    fig, axes = plt.subplots(1, 3, figsize=(17.5, 5.6))
    fig.subplots_adjust(left=0.05, right=0.99, top=0.9, bottom=0.13, wspace=0.24)
    hist = draw_hist_panel(axes[0], T_SERIES, T_COLOR, [rf"$T={T:.3g}$" for _, T in T_SERIES],
                           rf"(a) cooling at $p_0={T_SERIES[0][0]:.3f}$")
    hist += draw_hist_panel(axes[1], P_SERIES, [P0_COLOR[p] for p, _ in P_SERIES],
                            [rf"$p_0={p:.3f}$" for p, _ in P_SERIES], r"(b) fixed $T\approx0.012$")
    ax = axes[2]
    style_axes(ax)
    groups = by_p0(rows)
    for p0 in P0_ORDER:
        pts = [(r["T"], 100 * r["ell_fnear"]) for r in groups[p0]]
        x, y = np.array(pts).T
        ax.plot(x, y, "-o", color=P0_COLOR[p0], lw=1.6, ms=5, mec="white", mew=0.8, label=rf"$p_0={p0:.3f}$")
    ax.set_xscale("log")
    ax.set_ylim(10, 32)
    ax.set_xlabel(r"$T$", fontsize=FS_LABEL, color=INK)
    ax.set_ylabel(r"% of edges within $\pm10\%$ of $s_{\mathrm{hex}}$", fontsize=FS_LABEL, color=INK)
    ax.set_title("(c) concentration around $s_{\\mathrm{hex}}$, all states", fontsize=FS_TITLE, color=INK, loc="left")
    ax.text(0.97, 0.05, "regular hexagons: 100%", transform=ax.transAxes, ha="right", color=INK2, fontsize=FS_NOTE)
    ax.legend(fontsize=FS_LEGEND - 1, frameon=False, loc="upper right")
    fig.savefig(OUTDIR / "edge_distributions.png", dpi=150)
    plt.close(fig)
    return hist


def write_tables(hist: list[dict], rows: list[dict]) -> None:
    centers = 0.5 * (BINS[:-1] + BINS[1:])
    with (OUTDIR / "edge_hist.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["ell"] + [f"P_p{h['p0']:.3f}_T{h['T']:.8g}" for h in hist])
        for i, c in enumerate(centers):
            w.writerow([f"{c:.5f}"] + [f"{h['dens'][i]:.6g}" for h in hist])
    with (OUTDIR / "edge_summary.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["p0", "T", "ell_mean", "ell_std", "ell_cv", "frac_within_10pct_of_s_hex", "p6"])
        for r in sorted(rows, key=lambda r: (r["p0"], r["T"])):
            w.writerow([f"{r['p0']:.3f}", f"{r['T']:.8g}", f"{r['ell_mean']:.5f}", f"{r['ell_std']:.5f}",
                        f"{r['ell_std'] / r['ell_mean']:.4f}", f"{r['ell_fnear']:.4f}", f"{r['p6']:.4f}"])


def main() -> None:
    OUTDIR.mkdir(parents=True, exist_ok=True)
    rows = load_metrics()
    fig_snapshots()
    hist = fig_distributions(rows)
    write_tables(hist, rows)
    print(f"s_hex = {S_HEX:.4f}; wrote {OUTDIR}/edge_snapshots.png, edge_distributions.png, edge_hist.csv, edge_summary.csv")
    for h in hist:
        print(f"  p0={h['p0']:.3f} T={h['T']:.4g}: <ell>={h['ell_mean']:.3f} sigma={h['ell_std']:.3f} "
              f"near s_hex={100 * h['f_near']:.1f}%  (n={h['n_edges']})")
    groups = by_p0(rows)
    for p0 in P0_ORDER:
        c, hot = groups[p0][0], groups[p0][-1]
        print(f"  p0={p0:.3f}: hot T={hot['T']:.3g} sigma={hot['ell_std']:.3f} near={100 * hot['ell_fnear']:.0f}% | "
              f"coldest T={c['T']:.3g} <ell>={c['ell_mean']:.3f} sigma={c['ell_std']:.3f} near={100 * c['ell_fnear']:.0f}%")


if __name__ == "__main__":
    main()
