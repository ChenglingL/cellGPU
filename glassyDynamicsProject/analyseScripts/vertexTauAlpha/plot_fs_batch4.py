#!/usr/bin/env python3
"""
Generated by Cursor. 2026-08-26.
CRSISF Fs(dt) for all 12 fourth-batch vertex tau_alpha state points.

Physics:
  F_s^CR(q, dt) from timeCRSISF NetCDF, q = 6.80. Color is t_w / tau_block
  (red short, blue long). Dashed line is 1/e, the tau_alpha crossing.

Usage:
  python3 plot_fs_batch4.py
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.cm import ScalarMappable
from matplotlib.colors import Normalize

from measure_and_plot_tau_alpha import (
    FS_NAME,
    INV_E,
    Q_DEFAULT,
    read_two_values,
    scratch_root,
)
from measure_and_plot_tau_alpha_batch2 import load_batch2_points

HERE = Path(__file__).resolve().parent
STATE_CSV = HERE / "vertexModel_tauAlpha_batch4" / "state_points.csv"
OUTDIR = HERE / "vertexModel_tauAlpha_batch4"
N = 4096


def load_panel(p0, T, est):
    tau_block = max(1000.0, est)
    datadir = scratch_root(N) / f"p{p0:.3f}"
    panel = []
    if not datadir.is_dir():
        return tau_block, panel
    for nc in sorted(datadir.glob(f"timeCRSISF_N{N}_p{p0:.4f}_T*.nc")):
        m = FS_NAME.search(nc.name)
        if not m:
            continue
        Tfile = float(m.group("T"))
        if abs(Tfile - T) / max(abs(T), 1e-30) > 1e-5:
            continue
        if abs(float(m.group("k")) - Q_DEFAULT) > 0.02:
            continue
        tw = float(m.group("tw"))
        dt, fs = read_two_values(nc)
        panel.append((tw / tau_block, tw, dt, fs))
    panel.sort(key=lambda x: x[0])
    return tau_block, panel


def draw_panel(ax, p0, T, est, panel, cmap, norm):
    for kwait, _tw, dt, fs in panel:
        mask = dt > 0
        ax.plot(dt[mask], fs[mask], color=cmap(norm(kwait)), lw=1.1, alpha=0.9)
    ax.axhline(INV_E, color="k", ls="--", lw=1.0, zorder=5)
    ax.set_xscale("log")
    ax.set_ylim(-0.05, 1.08)
    ax.set_title(rf"$p_0={p0:.3f}$, $T={T:g}$, $\tau_{{\alpha,k}}={est:g}$")
    ax.set_ylabel(r"$F_s^{\mathrm{CR}}(q,\Delta t)$")
    ax.set_xlabel(r"$\Delta t$")


def main():
    pts = load_batch2_points(STATE_CSV)
    OUTDIR.mkdir(parents=True, exist_ok=True)
    cmap = plt.get_cmap("coolwarm_r")
    loaded = []
    kmax = 1.0
    for p0, T, est in pts:
        tau_block, panel = load_panel(p0, T, est)
        if panel:
            kmax = max(kmax, max(z[0] for z in panel))
        loaded.append((p0, T, est, tau_block, panel))
        print(f"  p0={p0:.3f} T={T:g} n_curves={len(panel)}")

    norm = Normalize(vmin=0.0, vmax=max(kmax, 1.0))

    fig, axes = plt.subplots(4, 3, figsize=(12.4, 13.6), sharey=True)
    for ax, (p0, T, est, _tb, panel) in zip(axes.ravel(), loaded):
        draw_panel(ax, p0, T, est, panel, cmap, norm)
    sm = ScalarMappable(norm=norm, cmap=cmap)
    sm.set_array([])
    cbar = fig.colorbar(sm, ax=axes.ravel().tolist(), fraction=0.02, pad=0.02)
    cbar.set_label(r"$t_w / \tau_{\mathrm{block}}$ (red short, blue long)")
    fig.suptitle(
        rf"vertex batch 4 CRSISF, $N={N}$, $q={Q_DEFAULT:g}$ (dashed: $1/e$)",
        y=0.995,
    )
    grid = OUTDIR / "vertexModel_tauAlpha_batch4_Fs_grid.png"
    fig.savefig(grid, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {grid}")

    for p0, T, est, _tb, panel in loaded:
        fig, ax = plt.subplots(figsize=(7.2, 5.0))
        draw_panel(ax, p0, T, est, panel, cmap, norm)
        sm = ScalarMappable(norm=norm, cmap=cmap)
        sm.set_array([])
        cbar = fig.colorbar(sm, ax=ax)
        cbar.set_label(r"$t_w / \tau_{\mathrm{block}}$ (red short, blue long)")
        fig.tight_layout()
        out = OUTDIR / f"vertexModel_tauAlpha_batch4_Fs_p{p0:.3f}_T{T:.6g}.png"
        fig.savefig(out, dpi=150)
        plt.close(fig)
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
