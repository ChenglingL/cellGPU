#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-11-02.
Why the label-tracked vertex-position tau_alpha bends below the trend on cooling: T1 flicker swaps
vertex labels without changing the cells; the S(q) peak k_max hardly moves at the cold end.

Physics:
  A T1 turns the short edge v1 -> v2 (v1 < v2) by +90 deg, so a T1 and its reverse turn it by
  180 deg: the cells are as before, but the two labels have traded junctions (~one edge, 0.64).
  At the first-record origin and lag t: swapped = fraction of t0 junctions (cell triplets) held by
  another label, dead = fraction of t0 triplets that no longer exist (a T1 not undone).
  Read at the 1/e time of the label F_s(q=6.7). tau: KWW of the replica means
  (tau_kww_variants.csv; label = array label as vertexPositionFs.cpp, junction = cell triplet,
  centroid = cell CRSISF round 2). k_max: vertex S(q) first peak (kmax.csv).

Writes vertexModel_vertexPositionFsKScan/:
  swap_mechanism.png   (a) swapped and dead at tau_label vs tau_label, (b) tau ratios vs the
                       junction tau, (c) k_max vs T, (d) tau(k_max)/tau(6.7) vs the junction tau
  swap_summary.csv     one row per state

Usage:
  python3 plot_vertex_position_fs_swaps.py
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from plot_vertex_production_fs import P0_ORDER

HERE = Path(__file__).resolve().parent
KS = HERE / "vertexModel_vertexPositionFsKScan"
P0_COLORS = dict(zip(P0_ORDER, ("#2a78d6", "#1baf7a", "#eda100", "#eb6834", "#e87ba4", "#6a4fb0")))


def same_state(a: pd.DataFrame, p0: float, T: float) -> pd.DataFrame:
    return a[np.isclose(a["p0"], p0) & (np.abs(a["T"] - T) / T < 1e-5)]


def summary() -> pd.DataFrame:
    tau1e = pd.read_csv(KS / "tau_1e.csv")
    frac = pd.read_csv(KS / "junction_fractions.csv")
    kmax = pd.read_csv(KS / "kmax.csv")
    kww = pd.read_csv(KS / "tau_kww_variants.csv")
    kww = kww.pivot_table(index=["p0", "T"], columns="variant", values="tau").reset_index()
    out = []
    for _, r in tau1e.iterrows():
        p0, T = r["p0"], r["T"]
        tl = r["tau_1e_label_q6.700"]
        g = same_state(frac, p0, T).sort_values("t")
        sw = dd = np.nan
        if np.isfinite(tl) and len(g):
            x = np.log(g["t"].to_numpy())
            sw = float(np.interp(np.log(tl), x, g["swapped"]))
            dd = float(np.interp(np.log(tl), x, g["dead"]))
        k = same_state(kww, p0, T)
        km = same_state(kmax, p0, T)
        get = lambda col: float(k[col].iloc[0]) if col in k and len(k) and np.isfinite(k[col].iloc[0]) else np.nan
        out.append({
            "p0": p0, "T": T, "kind": r["kind"], "k_max": float(km["k_max"].iloc[0]),
            "tau_1e_label": tl, "swapped_at_tau_label": sw, "dead_at_tau_label": dd,
            "tau_label": get("label_q6.700"), "tau_label_kmax": get("label_kmax"),
            "tau_junction": get("junction_q6.700"), "tau_junction_kmax": get("junction_kmax"),
            "tau_centroid": get("centroid"),
        })
    s = pd.DataFrame(out).sort_values(["p0", "T"], ascending=[True, False])
    s["junction_over_label"] = s["tau_junction"] / s["tau_label"]
    s["centroid_over_junction"] = s["tau_centroid"] / s["tau_junction"]
    s["label_kmax_over_q6.7"] = s["tau_label_kmax"] / s["tau_label"]
    s["junction_kmax_over_q6.7"] = s["tau_junction_kmax"] / s["tau_junction"]
    return s


def main() -> None:
    s = summary()
    s.to_csv(KS / "swap_summary.csv", index=False)
    print(f"wrote {KS / 'swap_summary.csv'} ({len(s)} states)")

    fig, axes = plt.subplots(2, 2, figsize=(12.5, 9.4), constrained_layout=True)
    (a, b), (c, d) = axes
    for p0 in P0_ORDER:
        g = s[s.p0 == p0]
        col = P0_COLORS[p0]
        for kind, face in (("production", col), ("vtx", "white")):
            h = g[g.kind == kind]
            lab = rf"$p_0={p0:.3f}$" if kind == "production" else None
            a.plot(h.tau_1e_label, h.swapped_at_tau_label, "o", mfc=face, mec=col, color=col, mew=1.3, label=lab)
            a.plot(h.tau_1e_label, h.dead_at_tau_label, "v", mfc=face, mec=col, mew=1.3, alpha=0.75)
            b.plot(h.tau_junction, h.junction_over_label, "o", mfc=face, mec=col, mew=1.3, label=lab)
            b.plot(h.tau_junction, h.centroid_over_junction, "D", ms=5, mfc=face, mec="#8a8985", mew=1.1)
            c.plot(h["T"], h.k_max, "o", mfc=face, mec=col, mew=1.3, label=lab)
            d.plot(h.tau_junction, h["label_kmax_over_q6.7"], "o", mfc=face, mec=col, mew=1.3, label=lab)
            d.plot(h.tau_junction, h["junction_kmax_over_q6.7"], "s", mfc=face, mec=col, mew=1.3, alpha=0.6)
        c.plot(g["T"], g.k_max, "-", color=col, lw=1, alpha=0.6)
    a.set(xscale="log", xlabel=r"label $\tau_{1/e}$ ($q=6.7$)", ylabel="fraction of junctions at the label 1/e time",
          title="(a) swapped labels (circles) vs changed junctions (triangles)")
    b.axhline(1.0, color="#8a8985", lw=1, ls="--")
    b.set(xscale="log", yscale="log", xlabel=r"junction $\tau_{\rm KWW}$ ($q=6.7$)",
          ylabel=r"$\tau$ ratio", title=r"(b) $\tau_{\rm junction}/\tau_{\rm label}$ (color), "
                                         r"$\tau_{\rm centroid}/\tau_{\rm junction}$ (grey)")
    c.axhline(6.7, color="#8a8985", lw=1, ls="--")
    c.set(xscale="log", xlabel=r"$T$", ylabel=r"$k_{\max}$ of vertex $S(q)$",
          title=r"(c) S(q) peak; dashed: $q=6.7$ used so far")
    d.axhline(1.0, color="#8a8985", lw=1, ls="--")
    d.set(xscale="log", xlabel=r"junction $\tau_{\rm KWW}$ ($q=6.7$)",
          ylabel=r"$\tau_{\rm KWW}(k_{\max})/\tau_{\rm KWW}(6.7)$",
          title="(d) k_max effect: label (circles), junction (squares)")
    for ax in axes.flat:
        ax.grid(alpha=0.3, which="both")
    a.legend(fontsize=8, title="filled: production, open: vtx", title_fontsize=8)
    fig.savefig(KS / "swap_mechanism.png", dpi=150)
    print(f"wrote {KS / 'swap_mechanism.png'}")


if __name__ == "__main__":
    main()
