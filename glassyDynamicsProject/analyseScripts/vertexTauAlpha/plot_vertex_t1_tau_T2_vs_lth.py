#!/usr/bin/env python3
"""
Generated by Cursor. 2026-09-08.
tau_alpha * T^2 vs l_T1 at p0=3.800, one series per T.

Physics:
  T1 fires when edge length < l_T1 (mean cell area 1). If tau_alpha
  scaled as T^{-2}, tau_alpha T^2 would collapse vs l_T1. Color is T:
  red hot, blue cold (log T). t1Scan recommended T grid only.

Usage:
  python3 glassyDynamicsProject/analyseScripts/vertexTauAlpha/plot_vertex_t1_tau_T2_vs_lth.py
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.cm import ScalarMappable
from matplotlib.colors import LogNorm

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from plot_vertex_t1_tau_vs_lth import CSV, N, P0, load_t1scan

OUT = HERE / "vertexModel_t1Scan" / "vertex_t1_tau_T2_vs_lth.png"


def main():
    rows = load_t1scan(CSV)
    if not rows:
        raise SystemExit(f"no t1Scan rows in {CSV}")
    by_T = defaultdict(list)
    for r in rows:
        by_T[r["T"]].append(r)
    Ts = sorted(by_T, reverse=True)
    cmap = plt.get_cmap("coolwarm")
    norm = LogNorm(vmin=min(Ts), vmax=max(Ts))

    fig, ax = plt.subplots(figsize=(6.8, 5.0))
    for T in Ts:
        sub = sorted(by_T[T], key=lambda r: r["t1"])
        ax.plot(
            [r["t1"] for r in sub],
            [r["tauAlpha"] * T * T for r in sub],
            color=cmap(norm(T)),
            marker="o",
            markersize=5,
            lw=1.2,
        )
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel(r"$\ell_{T1}$")
    ax.set_ylabel(r"$\tau_\alpha\,T^{2}$")
    ax.set_title(rf"$N={N}$, $p_0={P0:.3f}$")
    sm = ScalarMappable(norm=norm, cmap=cmap)
    sm.set_array([])
    cbar = fig.colorbar(sm, ax=ax)
    cbar.set_label(r"$T$ (red hot, blue cold)")
    fig.tight_layout()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT, dpi=150)
    plt.close(fig)
    print(f"wrote {OUT} ({len(Ts)} T, {len(rows)} points)")


if __name__ == "__main__":
    main()
