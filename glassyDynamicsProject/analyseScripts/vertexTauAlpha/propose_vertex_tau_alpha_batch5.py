#!/usr/bin/env python3
"""
Generated by Cursor. 2026-09-10.
Fifth-batch T grid at default l_T1=0.01 from batches 2-4 longest-crossed tau_alpha.

Physics:
  tau_alpha is the longest t_w whose CRSISF still crosses 1/e (q=6.80,
  cell centroids). Invert log tau vs 1/T (hot end: log T). Default T1
  cutoff l_T1=0.01 (mean cell area 1). Rerun tau_k = 10**(1+k/3) if the
  current-best run (batch 4 else 3 else 2) never crossed or differs from
  tau_k by a factor >= 1.5. Also include two coverage extras: p0=3.775
  tau=10 (ratio 1.48 and log-T hot) and p0=3.815 tau=10^4 (unsampled gap
  6798-25085). Units: reduced kT, p0 target shape index.

Usage:
  python3 propose_vertex_tau_alpha_batch5.py
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from propose_vertex_tau_alpha_batch4 import (
    B2_STATE,
    B3_STATE,
    CURVE_B1,
    CURVE_B2,
    CURVE_B3,
    P0_ORDER,
    RATIO_CUT,
    TAU_TARGETS,
    find_state_T,
    fold_ratio,
    invert_T_for_tau_meas,
    load_curves,
    load_state,
    longest_crossed_tw_rows,
    match_anchor,
    meas_table,
    merge_anchors,
    tau_meas_of_T,
    write_csv,
)

CURVE_B4 = HERE / "vertexModel_tauAlpha_batch4" / "vertexModel_tauAlpha_batch4_per_curve.csv"
B4_STATE = HERE / "vertexModel_tauAlpha_batch4" / "state_points.csv"
OUTDIR = HERE / "vertexModel_tauAlpha_batch5"

# Extra (p0, tau_k) even if fold-ratio is just under 1.5.
EXTRAS = (
    (3.775, 10.0, "logT_hot"),
    (3.815, 1.0e4, "cold_gap"),
)


def is_extra(p0, tau_k):
    for ep0, etau, reason in EXTRAS:
        if abs(p0 - ep0) < 1e-4 and abs(tau_k - etau) / etau < 1e-4:
            return reason
    return None


def plot_grid(anchors, points, outpath: Path):
    fig, axes = plt.subplots(2, 3, figsize=(11.0, 7.2), sharex=False, sharey=True)
    batch_style = {
        1: dict(c="0.55", s=22, zorder=3, label="batch-1 longest crossed"),
        2: dict(c="C1", s=28, zorder=4, label="batch-2 longest crossed"),
        3: dict(c="C3", s=36, zorder=5, label="batch-3 longest crossed"),
        4: dict(c="C4", s=40, zorder=6, label="batch-4 longest crossed"),
    }
    for i, p0 in enumerate(P0_ORDER):
        ax = axes.ravel()[i]
        tab = meas_table([a for a in anchors if a["batch"] >= 2], p0)
        aa = [a for a in anchors if abs(a["p0"] - p0) < 1e-4]
        for b, sty in batch_style.items():
            crossed = [
                a
                for a in aa
                if a["batch"] == b and a["crossed"] == 1 and math.isfinite(a["tauAlpha"])
            ]
            if not crossed:
                continue
            ax.scatter(
                [a["T"] for a in crossed],
                [a["tauAlpha"] for a in crossed],
                c=sty["c"],
                s=sty["s"],
                zorder=sty["zorder"],
                label=sty["label"],
            )
        if len(tab) >= 2:
            Ts = np.geomspace(min(T for T, _ in tab) * 0.6, max(T for T, _ in tab) * 1.3, 80)
            ax.plot(Ts, [tau_meas_of_T(tab, T) for T in Ts], "C0-", lw=1.1, label=r"interp $\tau(T)$")
        pp = [p for p in points if abs(float(p["p0"]) - p0) < 1e-4]
        if pp:
            ax.scatter(
                [float(p["T"]) for p in pp],
                [float(p["tauAlphaEst"]) for p in pp],
                facecolors="none",
                edgecolors="C2",
                s=52,
                zorder=7,
                label="batch-5 $T$",
            )
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_title(rf"$p_0={p0:.3f}$")
        ax.set_xlabel(r"$T$")
        ax.set_ylabel(r"$\tau_\alpha$")
        ax.legend(loc="best", fontsize=6, frameon=False)
    fig.suptitle(r"batch 5: default $\ell_{T1}=0.01$, $T$ from batches 2--4", y=1.01)
    fig.tight_layout()
    fig.savefig(outpath, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {outpath}")


def main():
    a1 = longest_crossed_tw_rows(load_curves(CURVE_B1), 1)
    a2 = longest_crossed_tw_rows(load_curves(CURVE_B2), 2)
    a3 = longest_crossed_tw_rows(load_curves(CURVE_B3), 3)
    a4 = longest_crossed_tw_rows(load_curves(CURVE_B4), 4)
    anchors_all = merge_anchors(a1, a2, a3, a4)
    anchors_inv = merge_anchors(a2, a3, a4)
    b2 = load_state(B2_STATE)
    b3 = load_state(B3_STATE)
    b4 = load_state(B4_STATE)

    points = []
    print("batch-5 reruns (default l_T1=0.01):")
    for p0 in P0_ORDER:
        tab = meas_table(anchors_inv, p0)
        if len(tab) < 2:
            raise SystemExit(f"need >=2 measured anchors for p0={p0}")
        for tau_k in TAU_TARGETS:
            T4 = find_state_T(b4, p0, tau_k)
            T3 = find_state_T(b3, p0, tau_k)
            T2 = find_state_T(b2, p0, tau_k)
            if T4 is not None:
                T_old, src_run, pool = T4, "b4", a4
            elif T3 is not None:
                T_old, src_run, pool = T3, "b3", a3
            else:
                T_old, src_run, pool = T2, "b2", a2
            anc = match_anchor(p0, T_old, pool) if T_old is not None else None
            meas = anc["tauAlpha"] if anc and anc["crossed"] == 1 else math.nan
            rat = fold_ratio(meas, tau_k)
            never = not math.isfinite(meas)
            off = math.isfinite(rat) and rat >= RATIO_CUT
            extra = is_extra(p0, tau_k)
            print(
                f"  p0={p0:.3f} tau_k={tau_k:.6g} {src_run} T={T_old if T_old else math.nan:.6g} "
                f"meas={meas:.4g} ratio={rat:.3g}"
            )
            if not (never or off or extra):
                continue
            T, how = invert_T_for_tau_meas(tab, tau_k)
            src = "meas_inverted_logT" if how == "logT" else "meas_inverted"
            if never:
                reason = "never_crossed"
            elif off:
                reason = "ratio>=1.5"
            else:
                reason = extra
            print(f"    -> T_new={T:.6g} {reason} {src}")
            points.append(
                {
                    "p0": f"{p0:.3f}",
                    "T": f"{T:.8g}",
                    "tauAlphaEst": f"{tau_k:.6g}",
                    "T_old": "" if T_old is None else f"{T_old:.8g}",
                    "tauMeasUsed": "" if not math.isfinite(meas) else f"{meas:.8g}",
                    "ratio": "" if not math.isfinite(rat) else f"{rat:.6g}",
                    "reason": reason,
                    "source": src,
                    "fromBatch": src_run,
                }
            )

    OUTDIR.mkdir(parents=True, exist_ok=True)
    write_csv(
        OUTDIR / "anchors.csv",
        ["p0", "T", "waitingTime", "tauAlphaEst", "tauAlpha", "crossed", "batch"],
        [
            {
                "p0": f"{a['p0']:.3f}",
                "T": f"{a['T']:.8g}",
                "waitingTime": f"{a['waitingTime']:.8g}",
                "tauAlphaEst": "" if not math.isfinite(a["tauAlphaEst"]) else f"{a['tauAlphaEst']:.8g}",
                "tauAlpha": "" if not math.isfinite(a["tauAlpha"]) else f"{a['tauAlpha']:.8g}",
                "crossed": a["crossed"],
                "batch": a["batch"],
            }
            for a in anchors_all
        ],
    )
    write_csv(
        OUTDIR / "state_points.csv",
        [
            "p0",
            "T",
            "tauAlphaEst",
            "T_old",
            "tauMeasUsed",
            "ratio",
            "reason",
            "source",
            "fromBatch",
        ],
        points,
    )
    plot_grid(anchors_all, points, OUTDIR / "vertexModel_tauAlpha_batch5_tau_vs_T.png")
    print(f"n_jobs={len(points)}")
    if len(points) != 6:
        raise SystemExit(f"expected 6 batch-5 jobs, got {len(points)}")


if __name__ == "__main__":
    main()
