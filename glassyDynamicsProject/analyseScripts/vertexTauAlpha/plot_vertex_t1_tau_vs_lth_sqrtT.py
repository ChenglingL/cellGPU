#!/usr/bin/env python3
"""
Generated by Cursor. 2026-09-08.
tau_alpha vs l_T1 * T^{1/2} at p0=3.800, color by l_T1.

Physics:
  T1 fires when edge length < l_T1 (mean cell area 1). If thermal edge
  motion scales as T^{1/2}, the combination l_T1 T^{1/2} is a trial
  reduced threshold. tau_alpha is the longest-tw CRSISF 1/e at q=6.80.
  Color is l_T1 (viridis, log). t1Scan recommended T grid only.

Usage:
  python3 glassyDynamicsProject/analyseScripts/vertexTauAlpha/plot_vertex_t1_tau_vs_lth_sqrtT.py
"""

from __future__ import annotations

import math
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.colors import LogNorm

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from plot_vertex_t1_tau_vs_lth import CSV, N, P0, load_t1scan

OUT = HERE / "vertexModel_t1Scan" / "vertex_t1_tau_vs_lth_sqrtT.png"
MARKERS = ["o", "s", "D", "^", "v", "P", "X", "<", ">", "h", "p"]


def t1_label(t1: float) -> str:
    lg = math.log10(t1)
    e = int(round(lg))
    if abs(lg - e) < 1e-8:
        inner = rf"10^{{{e}}}"
    else:
        inner = f"{t1:g}"
    return rf"$\ell_{{T1}}={inner}$"


def main():
    rows = load_t1scan(CSV)
    if not rows:
        raise SystemExit(f"no t1Scan rows in {CSV}")
    by_t1 = defaultdict(list)
    for r in rows:
        x = r["t1"] * math.sqrt(r["T"])
        by_t1[r["t1"]].append({"x": x, "tauAlpha": r["tauAlpha"]})
    t1s = sorted(by_t1)
    cmap = plt.get_cmap("viridis")
    norm = LogNorm(vmin=min(t1s), vmax=max(t1s))

    fig, ax = plt.subplots(figsize=(7.2, 5.2))
    for i, t1 in enumerate(t1s):
        sub = sorted(by_t1[t1], key=lambda r: r["x"])
        ax.plot(
            [r["x"] for r in sub],
            [r["tauAlpha"] for r in sub],
            color=cmap(norm(t1)),
            marker=MARKERS[i % len(MARKERS)],
            markersize=5,
            lw=1.2,
            label=t1_label(t1),
        )
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel(r"$\ell_{T1}\,T^{1/2}$")
    ax.set_ylabel(r"$\tau_\alpha$ (CRSISF $1/e$)")
    ax.set_title(rf"$N={N}$, $p_0={P0:.3f}$")
    ax.legend(loc="best", frameon=False, fontsize=8)
    fig.tight_layout()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT, dpi=150)
    plt.close(fig)
    print(f"wrote {OUT} ({len(t1s)} l_T1, {len(rows)} points)")


if __name__ == "__main__":
    main()
