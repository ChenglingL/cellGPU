#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-11-02.
Replica means of the vertex-position CRSISF from vertex_position_fs_kscan.py, for the KWW fit
and the trend checks: label vs junction tracking, at q=6.7 and at the S(q) peak k_max.

Physics:
  k_max: argmax of the vertex S(q) on [5, 8] with a 3-point parabola, S(q) the mean over the
  last 10 records x idx (the C++ grid, as plot_vertex_position_sq.py / sq_first_peak.csv).
  F_s(k_max, t) is interpolated linearly in q between grid points (spacing pi/L = 0.049).
  Label: displacement of the array label (vertexPositionFs.cpp). Junction: of the label that
  holds the t0 cell triplet at t, which undoes the label swaps of a T1 and its reverse.
  Replica mean and sample std on a geomspace grid of dt > 0 (mean_std_curve, as
  combine_vertex_position_fs.py), Fs_std floored at 1e-4. Time origin: first record (t_w).
  swapped: fraction of t0 junctions held by another label at t; dead: t0 triplet gone.
  tau_1e: last downward 1/e crossing of the replica mean, log-linear interpolation.

Writes vertexModel_vertexPositionFsKScan/:
  kmax.csv
  Fs_combined_mean_{label,junction}_{q6.700,kmax}.csv   (columns of Fs_combined_mean.csv)
  junction_fractions.csv                                 (p0, T, t, swapped, dead, sems)
  tau_1e.csv

Usage:
  python3 combine_vertex_position_fs_kscan.py
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
import pandas as pd

from combine_vertex_production_fs import STD_FLOOR, mean_std_curve
from measure_and_plot_tau_alpha import INV_E
from plot_vertex_position_sq import q_peaks
from vertex_position_fs_kscan import out_dir as kscan_dir

HERE = Path(__file__).resolve().parent
OUTDIR = HERE / "vertexModel_vertexPositionFsKScan"
Q_FIXED = 6.7
TRACKING = {"label": "fs_cr", "junction": "fs_jn"}


def fs_at_q(fs: np.ndarray, q: np.ndarray, qv: float) -> np.ndarray:
    """F_s(..., q) at qv, linear in q; fs has q as its last axis."""
    j = int(np.clip(np.searchsorted(q, qv), 1, q.size - 1))
    w = (qv - q[j - 1]) / (q[j] - q[j - 1])
    return (1.0 - w) * fs[..., j - 1] + w * fs[..., j]


def tau_1e(t: np.ndarray, y: np.ndarray) -> float:
    m = (t > 0) & np.isfinite(y)
    t, y = t[m], y[m]
    i = np.flatnonzero((y[:-1] >= INV_E) & (y[1:] < INV_E))
    if not i.size:
        return math.nan
    i = int(i[-1])
    return float(np.exp(np.interp(INV_E, [y[i + 1], y[i]], [np.log(t[i + 1]), np.log(t[i])])))


def main() -> None:
    parser = argparse.ArgumentParser(description="Combine the vertex-position F_s q scan.")
    parser.add_argument("--std-floor", type=float, default=STD_FLOOR)
    args = parser.parse_args()
    OUTDIR.mkdir(parents=True, exist_ok=True)

    files = sorted(kscan_dir().glob("kscan_*.npz"))
    if not files:
        raise SystemExit(f"no kscan files in {kscan_dir()}")
    kmax_rows, frac_rows, tau_rows = [], [], []
    fs_rows: dict[tuple[str, str], list[dict]] = {
        (tr, qc): [] for tr in TRACKING for qc in ("q6.700", "kmax")
    }
    for path in files:
        z = np.load(path)
        p0, T = round(float(z["p0"]), 3), float(z["T"])
        q, t = z["q"], z["t"]
        n_idx = int(z["idx"].size)
        sq_q = z["sq_q"]
        kq, sk, _, _ = q_peaks(sq_q, z["sq_last_quad"].mean(axis=0))
        kh, skh, _, _ = q_peaks(sq_q, z["sq_last_half"].mean(axis=0))
        k_orig = [q_peaks(sq_q, z["sq_origin_quad"][:, io].mean(axis=0))[0]
                  for io in range(z["origin_frac"].size)]
        kmax_rows.append({
            "p0": p0, "T": T, "kind": str(z["kind"]), "waitingTime": float(z["waiting_time"]),
            "n_idx": n_idx, "k_max": kq, "S_kmax": sk, "k_max_half": kh, "S_kmax_half": skh,
            **{f"k_max_origin{io}": k for io, k in enumerate(k_orig)},
        })
        tau = {"p0": p0, "T": T, "kind": str(z["kind"]), "k_max": kq}
        for tr, name in TRACKING.items():
            fs0 = z[name][:, 0]  # (nrep, nrec, nq), first-record origin
            for qc, qv in (("q6.700", Q_FIXED), ("kmax", kq)):
                curves = [(t, fs_at_q(fs0[i], q, qv)) for i in range(n_idx)]
                tgrid, mean, std, n = mean_std_curve(curves)
                std = np.maximum(std, args.std_floor)
                sem = std / math.sqrt(n)
                tau[f"tau_1e_{tr}_{qc}"] = tau_1e(tgrid, mean)
                fs_rows[(tr, qc)].extend(
                    {"p0": p0, "T": T, "q": qv, "t": float(a), "Fs_mean": float(b),
                     "Fs_std": float(c), "Fs_sem": float(d), "n_idx": n}
                    for a, b, c, d in zip(tgrid, mean, std, sem)
                )
        sw = z["swapped_pair"][:, 0, :]  # (nrep, nrec) from the first record
        dd = z["dead_pair"][:, 0, :]
        for j in range(1, t.size):
            frac_rows.append({
                "p0": p0, "T": T, "t": float(t[j]),
                "swapped": float(sw[:, j].mean()), "swapped_sem": float(sw[:, j].std(ddof=1) / math.sqrt(n_idx)),
                "dead": float(dd[:, j].mean()), "dead_sem": float(dd[:, j].std(ddof=1) / math.sqrt(n_idx)),
            })
        tau_rows.append(tau)

    order = ["p0", "T"]
    pd.DataFrame(kmax_rows).sort_values(order).to_csv(OUTDIR / "kmax.csv", index=False)
    pd.DataFrame(frac_rows).sort_values(order + ["t"]).to_csv(
        OUTDIR / "junction_fractions.csv", index=False)
    pd.DataFrame(tau_rows).sort_values(order).to_csv(OUTDIR / "tau_1e.csv", index=False)
    for (tr, qc), rows in fs_rows.items():
        out = OUTDIR / f"Fs_combined_mean_{tr}_{qc}.csv"
        pd.DataFrame(rows).sort_values(order + ["t"]).to_csv(out, index=False)
        print(f"wrote {out} ({len(rows)} rows)")
    print(f"wrote kmax.csv, junction_fractions.csv, tau_1e.csv for {len(files)} states in {OUTDIR}")


if __name__ == "__main__":
    main()
