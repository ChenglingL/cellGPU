#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-10-21.
Rigid quench of vertex production snapshots: is p0* ~ 3.72?

Physics (A0=1, N=4096, periodic box L=64):
  Driver vertexProductionRigidQuench FIRE-minimizes the last frames of each
  production trajectory (idx 0..9) with the 2025 KA=0 recipe
  (localTest/vertexFIRE.cpp): E = sum_i (P_i - p0q)^2, T1s on (l_T1=0.01).
  A quench is rigid if the minimized E > 1e-10 (bidisperseRigidity.nb cut).
  Each snapshot is quenched at its production p0 ("own"), then p0q is
  bisected for the onset p0*(snapshot): rigid below, floppy above.
  With KA=0 no network is floppy below q_hex = sqrt(8 sqrt 3) ~ 3.7224:
  sum A_i = L^2 and A_i <= P^2 / (4 z_i tan(pi/z_i)), which is concave in
  z_i, so <z>=6 gives N <= N P^2 / q_hex^2. Only a perfect honeycomb sits on
  that bound; 5-7 defects push p0*(snapshot) up.
  A production state is on the fluid branch at T=0 if its own quench is
  floppy, i.e. p0*(snapshot) < p0.
  tau_kww is the round-2 production centroid CRSISF KWW time (q=6.7).

Output (vertexModel_rigidQuench/):
  rigid_quench_snapshots.csv   one row per snapshot (own result, p0* bracket)
  rigid_quench_states.csv      per-(p0,T) summary
  rigid_quench_p0star.png      p0*(snapshot) and own-p0 rigid fraction vs tau
  rigid_quench_fraction_vs_p0q.png  rigid fraction vs quench p0q, per p0
  rigid_quench_p0star_vs_p6.png     p0*(snapshot) vs hexagon fraction
  rigid_quench_p6_fit.csv      least squares p0* = a + b (1 - p6), free a

Usage:
  python3 plot_vertex_rigid_quench.py
  python3 plot_vertex_rigid_quench.py --ka 1    # KA=1 runs -> vertexModel_rigidQuench_KA1/
  CELLGPU_SCRATCH=... python3 plot_vertex_rigid_quench.py
Reads the per-(p0,T) CSVs under productionRuns/rigidQuench/; partial files
(jobs still running) are fine.
"""

from __future__ import annotations

import argparse
import csv
import math
import os
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import LinearSegmentedColormap, LogNorm

HERE = Path(__file__).resolve().parent
CSV_STATES = HERE / "vertexModel_tauAlpha_final" / "production_state_points.csv"
KWW_TAU = HERE / "vertexModel_productionFs" / "round2" / "kww_global_tau.csv"

P0_ORDER = (3.750, 3.775, 3.800, 3.815, 3.825, 3.850)
N = 4096
P0Q_LO = 3.70  # taken as rigid without a quench (below the honeycomb bound)
BRACKET_TOL = 0.002 + 1e-9  # driver bisects until hi - lo <= 0.002; wider = still running
Q_HEX = math.sqrt(8.0 * math.sqrt(3.0))  # ~3.7224
P0_RANDOM = 3.81  # usual random-quench onset

# p0: one-hue ordinal ramp, darkest = lowest p0 (same as the hexagonality figures;
# validate_palette.js --ordinal passes). Markers are the second channel.
P0_COLOR = dict(zip(P0_ORDER, ("#0a2a52", "#104281", "#1c5cab", "#2a78d6", "#5598e7", "#86b6ef")))
P0_MARKER = dict(zip(P0_ORDER, ("o", "s", "D", "^", "v", "P")))
# tau inside a p0 panel: orange ordinal ramp, darkest = longest tau.
TAU_CMAP = LinearSegmentedColormap.from_list("tau", ("#f6c6ad", "#eb6834", "#a8401a", "#5c230e"))
INK = "#0b0b0b"
INK2 = "#52514e"
MUTED = "#898781"

FS_TITLE = 15
FS_LABEL = 15
FS_TICK = 12
FS_LEGEND = 10
FS_NOTE = 11


def scratch_root() -> Path:
    env = os.environ.get("CELLGPU_SCRATCH")
    if env:
        return Path(env)
    return Path("/scratch/bbtm/cli6/glassyDynamics/data")


def quench_dir() -> Path:
    return scratch_root() / f"N{N}" / "vertex" / "productionRuns" / "rigidQuench"


def outdir_for(ka: float) -> Path:
    return HERE / ("vertexModel_rigidQuench" if ka == 0 else f"vertexModel_rigidQuench_KA{ka:g}")


def p0_key(p0: float) -> float:
    return min(P0_ORDER, key=lambda p: abs(p - p0))


def load_states() -> list[tuple[float, float]]:
    out: list[tuple[float, float]] = []
    with CSV_STATES.open() as f:
        lines = (ln for ln in f if ln.strip() and not ln.lstrip().startswith("#"))
        for r in csv.DictReader(lines):
            out.append((float(r["p0"]), float(r["T"])))
    return out


def load_tau() -> dict[tuple[float, float], float]:
    tau: dict[tuple[float, float], float] = {}
    if not KWW_TAU.is_file():
        return tau
    with KWW_TAU.open() as f:
        for r in csv.DictReader(f):
            try:
                tau[(p0_key(float(r["p0"])), round(float(r["T"]), 8))] = float(r["tau_kww"])
            except (KeyError, ValueError):
                continue
    return tau


def load_quenches(ka: float) -> list[dict]:
    rows: list[dict] = []
    for path in sorted(quench_dir().glob(f"rigidQuench_N{N}_p*_T*_KA{ka:.4f}_idx*_bisect.csv")):
        with path.open() as f:
            # scratch I/O errors can leave a zero-filled row; drop the NULs and
            # let the short row fail below like a row cut by a running job
            for r in csv.DictReader(ln.replace("\0", "") for ln in f):
                try:
                    rows.append(
                        {
                            "p0": p0_key(float(r["p0"])),
                            "T": round(float(r["T"]), 8),
                            "idx": int(r["idx"]),
                            "rec": int(r["rec"]),
                            "p0q": float(r["p0q"]),
                            "stage": r["stage"],
                            "E": float(r["E"]),
                            "E1e5": float(r["E1e5"]),
                            "iters": int(r["iters"]),
                            "status": r["status"],
                            "rigid": int(r["rigid"]),
                            "q0": float(r["q0"]),
                            "q": float(r["q"]),
                            "Pmean": float(r["Pmean"]),
                            "p6_0": float(r["p6_0"]),
                            "p6": float(r["p6"]),
                            "sec": float(r["sec"]),
                        }
                    )
                except (KeyError, ValueError, TypeError):
                    continue  # a row cut by a running job
    return rows


def reduce_snapshots(rows: list[dict]) -> list[dict]:
    """One record per snapshot: own-p0 result and the p0* bracket [a, b]."""
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for r in rows:
        groups[(r["p0"], r["T"], r["idx"], r["rec"])].append(r)
    snaps: list[dict] = []
    for (p0, T, idx, rec), g in groups.items():
        own = [r for r in g if r["stage"] == "own"]
        if not own:
            continue
        own = own[0]
        rig = [r["p0q"] for r in g if r["rigid"]]
        flo = [r["p0q"] for r in g if not r["rigid"]]
        a = max(rig) if rig else P0Q_LO
        b = min(flo) if flo else math.inf
        # rigid KA=0 minimum sits at the network's least mean perimeter, so the
        # last rigid quench's <P> should land inside [a, b]
        top = max((r for r in g if r["rigid"]), key=lambda r: r["p0q"], default=None)
        snaps.append(
            {
                "p0": p0,
                "T": T,
                "idx": idx,
                "rec": rec,
                "own_rigid": own["rigid"],
                "own_E": own["E"],
                "own_E1e5": own["E1e5"],
                "own_status": own["status"],
                "own_q": own["q"],
                "own_p6": own["p6"],
                "q0": own["q0"],
                "p6_0": own["p6_0"],
                "a": a,
                "b": b,
                "p0star": 0.5 * (a + b) if b - a <= BRACKET_TOL else math.nan,
                "Pmin_rigid": top["Pmean"] if top else math.nan,
                "open": int(not math.isfinite(b)),
                "complete": int(b - a <= BRACKET_TOL),
                "consistent": int(a < b),
                "n_quench": len(g),
                "n_maxit": sum(1 for r in g if r["status"] == "maxit"),
                "sec": sum(r["sec"] for r in g),
            }
        )
    snaps.sort(key=lambda s: (P0_ORDER.index(s["p0"]), -s["T"], s["idx"], s["rec"]))
    return snaps


def wilson(k: int, n: int, z: float = 1.0) -> tuple[float, float]:
    """Wilson interval (z=1, ~68%) for a binomial fraction."""
    if n == 0:
        return math.nan, math.nan
    p = k / n
    den = 1.0 + z * z / n
    mid = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return mid - half, mid + half


def summarize(snaps: list[dict], tau: dict) -> list[dict]:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for s in snaps:
        groups[(s["p0"], s["T"])].append(s)
    out: list[dict] = []
    for (p0, T), g in groups.items():
        n = len(g)
        k = sum(s["own_rigid"] for s in g)
        lo, hi = wilson(k, n)
        ps = np.array([s["p0star"] for s in g], dtype=float)
        ok = np.isfinite(ps)
        rigid_E = [s["own_E"] / N for s in g if s["own_rigid"]]
        out.append(
            {
                "p0": p0,
                "T": T,
                "tau_kww": tau.get((p0, T), math.nan),
                "n_snap": n,
                "n_own_rigid": k,
                "f_own_rigid": k / n,
                "f_own_rigid_lo": lo,
                "f_own_rigid_hi": hi,
                "n_own_rigid_1e5": sum(1 for s in g if s["own_E1e5"] > 1e-10),
                "n_p0star": int(ok.sum()),
                "n_open": sum(s["open"] for s in g),
                "n_incomplete": sum(1 - s["complete"] - s["open"] for s in g),
                "p0star_mean": float(np.mean(ps[ok])) if ok.any() else math.nan,
                "p0star_std": float(np.std(ps[ok], ddof=1)) if ok.sum() > 1 else math.nan,
                "p0star_min": float(np.min(ps[ok])) if ok.any() else math.nan,
                "p0star_max": float(np.max(ps[ok])) if ok.any() else math.nan,
                "p0star_median": float(np.median(ps[ok])) if ok.any() else math.nan,
                "own_Epc_rigid_mean": float(np.mean(rigid_E)) if rigid_E else math.nan,
                "p6_snapshot": float(np.mean([s["p6_0"] for s in g])),
                "q_snapshot": float(np.mean([s["q0"] for s in g])),
                "p6_inherent_own": float(np.mean([s["own_p6"] for s in g])),
                "q_inherent_own": float(np.mean([s["own_q"] for s in g])),
                "n_inconsistent": sum(1 - s["consistent"] for s in g),
                "n_maxit": sum(s["n_maxit"] for s in g),
                "cpu_h": sum(s["sec"] for s in g) / 3600.0,
            }
        )
    out.sort(key=lambda z: (P0_ORDER.index(z["p0"]), -z["T"]))
    return out


def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        return
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.8g}" if isinstance(v, float) else v) for k, v in r.items()})


def style_axis(ax) -> None:
    ax.tick_params(labelsize=FS_TICK, colors=INK2)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    for sp in ("left", "bottom"):
        ax.spines[sp].set_color(MUTED)
    ax.grid(True, color="#e6e5e1", lw=0.6, zorder=0)


def ref_lines(ax, x_text: float, with_random: bool = True) -> None:
    ax.axhline(Q_HEX, color=INK2, lw=1.2, ls="--", zorder=1)
    ax.text(x_text, Q_HEX, r"  $\sqrt{8\sqrt{3}}=3.722$", color=INK2, fontsize=FS_NOTE,
            va="bottom", ha="left", transform=ax.get_yaxis_transform())
    if with_random:
        ax.axhline(P0_RANDOM, color=MUTED, lw=1.0, ls=":", zorder=1)
        ax.text(x_text, P0_RANDOM, "  3.81", color=MUTED, fontsize=FS_NOTE,
                va="bottom", ha="left", transform=ax.get_yaxis_transform())


def plot_p0star(states: list[dict], path: Path, ka: float) -> None:
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13.0, 5.2))
    for p0 in P0_ORDER:
        st = [s for s in states if s["p0"] == p0 and math.isfinite(s["tau_kww"])]
        if not st:
            continue
        st.sort(key=lambda s: s["tau_kww"])
        x = np.array([s["tau_kww"] for s in st])
        y = np.array([s["p0star_mean"] for s in st])
        e = np.array([s["p0star_std"] for s in st])
        c = P0_COLOR[p0]
        ax1.errorbar(x, y, yerr=e, color=c, marker=P0_MARKER[p0], ms=7, lw=2, capsize=3,
                     mec="white", mew=1.0, label=rf"$p_0={p0:.3f}$", zorder=3)
        ax1.axhline(p0, xmin=0.97, xmax=1.0, color=c, lw=3, zorder=2)
        f = np.array([s["f_own_rigid"] for s in st])
        flo = np.array([s["f_own_rigid_lo"] for s in st])
        fhi = np.array([s["f_own_rigid_hi"] for s in st])
        # Wilson bounds can cross f by rounding at k=0 or k=n
        yerr = np.clip([f - flo, fhi - f], 0.0, None)
        ax2.errorbar(x, f, yerr=yerr, color=c, marker=P0_MARKER[p0], ms=7, lw=2,
                     capsize=3, mec="white", mew=1.0, label=rf"$p_0={p0:.3f}$", zorder=3)
    for ax in (ax1, ax2):
        ax.set_xscale("log")
        ax.set_xlabel(r"$\tau_\alpha$ of the parent state", fontsize=FS_LABEL, color=INK)
        style_axis(ax)
    ref_lines(ax1, 0.0)
    ax1.set_ylabel(r"onset $p_0^*$ of the quenched snapshot", fontsize=FS_LABEL, color=INK)
    ax1.set_title(rf"$K_A={ka:g}$ onset per snapshot (mean $\pm$ sd)", fontsize=FS_TITLE, color=INK)
    ax1.text(1.015, 0.5, r"right-edge ticks: own $p_0$", transform=ax1.transAxes, rotation=90,
             ha="left", va="center", fontsize=FS_NOTE, color=INK2)
    ax2.set_ylim(-0.04, 1.04)
    ax2.set_ylabel(r"rigid fraction, quench at own $p_0$", fontsize=FS_LABEL, color=INK)
    ax2.set_title(r"Own-$p_0$ quench ($E>10^{-10}$ is rigid)", fontsize=FS_TITLE, color=INK)
    ax2.legend(fontsize=FS_LEGEND, frameon=False, loc="best")
    fig.tight_layout()
    fig.savefig(path, dpi=180)
    plt.close(fig)


def plot_fraction_vs_p0q(snaps: list[dict], states: list[dict], path: Path, p0q_max: float) -> None:
    taus = [s["tau_kww"] for s in states if math.isfinite(s["tau_kww"])]
    if not taus:
        return
    norm = LogNorm(vmin=min(taus), vmax=max(taus))
    grid = np.linspace(P0Q_LO, p0q_max, 1001)
    ps_all = [s["p0star"] for s in snaps if math.isfinite(s["p0star"])]
    x_hi = max(3.90, min(p0q_max, max(ps_all) + 0.02)) if ps_all else p0q_max
    fig, axes = plt.subplots(2, 3, figsize=(14.0, 8.0), sharex=True, sharey=True)
    for ax, p0 in zip(axes.ravel(), P0_ORDER):
        st = sorted((s for s in states if s["p0"] == p0), key=lambda s: s["tau_kww"])
        for s in st:
            ps = np.array([z["p0star"] if math.isfinite(z["p0star"]) else np.inf
                           for z in snaps if z["p0"] == p0 and z["T"] == s["T"]])
            if ps.size == 0:
                continue
            frac = (ps[None, :] > grid[:, None]).mean(axis=1)
            col = TAU_CMAP(norm(s["tau_kww"])) if math.isfinite(s["tau_kww"]) else MUTED
            ax.plot(grid, frac, color=col, lw=1.8, zorder=3)
        ax.axvline(Q_HEX, color=INK2, lw=1.2, ls="--", zorder=1)
        ax.axvline(p0, color=P0_COLOR[p0], lw=2.0, zorder=2)
        ax.set_title(rf"$p_0={p0:.3f}$", fontsize=FS_TITLE, color=INK)
        ax.set_xlim(P0Q_LO, x_hi)
        style_axis(ax)
    for ax in axes[1]:
        ax.set_xlabel(r"quench $p_0$", fontsize=FS_LABEL, color=INK)
    for ax in axes[:, 0]:
        ax.set_ylabel("rigid fraction", fontsize=FS_LABEL, color=INK)
    sm = plt.cm.ScalarMappable(norm=norm, cmap=TAU_CMAP)
    cb = fig.colorbar(sm, ax=axes.ravel().tolist(), shrink=0.85, pad=0.02)
    cb.set_label(r"$\tau_\alpha$ of the parent state", fontsize=FS_LABEL, color=INK)
    cb.ax.tick_params(labelsize=FS_TICK, colors=INK2)
    fig.text(0.01, 0.005, r"dashed: $\sqrt{8\sqrt{3}}=3.722$;  solid: production $p_0$",
             fontsize=FS_NOTE, color=INK2)
    fig.savefig(path, dpi=180, bbox_inches="tight")
    plt.close(fig)


def fit_defect_line(snaps: list[dict]) -> dict:
    """Least squares p0* = a + b (1 - p6) over all snapshots, free intercept."""
    g = [s for s in snaps if math.isfinite(s["p0star"])]
    x = np.array([1.0 - s["p6_0"] for s in g])
    y = np.array([s["p0star"] for s in g])
    A = np.vstack([np.ones_like(x), x]).T
    coef = np.linalg.lstsq(A, y, rcond=None)[0]
    resid = y - A @ coef
    cov = float(resid @ resid) / (len(x) - 2) * np.linalg.inv(A.T @ A)
    return {"n": len(x), "a": float(coef[0]), "a_se": float(math.sqrt(cov[0, 0])),
            "b": float(coef[1]), "b_se": float(math.sqrt(cov[1, 1])),
            "rms": float(math.sqrt(np.mean(resid**2))), "q_hex": Q_HEX}


def plot_p0star_vs_p6(snaps: list[dict], path: Path, fit: dict) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 5.4))
    for p0 in P0_ORDER:
        g = [s for s in snaps if s["p0"] == p0 and math.isfinite(s["p0star"])]
        if not g:
            continue
        ax.scatter([s["p6_0"] for s in g], [s["p0star"] for s in g], s=22, color=P0_COLOR[p0],
                   marker=P0_MARKER[p0], edgecolors="white", linewidths=0.5,
                   label=rf"$p_0={p0:.3f}$", zorder=3)
    xs = np.linspace(min(s["p6_0"] for s in snaps), 1.0, 50)
    ax.plot(xs, fit["a"] + fit["b"] * (1.0 - xs), color=INK, lw=1.5, zorder=4)
    ax.text(0.03, 0.22, rf"fit $p_0^*=a+b\,(1-p_6)$" "\n" rf"$a={fit['a']:.4f}\pm{fit['a_se']:.4f}$, "
            rf"$b={fit['b']:.3f}$", transform=ax.transAxes, fontsize=FS_NOTE, color=INK, va="top")
    ref_lines(ax, 0.0)
    ax.set_xlabel(r"hexagon fraction $p_6$ of the snapshot", fontsize=FS_LABEL, color=INK)
    ax.set_ylabel(r"onset $p_0^*$ of the snapshot", fontsize=FS_LABEL, color=INK)
    ax.set_xlim(right=1.0)
    style_axis(ax)
    ax.legend(fontsize=FS_LEGEND, frameon=False, loc="upper right", bbox_to_anchor=(1.0, 0.92))
    fig.tight_layout()
    fig.savefig(path, dpi=180)
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ka", type=float, default=0.0, help="KA of the quench runs to read (default 0)")
    ka = ap.parse_args().ka
    outdir = outdir_for(ka)
    outdir.mkdir(parents=True, exist_ok=True)
    rows = load_quenches(ka)
    print(f"KA = {ka:g}: quench rows = {len(rows)} from {quench_dir()}")
    snaps = reduce_snapshots(rows)
    tau = load_tau()
    states = summarize(snaps, tau)
    n_states = len(load_states())
    print(f"snapshots = {len(snaps)}  states with data = {len(states)}/{n_states}")
    write_csv(outdir / "rigid_quench_snapshots.csv", snaps)
    write_csv(outdir / "rigid_quench_states.csv", states)
    for s in states:
        print(f"p0={s['p0']:.3f} T={s['T']:.6g} tau={s['tau_kww']:.4g} n={s['n_snap']} "
              f"rigid@own={s['n_own_rigid']}/{s['n_snap']} p0*={s['p0star_mean']:.4f}"
              f"+-{s['p0star_std']:.4f} [{s['p0star_min']:.4f},{s['p0star_max']:.4f}] "
              f"p6={s['p6_snapshot']:.3f} maxit={s['n_maxit']}")
    if not states:
        return
    plot_p0star(states, outdir / "rigid_quench_p0star.png", ka)
    plot_fraction_vs_p0q(snaps, states, outdir / "rigid_quench_fraction_vs_p0q.png",
                         max(r["p0q"] for r in rows))
    fit = fit_defect_line(snaps)
    write_csv(outdir / "rigid_quench_p6_fit.csv", [fit])
    print(f"p0* = a + b(1-p6): a = {fit['a']:.5f} +- {fit['a_se']:.5f} (q_hex = {Q_HEX:.5f}), "
          f"b = {fit['b']:.4f} +- {fit['b_se']:.4f}, rms = {fit['rms']:.4f}, n = {fit['n']}")
    plot_p0star_vs_p6(snaps, outdir / "rigid_quench_p0star_vs_p6.png", fit)


if __name__ == "__main__":
    main()
