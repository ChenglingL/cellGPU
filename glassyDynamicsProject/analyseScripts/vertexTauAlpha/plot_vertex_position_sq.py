#!/usr/bin/env python3
"""
Generated by Cursor. 2026-09-21.
Plot mean S(q) of vertex production vertex positions, one panel per p0.

Physics:
  S(q) is the isotropic annular average of |sum_n exp(i K · r_n)|^2 / N_v
  with r_n = vertex coordinates, N_v = 2 N_cells, K on the first-quadrant
  2 pi / L lattice (same as structuralFeatures::computeStructureFactor).
  Each (p0, T) is the mean over the last 10 log-spaced frames of idx=0..9.
  First-peak q is the argmax of S on q in [5, 8] (the principal peak; a weak
  shoulder near q~4 is not the first peak) with 3-point parabola.
  q_argmax is the global argmax on q in [3, 16]. The CRSISF q is taken from
  the coldest T at each p0, where that peak is sharpest.

Color: coolwarm, independent LogNorm per p0 (coldest T blue, hottest red).
No colorbars.

Usage:
  python3 plot_vertex_position_sq.py
  CELLGPU_SCRATCH=... python3 plot_vertex_position_sq.py
"""

from __future__ import annotations

import csv
import math
import os
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import LogNorm

HERE = Path(__file__).resolve().parent
OUTDIR = HERE / "vertexModel_vertexPositionSq"
CSV_STATES = HERE / "vertexModel_tauAlpha_final" / "production_state_points.csv"
P0_ORDER = (3.750, 3.775, 3.800, 3.815, 3.825, 3.850)
N = 4096
Q_PEAK_LO = 5.0
Q_PEAK_HI = 8.0
Q_ARGMAX_LO = 3.0
Q_ARGMAX_HI = 16.0
Q_PLOT_LO = 1.0
Q_PLOT_HI = 18.0

FS_TITLE = 17
FS_LABEL = 16
FS_TICK = 14


def scratch_root() -> Path:
    env = os.environ.get("CELLGPU_SCRATCH")
    if env:
        return Path(env)
    return Path("/scratch/bbtm/cli6/glassyDynamics/data")


def sq_path(p0: float, T: float) -> Path:
    return (
        scratch_root()
        / f"N{N}"
        / "vertex"
        / "productionRuns"
        / "vertexPositionSq"
        / f"sqVertex_N{N}_p{p0:.4f}_T{T:.8f}.nc"
    )


def read_two_values(path: Path):
    try:
        from netCDF4 import Dataset

        with Dataset(path, "r") as ds:
            q = np.array(ds.variables["firstValue"][:], dtype=float)
            s = np.array(ds.variables["secondValue"][:], dtype=float)
        return q, s
    except Exception:
        pass
    from scipy.io import netcdf_file

    with netcdf_file(path, "r", mmap=False) as ds:
        q = np.array(ds.variables["firstValue"].data, dtype=float)
        s = np.array(ds.variables["secondValue"].data, dtype=float)
    return q, s


def load_state_points() -> list[tuple[float, float]]:
    rows: list[tuple[float, float]] = []
    with CSV_STATES.open() as f:
        lines = (ln for ln in f if ln.strip() and not ln.lstrip().startswith("#"))
        for r in csv.DictReader(lines):
            p0 = float(r["p0"])
            T = float(r["T"])
            if math.isfinite(p0) and math.isfinite(T) and T > 0:
                rows.append((p0, T))
    return rows


def match_p0(p0: float) -> float | None:
    m = min(P0_ORDER, key=lambda p: abs(p - p0))
    if abs(m - p0) > 1e-4:
        return None
    return m


def _parabola(qi: np.ndarray, si: np.ndarray, i: int) -> tuple[float, float]:
    smax = float(si[i])
    if i <= 0 or i >= si.size - 1:
        return float(qi[i]), smax
    y0, y1, y2 = float(si[i - 1]), float(si[i]), float(si[i + 1])
    denom = y0 - 2.0 * y1 + y2
    if abs(denom) < 1e-18:
        return float(qi[i]), smax
    delta = 0.5 * (y0 - y2) / denom
    if abs(delta) > 1.0:
        return float(qi[i]), smax
    dq = float(qi[i] - qi[i - 1])
    qhat = float(qi[i]) + delta * dq
    shat = y1 - 0.25 * (y0 - y2) * delta
    return qhat, float(shat)


def q_peaks(q: np.ndarray, s: np.ndarray) -> tuple[float, float, float, float]:
    """Principal-peak argmax on [5, 8] and global argmax on [3, 16]."""
    mask = (q >= Q_PEAK_LO) & (q <= Q_PEAK_HI) & np.isfinite(s)
    if not np.any(mask):
        q_first, s_first = math.nan, math.nan
    else:
        qi = q[mask]
        si = s[mask]
        q_first, s_first = _parabola(qi, si, int(np.argmax(si)))
    mask_g = (q >= Q_ARGMAX_LO) & (q <= Q_ARGMAX_HI) & np.isfinite(s)
    if not np.any(mask_g):
        return q_first, s_first, math.nan, math.nan
    qg = q[mask_g]
    sg = s[mask_g]
    q_arg, s_arg = _parabola(qg, sg, int(np.argmax(sg)))
    return q_first, s_first, q_arg, s_arg


def _combined_axes(fig_w: float = 13.6, fig_h: float = 8.0):
    fig = plt.figure(figsize=(fig_w, fig_h))
    gs = fig.add_gridspec(
        2,
        3,
        left=0.07,
        right=0.98,
        top=0.95,
        bottom=0.09,
        wspace=0.26,
        hspace=0.24,
    )
    axes = []
    for i, p0 in enumerate(P0_ORDER):
        row, col = divmod(i, 3)
        ax = fig.add_subplot(gs[row, col])
        ax.set_title(rf"$p_0={p0:.3f}$", fontsize=FS_TITLE, pad=4)
        ax.tick_params(labelsize=FS_TICK)
        axes.append(ax)
    return fig, axes


def main() -> None:
    OUTDIR.mkdir(parents=True, exist_ok=True)
    by_p0: dict[float, list[tuple[float, np.ndarray, np.ndarray]]] = {p: [] for p in P0_ORDER}
    peaks: list[tuple[float, float, float, float, float, float]] = []
    missing: list[tuple[float, float]] = []

    for p0_raw, T in load_state_points():
        p0 = match_p0(p0_raw)
        if p0 is None:
            continue
        path = sq_path(p0, T)
        if not path.is_file():
            missing.append((p0, T))
            continue
        q, s = read_two_values(path)
        by_p0[p0].append((T, q, s))
        qf, sf, qa, sa = q_peaks(q, s)
        peaks.append((p0, T, qf, sf, qa, sa))

    if missing:
        print(f"missing {len(missing)} S(q) files:")
        for p0, T in missing:
            print(f"  p0={p0:.3f} T={T:.8f} -> {sq_path(p0, T)}")

    cmap = plt.get_cmap("coolwarm")
    fig, axes = _combined_axes()
    for i, p0 in enumerate(P0_ORDER):
        ax = axes[i]
        curves = sorted(by_p0[p0], key=lambda z: z[0])
        if not curves:
            ax.text(0.5, 0.5, "no data", ha="center", va="center", transform=ax.transAxes)
            continue
        Ts = [z[0] for z in curves]
        tmin, tmax = min(Ts), max(Ts)
        if tmin <= 0 or tmin == tmax:
            norm = None
        else:
            norm = LogNorm(vmin=tmin, vmax=tmax)
        for T, q, s in curves:
            if norm is None:
                color = cmap(0.5)
            else:
                color = cmap(norm(T))
            m = (q >= Q_PLOT_LO) & (q <= Q_PLOT_HI)
            ax.plot(q[m], s[m], color=color, lw=1.3)
        ax.set_xlim(Q_PLOT_LO, Q_PLOT_HI)
        ax.set_ylim(bottom=0)
        row, col = divmod(i, 3)
        if row == 1:
            ax.set_xlabel(r"$q$", fontsize=FS_LABEL)
        if col == 0:
            ax.set_ylabel(r"$S(q)$", fontsize=FS_LABEL)

    png = OUTDIR / "sq_vs_q_all_p0.png"
    fig.savefig(png, dpi=150)
    plt.close(fig)
    print(f"wrote {png}")

    peak_csv = OUTDIR / "sq_first_peak.csv"
    with peak_csv.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["p0", "T", "q_peak", "S_peak", "q_argmax", "S_argmax"])
        for row in peaks:
            w.writerow(
                [
                    f"{row[0]:.3f}",
                    f"{row[1]:.8g}",
                    f"{row[2]:.6f}",
                    f"{row[3]:.6f}",
                    f"{row[4]:.6f}",
                    f"{row[5]:.6f}",
                ]
            )
    print(f"wrote {peak_csv}")

    print()
    print("| p0 | T | q_peak | S_peak | q_argmax | S_argmax |")
    print("| --- | --- | --- | --- | --- | --- |")
    for p0, T, qp, sp, qa, sa in peaks:
        print(f"| {p0:.3f} | {T:.8g} | {qp:.4f} | {sp:.4f} | {qa:.4f} | {sa:.4f} |")
    if peaks:
        qps = [r[2] for r in peaks if math.isfinite(r[2])]
        if qps:
            qps_sorted = sorted(qps)
            mid = qps_sorted[len(qps_sorted) // 2]
            print(
                f"n_peak={len(qps)} median q_peak={mid:.4f} "
                f"min={min(qps):.4f} max={max(qps):.4f}"
            )
        by_p0_peak: dict[float, list[tuple[float, float]]] = {p: [] for p in P0_ORDER}
        for p0, T, qp, _sp, _qa, _sa in peaks:
            if math.isfinite(qp):
                by_p0_peak[p0].append((T, qp))
        cold = []
        print("coldest T per p0:")
        for p0 in P0_ORDER:
            if not by_p0_peak[p0]:
                continue
            T, qp = min(by_p0_peak[p0], key=lambda z: z[0])
            cold.append(qp)
            print(f"  p0={p0:.3f} T={T:.6g} q_peak={qp:.4f}")
        if cold:
            cold_sorted = sorted(cold)
            print(
                f"low-T q_peak n={len(cold)} median={cold_sorted[len(cold)//2]:.4f} "
                f"min={cold_sorted[0]:.4f} max={cold_sorted[-1]:.4f}"
            )
    if missing:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
