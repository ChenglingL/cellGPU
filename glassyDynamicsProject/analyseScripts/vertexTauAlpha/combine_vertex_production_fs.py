#!/usr/bin/env python3
"""
Generated by Cursor. 2026-09-14.
Replica mean and std of production CRSISF F_s^CR(q, dt) at q=6.7.

Physics:
  F_s^CR(q, dt) = (1/N) sum_j J_0(q |dr_j^CR|), tracer = cell centroid.
  Per (p0, T), interpolate idx=0..9 onto a common geomspace dt grid, then
  take the arithmetic mean and sample standard deviation (ddof=1).
  SEM = std / sqrt(n_idx). Units: dt in simulation time, Fs dimensionless.

Writes vertexModel_productionFs/Fs_combined_mean.csv for the KWW HMC fit.

Usage:
  python3 combine_vertex_production_fs.py
  CELLGPU_SCRATCH=... python3 combine_vertex_production_fs.py
"""

from __future__ import annotations

import argparse
import math
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

from measure_and_plot_tau_alpha import FS_NAME, read_two_values
from plot_vertex_production_fs import (
    OUTDIR,
    Q,
    load_state_points,
    match_p0,
    scratch_fs,
)

# Floor so NUTS never sees sigma=0 at the first lags.
STD_FLOOR = 1e-4


def mean_std_curve(
    curves: list[tuple[np.ndarray, np.ndarray]],
) -> tuple[np.ndarray, np.ndarray, np.ndarray, int]:
    """Mean and sample std of Fs on a common positive-dt geomspace grid."""
    grids = []
    for dt, fs in curves:
        m = dt > 0
        if np.count_nonzero(m) < 2:
            continue
        grids.append((dt[m], fs[m]))
    n_idx = len(grids)
    if n_idx == 0:
        empty = np.array([])
        return empty, empty, empty, 0
    tmin = max(g[0][0] for g in grids)
    tmax = min(g[0][-1] for g in grids)
    if not (tmax > tmin > 0):
        dt0, fs0 = grids[0]
        std0 = np.zeros_like(fs0) if n_idx == 1 else np.full_like(fs0, np.nan)
        return dt0, fs0, std0, n_idx
    n = min(len(g[0]) for g in grids)
    n = max(n, 32)
    tgrid = np.geomspace(tmin, tmax, n)
    stacked = np.vstack([np.interp(tgrid, dt, fs) for dt, fs in grids])
    mean = stacked.mean(axis=0)
    if n_idx == 1:
        std = np.zeros_like(mean)
    else:
        std = stacked.std(axis=0, ddof=1)
    return tgrid, mean, std, n_idx


def load_by_key(root: Path) -> dict[tuple[float, float], list[tuple[np.ndarray, np.ndarray]]]:
    by_key: dict[tuple[float, float], list[tuple[np.ndarray, np.ndarray]]] = defaultdict(list)
    nfile = 0
    if not root.is_dir():
        return by_key
    for nc in sorted(root.glob("p*/timeCRSISF_*.nc")):
        m = FS_NAME.search(nc.name)
        if not m:
            continue
        if abs(float(m.group("k")) - Q) > 0.02:
            continue
        p0 = match_p0(float(m.group("p0")))
        if p0 is None:
            continue
        T = float(m.group("T"))
        dt, fs = read_two_values(nc)
        by_key[(p0, T)].append((dt, fs))
        nfile += 1
    print(f"loaded {nfile} CRSISF files from {root}")
    return by_key


def curves_for_state(
    by_key: dict[tuple[float, float], list[tuple[np.ndarray, np.ndarray]]],
    p0: float,
    T: float,
) -> list[tuple[np.ndarray, np.ndarray]]:
    curves = by_key.get((p0, T), [])
    if curves:
        return curves
    cand = [k for k in by_key if k[0] == p0 and abs(k[1] - T) / max(T, 1e-30) < 1e-5]
    if cand:
        return by_key[cand[0]]
    return []


def main() -> None:
    parser = argparse.ArgumentParser(description="Combine production CRSISF replicas.")
    parser.add_argument(
        "--std-floor",
        type=float,
        default=STD_FLOOR,
        help="minimum Fs_std written to CSV (default 1e-4)",
    )
    args = parser.parse_args()

    OUTDIR.mkdir(parents=True, exist_ok=True)
    by_key = load_by_key(scratch_fs())
    expected = load_state_points()
    rows: list[dict] = []
    missing: list[tuple[float, float]] = []

    for p0_raw, T in expected:
        p0 = match_p0(p0_raw)
        if p0 is None:
            continue
        curves = curves_for_state(by_key, p0, T)
        if not curves:
            missing.append((p0, T))
            continue
        tgrid, mean, std, n_idx = mean_std_curve(curves)
        if tgrid.size == 0:
            missing.append((p0, T))
            continue
        std = np.maximum(std, args.std_floor)
        sem = std / math.sqrt(n_idx)
        for t, y, s, e in zip(tgrid, mean, std, sem):
            rows.append(
                {
                    "p0": p0,
                    "T": T,
                    "t": float(t),
                    "Fs_mean": float(y),
                    "Fs_std": float(s),
                    "Fs_sem": float(e),
                    "n_idx": n_idx,
                }
            )

    df = pd.DataFrame(rows)
    out = OUTDIR / "Fs_combined_mean.csv"
    df.to_csv(out, index=False)
    n_state = df.groupby(["p0", "T"]).ngroups if not df.empty else 0
    print(f"wrote {out} ({len(df)} rows, {n_state} state points)")
    if missing:
        print(f"missing {len(missing)} (p0, T):")
        for p0, T in missing:
            print(f"  p0={p0:.3f} T={T:.8f}")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
