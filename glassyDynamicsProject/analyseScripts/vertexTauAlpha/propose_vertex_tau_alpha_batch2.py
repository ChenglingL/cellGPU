#!/usr/bin/env python3
"""
Generated by Cursor. 2026-08-24.
Second-batch vertex tau_alpha T grid from first-batch CRSISF 1/e crossings.

Physics:
  tau_alpha is the first lag where cage-relative SISF crosses 1/e (same as
  measure_and_plot_tau_alpha.py). At (p0, T) where the longest waiting-time
  trajectory still crosses 1/e,
      tau_vertex ≈ C(p0) * tau_Voronoi
  with C the geometric mean of that ratio. Estimate elsewhere:
      tau_est(T) = C(p0) * tau_Voronoi(T)
  with log tau_Voronoi interpolated vs 1/T. Invert T so each p0 has
      tau_k = 10**(1 + k/3), k = 0..9
  (10 to 10^4, three T per decade of tau_alpha).

Usage:
  python3 propose_vertex_tau_alpha_batch2.py
"""

from __future__ import annotations

import csv
import math
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
CURVE_CSV = HERE / "vertexModel_tauAlpha_test" / "vertexModel_tauAlpha_test_per_curve.csv"
VORONOI_CSV = (
    HERE.parent / "TauAlphaTable" / "data_2DVoronoi" / "tauAlpha_2DVoronoi_all.csv"
)
OUTDIR = HERE / "vertexModel_tauAlpha_batch2"

P0_ORDER = (3.750, 3.775, 3.800, 3.815, 3.825, 3.850)
TAU_TARGETS = [10.0 ** (1.0 + k / 3.0) for k in range(10)]


def load_curves(path: Path):
    rows = []
    with path.open() as f:
        for r in csv.DictReader(f):
            tau_s = r["tauAlpha"].strip()
            tau = float(tau_s) if tau_s else math.nan
            rows.append(
                {
                    "p0": float(r["p0"]),
                    "T": float(r["T"]),
                    "waitingTime": float(r["waitingTime"]),
                    "tauAlphaEst": float(r["tauAlphaEst"]) if r["tauAlphaEst"] else math.nan,
                    "tauAlpha": tau,
                    "crossed": int(r["crossed"]),
                }
            )
    return rows


def load_voronoi(path: Path):
    by_p0 = defaultdict(list)
    with path.open() as f:
        for r in csv.DictReader(f):
            p0 = float(r["p0"])
            T = float(r["T"])
            tau = float(r["tauAlpha"])
            by_p0[p0].append((T, tau))
    for p0 in by_p0:
        by_p0[p0].sort(key=lambda x: -x[0])  # hot to cold
    return by_p0


def match_p0(p0, keys, tol=1e-4):
    for k in keys:
        if abs(k - p0) < tol:
            return k
    return None


def voronoi_tau_at_T(table, T, rel_tol=1e-4):
    """Exact table match if T is a tabulated point, else interpolate."""
    for Tv, tau in table:
        if abs(Tv - T) / max(T, Tv, 1e-30) < rel_tol:
            return tau
    return tau_voro_of_T(table, T)


def invT_logtau(table):
    x = np.array([1.0 / T for T, _ in table], dtype=float)
    y = np.array([math.log(tau) for _, tau in table], dtype=float)
    order = np.argsort(x)
    return x[order], y[order]


def logtau_voro_of_invT(table, inv_T):
    x, y = invT_logtau(table)
    if inv_T <= x[0]:
        slope = (y[1] - y[0]) / (x[1] - x[0])
        return y[0] + slope * (inv_T - x[0])
    if inv_T >= x[-1]:
        slope = (y[-1] - y[-2]) / (x[-1] - x[-2])
        return y[-1] + slope * (inv_T - x[-1])
    return float(np.interp(inv_T, x, y))


def tau_voro_of_T(table, T):
    return math.exp(logtau_voro_of_invT(table, 1.0 / T))


def invert_T_loglog_hot(table, tau_voro_target):
    """High-T fallback: log tau vs log T on the two hottest Voronoi points."""
    T0, tau0 = table[0]  # hot to cold
    T1, tau1 = table[1]
    lx0, ly0 = math.log(T0), math.log(tau0)
    lx1, ly1 = math.log(T1), math.log(tau1)
    slope = (ly1 - ly0) / (lx1 - lx0)
    if slope == 0:
        raise ValueError("flat Voronoi tau (log T)")
    lx = lx0 + (math.log(tau_voro_target) - ly0) / slope
    return math.exp(lx)


def invert_T_for_tau_voro(table, tau_voro_target):
    """T such that tau_Voronoi(T) = tau_voro_target.

    Interior: piecewise linear log tau vs 1/T. Cold of the table: same
    slope as the two coldest points. Hot of the table: log tau vs log T
    on the two hottest points (Arrhenius 1/T has a T→∞ floor and mixed
    schemes are non-monotonic).
    """
    x, y = invT_logtau(table)
    yt = math.log(tau_voro_target)
    if yt <= y[0]:
        # Arrhenius 1/T from the two hottest points often hits a T→∞ floor
        # above tau~10 and is not monotonic vs log-T. Use log tau vs log T.
        return invert_T_loglog_hot(table, tau_voro_target), "logT"
    elif yt >= y[-1]:
        slope = (y[-1] - y[-2]) / (x[-1] - x[-2])
        if slope == 0:
            raise ValueError("flat Voronoi tau")
        inv_T = x[-1] + (yt - y[-1]) / slope
        if inv_T <= 0:
            raise ValueError(f"non-positive 1/T for tau_voro={tau_voro_target}")
    else:
        inv_T = float(np.interp(yt, y, x))
    return 1.0 / inv_T, "1/T"


def longest_tw_anchors(rows, voronoi):
    groups = defaultdict(list)
    for r in rows:
        groups[(r["p0"], r["T"])].append(r)
    anchors = []
    for (p0, T), grp in sorted(groups.items()):
        best = max(grp, key=lambda z: z["waitingTime"])
        if best["crossed"] != 1 or not math.isfinite(best["tauAlpha"]):
            continue
        pk = match_p0(p0, voronoi.keys())
        tau_v = voronoi_tau_at_T(voronoi[pk], T) if pk is not None else math.nan
        C = best["tauAlpha"] / tau_v if tau_v > 0 else math.nan
        anchors.append(
            {
                "p0": p0,
                "T": T,
                "waitingTime": best["waitingTime"],
                "tauAlphaVertex": best["tauAlpha"],
                "tauAlphaVoronoi": tau_v,
                "C": C,
            }
        )
    return anchors


def C_by_p0(anchors):
    buckets = defaultdict(list)
    for a in anchors:
        if a["C"] > 0 and math.isfinite(a["C"]):
            buckets[a["p0"]].append(a["C"])
    out = {}
    for p0, cs in buckets.items():
        out[p0] = math.exp(sum(math.log(c) for c in cs) / len(cs))
    return out


def write_csv(path: Path, fieldnames, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in rows:
            w.writerow(r)
    print(f"wrote {path} ({len(rows)} rows)")


def plot_grid(voronoi, Cmap, anchors, points, outpath: Path):
    fig, axes = plt.subplots(2, 3, figsize=(11.0, 7.2), sharex=False, sharey=True)
    axlist = axes.ravel()
    for i, p0 in enumerate(P0_ORDER):
        ax = axlist[i]
        pk = match_p0(p0, voronoi.keys())
        table = voronoi[pk]
        C = Cmap[match_p0(p0, Cmap.keys())]
        pp = [p for p in points if abs(p["p0"] - p0) < 1e-4]
        Tmin = min(T for T, _ in table)
        Tmax = max(T for T, _ in table)
        if pp:
            Tmin = min(Tmin, min(p["T"] for p in pp))
            Tmax = max(Tmax, max(p["T"] for p in pp))
        Ts = np.geomspace(Tmin * 0.7, Tmax * 1.4, 80)
        tau_v = np.array([tau_voro_of_T(table, T) for T in Ts])
        ax.plot(Ts, tau_v, "k--", lw=1.0, label=r"Voronoi $\tau_\alpha$")
        ax.plot(Ts, C * tau_v, "C0-", lw=1.2, label=rf"$C\times$Voronoi ($C={C:.2f}$)")
        aa = [a for a in anchors if abs(a["p0"] - p0) < 1e-4]
        if aa:
            ax.scatter(
                [a["T"] for a in aa],
                [a["tauAlphaVertex"] for a in aa],
                c="C3",
                s=36,
                zorder=4,
                label="longest $t_w$ $1/e$",
            )
        ax.scatter(
            [p["T"] for p in pp],
            [p["tauAlphaEst"] for p in pp],
            facecolors="none",
            edgecolors="C2",
            s=42,
            zorder=5,
            label="batch-2 targets",
        )
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_title(rf"$p_0={p0:.3f}$")
        ax.set_xlabel(r"$T$")
        ax.set_ylabel(r"$\tau_\alpha$")
        ax.legend(loc="best", fontsize=7, frameon=False)
    fig.suptitle(r"vertex batch 2: $\tau_\alpha^{\mathrm{est}}=C\,\tau_\alpha^{\mathrm{Voronoi}}$", y=1.01)
    fig.tight_layout()
    fig.savefig(outpath, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {outpath}")


def main():
    rows = load_curves(CURVE_CSV)
    voronoi = load_voronoi(VORONOI_CSV)
    anchors = longest_tw_anchors(rows, voronoi)
    Cmap = C_by_p0(anchors)

    print("longest t_w 1/e anchors:")
    for a in anchors:
        print(
            f"  p0={a['p0']:.3f} T={a['T']:g} tw={a['waitingTime']:g} "
            f"tau_v={a['tauAlphaVertex']:.4g} tau_Voro={a['tauAlphaVoronoi']:.4g} "
            f"C={a['C']:.3g}"
        )
    print("C(p0) geometric mean:")
    for p0 in P0_ORDER:
        pk = match_p0(p0, Cmap.keys())
        print(f"  p0={p0:.3f}  C={Cmap[pk]:.4f}")

    points = []
    for p0 in P0_ORDER:
        pk = match_p0(p0, voronoi.keys())
        ck = match_p0(p0, Cmap.keys())
        C = Cmap[ck]
        table = voronoi[pk]
        for tau_k in TAU_TARGETS:
            tau_voro_needed = tau_k / C
            T, how = invert_T_for_tau_voro(table, tau_voro_needed)
            src = "C*voronoi_logT_hot" if how == "logT" else "C*voronoi_inverted"
            points.append(
                {
                    "p0": f"{p0:.3f}",
                    "T": f"{T:.8g}",
                    "tauAlphaEst": f"{tau_k:.6g}",
                    "C": f"{C:.6g}",
                    "tauVoronoiNeeded": f"{tau_voro_needed:.6g}",
                    "source": src,
                }
            )

    OUTDIR.mkdir(parents=True, exist_ok=True)
    write_csv(
        OUTDIR / "anchors.csv",
        ["p0", "T", "waitingTime", "tauAlphaVertex", "tauAlphaVoronoi", "C"],
        [
            {
                "p0": f"{a['p0']:.3f}",
                "T": f"{a['T']:.8g}",
                "waitingTime": f"{a['waitingTime']:.8g}",
                "tauAlphaVertex": f"{a['tauAlphaVertex']:.8g}",
                "tauAlphaVoronoi": f"{a['tauAlphaVoronoi']:.8g}",
                "C": f"{a['C']:.8g}",
            }
            for a in anchors
        ],
    )
    write_csv(
        OUTDIR / "C_by_p0.csv",
        ["p0", "C", "nAnchors"],
        [
            {
                "p0": f"{p0:.3f}",
                "C": f"{Cmap[match_p0(p0, Cmap.keys())]:.8g}",
                "nAnchors": sum(1 for a in anchors if abs(a["p0"] - p0) < 1e-4),
            }
            for p0 in P0_ORDER
        ],
    )
    write_csv(
        OUTDIR / "state_points.csv",
        ["p0", "T", "tauAlphaEst", "C", "tauVoronoiNeeded", "source"],
        points,
    )
    plot_grid(
        voronoi,
        Cmap,
        anchors,
        [
            {
                "p0": float(p["p0"]),
                "T": float(p["T"]),
                "tauAlphaEst": float(p["tauAlphaEst"]),
            }
            for p in points
        ],
        OUTDIR / "vertexModel_tauAlpha_batch2_tau_vs_T.png",
    )


if __name__ == "__main__":
    main()
