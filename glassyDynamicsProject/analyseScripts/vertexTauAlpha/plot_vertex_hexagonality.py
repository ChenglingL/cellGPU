"""
Generated by Claude Code. 2026-09-30.
How hexagonal the vertex-model cells are, and why the centroid S(q) hides it.

Physics (mean cell area A0=1, KA=KP=1, N=4096, periodic box L=64):
  Cells are rebuilt from the production trajectories (pos, Vneighs,
  VertexCellNeighbors), last record of each idx=0..9. z_i is the number of
  sides. Euler on the torus with 3-valent vertices gives <z>=6 exactly in
  every frame, so hexagonality is the spread of z:
    p6 = fraction of 6-sided cells,  mu2 = <(z-6)^2>.
  Bond order of cell j over its edge-sharing neighbours k (centroid bonds):
    psi6_j = (1/z_j) sum_k exp(6 i theta_jk),  box-wide |Psi6| = |<psi6_j>|.
  Shape of the hexagons: q = P/sqrt(A) against the regular hexagon
  q_hex = sqrt(8 sqrt 3) ~ 3.722, and interior angles against 120 deg.
  S(q) is the stored production centroid S(q) (first-quadrant annulus
  average, last 10 frames x idx 0..9; vertexProductionSq). The 2D map is
  S(k) = |sum_n exp(i k.r_n)|^2 / N on the full 2 pi/L grid of one frame.
  tau_kww is the round-2 production centroid CRSISF KWW time (q=6.7).
  Vertex S(q) (stored, vertexPositionSq): the vertices of regular hexagons of
  area 1 form a honeycomb with side s_hex = sqrt(2/(3 sqrt 3)) ~ 0.620 on the
  same triangular lattice as the centroids. Shell G = h b1 + k b2 carries the
  basis weight |1 + exp(2 pi i (h+k)/3)|^2 = 1 or 4, so the strongest vertex
  peak is sqrt(3) q* = 4 pi/(sqrt(3) s_hex) ~ 11.69, where both ends of every
  edge scatter in phase (not 2 pi/s_hex ~ 10.1). Edge pairs alone give
  3 <J0(q ell)> to S(q); edge-length spread sigma_ell damps the 11.69 peak like
  a Debye-Waller factor exp(-G2^2 sigma_ell^2 / 2).

Output (vertexModel_hexagonality/):
  hex_metrics.csv          per-(p0,T) replica means (cached; --recompute)
  hex_snapshots.png        cells coloured by number of sides
  hex_order_vs_T.png       p6, |Psi6|, <q|z=6>, p6 vs tau_kww
  hex_vs_sq.png            S(q), P(z), S(q*) vs 1/(1-p6), 2D S(k)
  hex_vertex_sq.png        vertex S(q), P(ell), sqrt(3) q* peak vs edge spread

Usage:
  python3 plot_vertex_hexagonality.py
  python3 plot_vertex_hexagonality.py --recompute
  CELLGPU_SCRATCH=... python3 plot_vertex_hexagonality.py
Reads about 700 trajectory records (one per replica); I/O bound, ~1 min.
"""

