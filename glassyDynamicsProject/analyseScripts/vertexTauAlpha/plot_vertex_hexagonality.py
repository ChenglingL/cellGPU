def inv_defect_to_p6(x):
    x = np.asarray(x, dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        return 1.0 - 1.0 / x


def p6_to_inv_defect(p):
    p = np.asarray(p, dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        return 1.0 / (1.0 - p)


