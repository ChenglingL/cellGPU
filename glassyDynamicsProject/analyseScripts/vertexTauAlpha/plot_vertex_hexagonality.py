def draw_tissue(ax, g: dict, x0: float, y0: float, w: float) -> None:
    cen = g["cen"]
    sel = np.where(
        (cen[:, 0] > x0 - 1.5) & (cen[:, 0] < x0 + w + 1.5)
        & (cen[:, 1] > y0 - 1.5) & (cen[:, 1] < y0 + w + 1.5)
    )[0]
    polys, colors = [], []
    for c in sel:
        s, n = g["start"][c], g["z"][c]
        polys.append(g["poly"][s : s + n])
        colors.append(Z_COLOR[min(max(int(n), 4), 8)])
    pc = PolyCollection(polys, facecolors=colors, edgecolors="#6f6e69", linewidths=0.45)
    ax.add_collection(pc)
    ax.set_xlim(x0, x0 + w)
    ax.set_ylim(y0, y0 + w)
    ax.set_aspect("equal")
    ax.set_xticks([])
    ax.set_yticks([])
    for s in ax.spines.values():
        s.set_color(INK2)
        s.set_linewidth(0.8)


