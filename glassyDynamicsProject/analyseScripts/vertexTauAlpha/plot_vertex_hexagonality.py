def peak_in(q: np.ndarray, s: np.ndarray, lo: float, hi: float) -> tuple[float, float]:
    m = (q >= lo) & (q <= hi)
    i = int(np.argmax(s[m]))
    return float(q[m][i]), float(s[m][i])


def edge_sample(p0: float, T: float) -> np.ndarray:
    """Unique edge lengths pooled over the last record of every replica."""
    out = []
    for path in traj_paths(p0, T):
        fr = read_frame(path)
        out.append(unique_edge_lengths(fr["pos"], fr["vn"], np.array([fr["box"][0], fr["box"][3]])))
    return np.concatenate(out)


