def read_frame(path: Path, rec: int = -1) -> dict:
    with netcdf_file(path, "r", mmap=True) as ds:
        nrec = ds.variables["time"].shape[0]
        r = rec if rec >= 0 else nrec + rec
        pos = np.array(ds.variables["pos"][r], dtype=float).reshape(-1, 2)
        vn = np.array(ds.variables["Vneighs"][r], dtype=np.int64).reshape(-1, 3)
        vcn = np.array(ds.variables["VertexCellNeighbors"][r], dtype=np.int64).reshape(-1, 3)
        box = np.array(ds.variables["BoxMatrix"][r], dtype=float)
    return {"pos": pos, "vn": vn, "vcn": vcn, "box": box}


def unique_edge_lengths(pos: np.ndarray, vn: np.ndarray, L: np.ndarray) -> np.ndarray:
    v = np.repeat(np.arange(pos.shape[0]), 3)
    w = vn.ravel()
    keep = v < w
    d = pos[w[keep]] - pos[v[keep]]
    d -= L * np.round(d / L)
    return np.hypot(d[:, 0], d[:, 1])


def walk_cell(verts: np.ndarray, vn: np.ndarray) -> list[int] | None:
    """Order one cell's vertices by walking mesh edges inside the cell."""
    members = set(int(v) for v in verts)
    ring = [int(verts[0])]
    prev = -1
    for _ in range(len(verts) - 1):
        cur = ring[-1]
        nxt = [int(w) for w in vn[cur] if int(w) in members and int(w) != prev and int(w) not in ring]
        if not nxt:
            return None
        prev = cur
        ring.append(nxt[0])
    return ring if len(ring) == len(verts) else None


def build_tissue(fr: dict) -> dict:
    """Cell polygons from the 3-valent mesh. Corners are ordered by angle about
    the vertex mean of each (unwrapped) cell; cells where that order does not
    follow mesh edges (non-star-shaped, mostly hot T) are re-walked along the
    edges and oriented counter-clockwise."""
    pos, vn, vcn, box = fr["pos"], fr["vn"], fr["vcn"], fr["box"]
    if abs(box[1]) > 1e-12 or abs(box[2]) > 1e-12:
        raise ValueError("only rectangular boxes are handled")
    L = np.array([box[0], box[3]])
    Nv = pos.shape[0]
    Nc = Nv // 2
    cell_of = vcn.ravel()
    vert_of = np.repeat(np.arange(Nv), 3)
    order = np.argsort(cell_of, kind="stable")
    vert_sorted = vert_of[order]
    z = np.bincount(cell_of, minlength=Nc)
    start = np.concatenate([[0], np.cumsum(z)[:-1]])
    cid = np.repeat(np.arange(Nc), z)
    ref = vert_sorted[start]
    d = pos[vert_sorted] - pos[np.repeat(ref, z)]
    d -= L * np.round(d / L)
    cm = np.add.reduceat(d, start, axis=0) / z[:, None]
    rel = d - cm[cid]
    ang = np.arctan2(rel[:, 1], rel[:, 0])
    o2 = np.lexsort((ang, cid))
    rel = rel[o2]
    vs = vert_sorted[o2]
    idx = np.arange(rel.shape[0])
    last = start + z - 1
    nxt = idx + 1
    nxt[last] = start
    adjacent = (vn[vs] == vs[nxt][:, None]).any(axis=1)
    n_rewalked = 0
    for c in np.unique(cid[~adjacent]):
        s, n = start[c], z[c]
        ring = walk_cell(vs[s : s + n], vn)
        if ring is None:
            continue
        where = {int(v): k for k, v in enumerate(vs[s : s + n])}
        new = rel[s : s + n][[where[v] for v in ring]]
        area2 = np.sum(new[:, 0] * np.roll(new[:, 1], -1) - np.roll(new[:, 0], -1) * new[:, 1])
        if area2 < 0:
            new = new[::-1]
            ring = ring[::-1]
        rel[s : s + n] = new
        vs[s : s + n] = ring
        n_rewalked += 1
    prv = idx - 1
    prv[start] = last
    x0, y0 = rel[:, 0], rel[:, 1]
    x1, y1 = rel[nxt, 0], rel[nxt, 1]
    cross = x0 * y1 - x1 * y0
    A = 0.5 * np.bincount(cid, weights=cross, minlength=Nc)
    elen = np.hypot(x1 - x0, y1 - y0)
    P = np.bincount(cid, weights=elen, minlength=Nc)
    crel = np.stack(
        [
            np.bincount(cid, weights=(x0 + x1) * cross, minlength=Nc) / (6.0 * A),
            np.bincount(cid, weights=(y0 + y1) * cross, minlength=Nc) / (6.0 * A),
        ],
        axis=1,
    )
    cen = pos[ref] + cm + crel
    cen -= L * np.floor(cen / L)
    ax_, ay_ = rel[prv, 0] - x0, rel[prv, 1] - y0
    bx_, by_ = x1 - x0, y1 - y0
    cosang = (ax_ * bx_ + ay_ * by_) / (np.hypot(ax_, ay_) * np.hypot(bx_, by_))
    theta = np.degrees(np.arccos(np.clip(cosang, -1.0, 1.0)))
    # Each mesh edge (v,w) separates the two cells common to v and w.
    v = np.repeat(np.arange(Nv), 3)
    w = vn.ravel()
    keep = v < w
    cv = vcn[v[keep]]
    cw = vcn[w[keep]]
    common = (cv[:, :, None] == cw[:, None, :]).any(axis=2)
    ok_edges = bool(np.all(common.sum(axis=1) == 2))
    pairs = cv[common].reshape(-1, 2) if ok_edges else np.zeros((0, 2), dtype=np.int64)
    poly = rel + (cen - crel)[cid]
    return {
        "z": z, "A": A, "P": P, "cen": cen, "L": L, "pairs": pairs, "theta": theta,
        "elen": elen, "cid": cid, "start": start, "poly": poly, "Nc": Nc,
        "n_rewalked": n_rewalked, "ell": unique_edge_lengths(pos, vn, L),
        "ok": ok_edges and bool(np.all(A > 0)) and abs(A.sum() - L.prod()) < 1e-6 * L.prod(),
    }


def psi6_local(g: dict) -> np.ndarray:
    cen, L, pairs, Nc = g["cen"], g["L"], g["pairs"], g["Nc"]
    i, j = pairs[:, 0], pairs[:, 1]
    d = cen[j] - cen[i]
    d -= L * np.round(d / L)
    e = np.exp(6j * np.arctan2(d[:, 1], d[:, 0]))
    s = np.zeros(Nc, dtype=complex)
    np.add.at(s, i, e)
    np.add.at(s, j, e)  # exp(6i(theta+pi)) = exp(6i theta)
    nn = np.bincount(np.concatenate([i, j]), minlength=Nc)
    return s / np.maximum(nn, 1)


