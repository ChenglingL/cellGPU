def sk2d(cen: np.ndarray, L: float, kmax: float):
    nmax = int(kmax * L / (2.0 * math.pi))
    k1 = 2.0 * math.pi * np.arange(-nmax, nmax + 1) / L
    ex = np.exp(1j * np.outer(k1, cen[:, 0]))
    ey = np.exp(1j * np.outer(k1, cen[:, 1]))
    S = np.abs(ex @ ey.T) ** 2 / cen.shape[0]  # S[i,j] at (kx_i, ky_j)
    return k1, S


def ring_average_first_quadrant(k1: np.ndarray, S: np.ndarray, L: float, dk: float = 0.5):
    """Same annulus rule as structuralFeatures::computeStructureFactor."""
    KX, KY = np.meshgrid(k1, k1, indexing="ij")
    m = (KX > -1e-12) & (KY > -1e-12)
    k = np.hypot(KX[m], KY[m])
    s = S[m]
    dK = 2.0 * math.pi / L
    bw = dK * dk
    edges = np.arange(dK - 0.5 * bw, k.max(), bw)
    b = np.digitize(k, edges) - 1
    ok = (b >= 0) & (b < edges.size - 1)
    num = np.bincount(b[ok], weights=s[ok], minlength=edges.size - 1)
    cnt = np.bincount(b[ok], minlength=edges.size - 1)
    good = cnt > 0
    return (edges[:-1] + 0.5 * bw)[good], num[good] / cnt[good]


def representative_frame(p0: float, T: float) -> tuple[dict, float]:
    """Replica whose box-wide |Psi6| is the median over idx."""
    gs = [build_tissue(read_frame(p)) for p in traj_paths(p0, T)]
    psi = np.array([abs(psi6_local(g).mean()) for g in gs])
    i = int(np.argsort(psi)[len(psi) // 2])
    return gs[i], float(psi[i])


