def load_states() -> list[tuple[float, float]]:
    out, seen = [], set()
    with CSV_STATES.open() as f:
        lines = (ln for ln in f if ln.strip() and not ln.lstrip().startswith("#"))
        for r in csv.DictReader(lines):
            p0 = match_p0(float(r["p0"]))
            T = float(r["T"])
            if p0 is None or not (T > 0):
                continue
            k = state_key(p0, T)
            if k not in seen:
                seen.add(k)
                out.append((p0, T))
    return sorted(out)


def load_keyed(path: Path, cols: tuple[str, ...]) -> dict:
    out = {}
    if not path.is_file():
        return out
    with path.open() as f:
        for r in csv.DictReader(ln for ln in f if not ln.lstrip().startswith("#")):
            p0 = match_p0(float(r["p0"]))
            if p0 is None:
                continue
            out[state_key(p0, float(r["T"]))] = {c: float(r[c]) for c in cols}
    return out


def compute_metrics(recompute: bool) -> list[dict]:
    if METRICS.is_file() and not recompute:
        with METRICS.open() as f:
            rows = list(csv.DictReader(f))
        return [{k: float(v) for k, v in r.items()} for r in rows]
    states = load_states()
    with ThreadPoolExecutor(max_workers=8) as ex:
        res = [r for r in ex.map(lambda s: state_metrics(*s), states) if r is not None]
    sq = load_keyed(SQ_PEAK, ("q_peak", "S_peak"))
    kww = load_keyed(KWW_TAU, ("tau_kww", "crossed_1e"))
    for r in res:
        k = state_key(r["p0"], r["T"])
        r["S_peak"] = sq.get(k, {}).get("S_peak", math.nan)
        r["q_peak"] = sq.get(k, {}).get("q_peak", math.nan)
        r["tau_kww"] = kww.get(k, {}).get("tau_kww", math.nan)
        r["tau_crossed_1e"] = kww.get(k, {}).get("crossed_1e", math.nan)
        cur = read_vsq_curve(r["p0"], r["T"])
        r["q1_vert"], r["S1_vert"] = peak_in(*cur, 5.0, 8.5) if cur else (math.nan, math.nan)
        r["q2_vert"], r["S2_vert"] = peak_in(*cur, 10.0, 13.5) if cur else (math.nan, math.nan)
    OUTDIR.mkdir(parents=True, exist_ok=True)
    keys = list(res[0].keys())
    with METRICS.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        for r in res:
            w.writerow({k: (f"{v:.8g}" if isinstance(v, float) else v) for k, v in r.items()})
    print(f"wrote {METRICS} ({len(res)} states)")
    return [{k: float(v) for k, v in r.items()} for r in res]


def find(rows: list[dict], p0: float, T: float) -> dict:
    k = state_key(p0, T)
    for r in rows:
        if state_key(r["p0"], r["T"]) == k:
            return r
    raise KeyError(k)


