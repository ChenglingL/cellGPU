def frame_metrics(g: dict) -> dict:
    z = g["z"]
    hexa = z == 6
    q = g["P"] / np.sqrt(g["A"])
    ps = psi6_local(g)
    zc = z[g["cid"]]
    m1 = np.bincount(g["cid"], weights=g["elen"]) / z
    m2 = np.bincount(g["cid"], weights=g["elen"] ** 2) / z
    cv = np.sqrt(np.maximum(m2 - m1 * m1, 0.0)) / m1
    return {
        "p4": float(np.mean(z <= 4)),
        "p5": float(np.mean(z == 5)),
        "p6": float(np.mean(hexa)),
        "p7": float(np.mean(z == 7)),
        "p8": float(np.mean(z >= 8)),
        "mu2": float(np.mean((z - 6.0) ** 2)),
        "q_mean": float(q.mean()),
        "q6_mean": float(q[hexa].mean()),
        "psi6_local": float(np.abs(ps).mean()),
        "psi6_global": float(abs(ps.mean())),
        "angle_std6_deg": float(g["theta"][zc == 6].std()),
        "ellcv6": float(cv[hexa].mean()),
        "ell_mean": float(g["ell"].mean()),
        "ell_std": float(g["ell"].std()),
        "ell_fnear": float(np.mean(np.abs(g["ell"] / S_HEX - 1.0) < 0.1)),
        "edge_term_g2": float(3.0 * np.mean(j0(G2_HEX * g["ell"]))),
        "_zmean": float(z.mean()),
        "_ok": g["ok"],
    }


def state_metrics(p0: float, T: float) -> dict | None:
    paths = traj_paths(p0, T)
    if not paths:
        return None
    per = [frame_metrics(build_tissue(read_frame(p))) for p in paths]
    bad = sum(1 for m in per if not m["_ok"] or abs(m["_zmean"] - 6.0) > 1e-12)
    out = {"p0": p0, "T": T, "n_frames": len(per), "n_bad": bad}
    for k in FRAME_KEYS:
        v = np.array([m[k] for m in per])
        out[k] = float(v.mean())
        out[k + "_sd"] = float(v.std(ddof=1)) if v.size > 1 else math.nan
    return out


