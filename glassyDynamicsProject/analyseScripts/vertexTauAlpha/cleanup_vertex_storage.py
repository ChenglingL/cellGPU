#!/usr/bin/env python3
"""
Generated by Cursor. 2026-09-09.
Free scratch: delete superseded vertex (p0, T) raw files and extra T1-scan trajectories.

Physics:
  tau_estimate is driver -t (tauAlphaEst); tau_block = max(tau_est, 1000).
  Default-threshold jobs write 15 glassyDynamics files at waitingTime = k * tau_block,
  k = 0..14. T1 scan (folder t1_<tag> = l_T1) keeps only the last (max waitingTime)
  trajectory per (l_T1, p0, T). Voronoi trees are never listed.

Usage:
  python3 cleanup_vertex_storage.py --dry-run
  python3 cleanup_vertex_storage.py --execute
"""

from __future__ import annotations

import argparse
import csv
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_SCRATCH = "/scratch/bbtm/cli6/glassyDynamics/data"
N = 4096
MIN_BYTES = 1_000_000

TRAJ = re.compile(
    r"glassyDynamics_N(?P<n>\d+)_p(?P<p0>[0-9.]+)_T(?P<T>[0-9.]+)"
    r"_waitingTime(?P<tw>\d+)_idx(?P<idx>\d+)\.nc$"
)
CRSISF = re.compile(
    r"timeCRSISF_N(?P<n>\d+)_p(?P<p0>[0-9.]+)_T(?P<T>[0-9.]+)"
    r"_k[0-9.]+_waitingTime(?P<tw>\d+)_idx(?P<idx>\d+)\.nc$"
)
SIDECAR = re.compile(
    r"(?:SACtime(?:After10)?|sigmaXY)_N(?P<n>\d+)_p(?P<p0>[0-9.]+)_T(?P<T>[0-9.]+)"
)


def scratch_root() -> Path:
    return Path(os.environ.get("CELLGPU_SCRATCH", DEFAULT_SCRATCH)).resolve()


def vertex_root(scratch: Path) -> Path:
    return (scratch / f"N{N}" / "vertex").resolve()


def assert_vertex_file(path: Path, vroot: Path) -> None:
    rp = str(path.resolve())
    vr = str(vroot)
    if "/vertex/" not in rp + "/":
        raise SystemExit(f"refusing non-vertex path: {path}")
    if not rp.startswith(vr + os.sep) and rp != vr:
        raise SystemExit(f"path outside vertex root: {path}")
    if "productionRuns" in rp or "/additional/" in rp:
        raise SystemExit(f"refusing Voronoi-looking path: {path}")
    if "fluidConfigurations" in rp:
        raise SystemExit(f"refusing fluid config: {path}")


def load_csv(path: Path) -> list[dict]:
    with path.open() as f:
        return list(csv.DictReader(f))


def tau_key(est: float) -> str:
    return f"{est:.4g}"


def p0_key(p0: float) -> str:
    return f"{p0:.3f}"


def t_match(file_T: float, csv_T: float) -> bool:
    scale = max(abs(csv_T), 1e-12)
    return abs(file_T - csv_T) <= 5e-8 * scale + 5e-10


def doomed_default_points() -> list[tuple[float, float, str]]:
    """(p0, T, reason) to wipe under vertex/p*/ (not t1Scan)."""
    b1 = HERE / "vertexModel_tauAlpha_test" / "vertexModel_tauAlpha_test_per_curve.csv"
    b2 = HERE / "vertexModel_tauAlpha_batch2" / "state_points.csv"
    b3 = HERE / "vertexModel_tauAlpha_batch3" / "state_points.csv"
    b4 = HERE / "vertexModel_tauAlpha_batch4" / "state_points.csv"

    out: dict[tuple[str, str], tuple[float, float, str]] = {}

    def add(p0: float, T: float, reason: str) -> None:
        key = (p0_key(p0), f"{T:.8f}")
        if key not in out:
            out[key] = (p0, T, reason)

    seen_b1: set[tuple[str, str]] = set()
    for r in load_csv(b1):
        p0, T = float(r["p0"]), float(r["T"])
        k = (p0_key(p0), f"{T:.8f}")
        if k not in seen_b1:
            seen_b1.add(k)
            add(p0, T, "batch1_voronoi_tau_est")

    b2_by = {}
    for r in load_csv(b2):
        p0 = float(r["p0"])
        est = float(r["tauAlphaEst"])
        b2_by[(p0_key(p0), tau_key(est))] = (p0, float(r["T"]))

    for r in load_csv(b3):
        p0 = float(r["p0"])
        est = float(r["tauAlphaEst"])
        prev = b2_by.get((p0_key(p0), tau_key(est)))
        if prev is not None:
            add(prev[0], prev[1], "batch2_retargeted_in_batch3")

    for r in load_csv(b4):
        t_old = (r.get("T_old") or "").strip()
        if t_old:
            add(float(r["p0"]), float(t_old), "batch4_T_old")

    return list(out.values())


def is_doomed_T(p0: float, T: float, doomed: list[tuple[float, float, str]]) -> str | None:
    for dp, dT, reason in doomed:
        if p0_key(p0) == p0_key(dp) and t_match(T, dT):
            return reason
    return None


def collect_default(vroot: Path, doomed: list[tuple[float, float, str]]) -> list[tuple[Path, int, str]]:
    hits: list[tuple[Path, int, str]] = []
    pdirs = []
    try:
        with os.scandir(vroot) as it:
            pdirs = [Path(e.path) for e in it if e.is_dir(follow_symlinks=False) and e.name.startswith("p")]
    except OSError:
        return hits

    def consider(path: Path, p0: float, T: float, sz: int) -> None:
        assert_vertex_file(path, vroot)
        reason = is_doomed_T(p0, T, doomed)
        if reason is None:
            return
        hits.append((path, sz, reason))

    for pdir in pdirs:
        for path, sz in _scandir_nc(pdir):
            m = TRAJ.search(path.name)
            if m:
                consider(path, float(m.group("p0")), float(m.group("T")), sz)
                continue
            m = SIDECAR.search(path.name)
            if m:
                consider(path, float(m.group("p0")), float(m.group("T")), sz)

    crsis_root = vroot / "tauAlphaData"
    if crsis_root.is_dir():
        try:
            with os.scandir(crsis_root) as it:
                cr_pdirs = [Path(e.path) for e in it if e.is_dir(follow_symlinks=False)]
        except OSError:
            cr_pdirs = []
        for pdir in cr_pdirs:
            for path, sz in _scandir_nc(pdir):
                m = CRSISF.search(path.name)
                if m:
                    consider(path, float(m.group("p0")), float(m.group("T")), sz)
    return hits


def _scandir_nc(dirpath: Path):
    """Yield (Path, size) for *.nc in one directory; skip missing dirs."""
    try:
        with os.scandir(dirpath) as it:
            for ent in it:
                if not ent.name.endswith(".nc") or not ent.is_file(follow_symlinks=False):
                    continue
                try:
                    sz = ent.stat(follow_symlinks=False).st_size
                except OSError:
                    sz = 0
                yield Path(ent.path), sz
    except FileNotFoundError:
        return


def collect_t1(vroot: Path) -> list[tuple[Path, int, str]]:
    hits: list[tuple[Path, int, str]] = []
    scan = vroot / "t1Scan"
    if not scan.is_dir():
        return hits

    groups: dict[tuple[str, str, str], list[tuple[Path, int, int]]] = defaultdict(list)

    try:
        tags = [e.name for e in os.scandir(scan) if e.is_dir(follow_symlinks=False)]
    except OSError:
        return hits

    for tag in tags:
        tagdir = scan / tag
        try:
            pdirs = [e.name for e in os.scandir(tagdir) if e.is_dir(follow_symlinks=False)]
        except OSError:
            continue
        for pdir in pdirs:
            if not pdir.startswith("p"):
                continue
            for path, sz in _scandir_nc(tagdir / pdir):
                m = TRAJ.search(path.name)
                if not m:
                    continue
                assert_vertex_file(path, vroot)
                groups[(tag, m.group("p0"), m.group("T"))].append(
                    (path, int(m.group("tw")), sz)
                )

    drop_keys: set[tuple[str, str, str, int]] = set()
    for (tag, p0s, Tstr), files in groups.items():
        valid = [f for f in files if f[2] >= MIN_BYTES]
        keep = max(valid, key=lambda z: z[1]) if valid else None
        for path, tw, sz in files:
            if keep is not None and path == keep[0]:
                continue
            hits.append((path, sz, f"t1_not_last tag={tag}"))
            drop_keys.add((tag, p0s, Tstr, tw))

    for tag in tags:
        cr_root = scan / tag / "tauAlphaData"
        if not cr_root.is_dir():
            continue
        try:
            pdirs = [e.name for e in os.scandir(cr_root) if e.is_dir(follow_symlinks=False)]
        except OSError:
            continue
        for pdir in pdirs:
            for path, sz in _scandir_nc(cr_root / pdir):
                m = CRSISF.search(path.name)
                if not m:
                    continue
                key = (tag, m.group("p0"), m.group("T"), int(m.group("tw")))
                if key in drop_keys:
                    assert_vertex_file(path, vroot)
                    hits.append((path, sz, f"t1_crisf_not_last tag={tag}"))
    return hits


def gb(n: int) -> str:
    return f"{n / (1024**3):.2f} GiB"


def main() -> int:
    ap = argparse.ArgumentParser(description="Delete superseded vertex data; keep Voronoi.")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--execute", action="store_true")
    args = ap.parse_args()

    scratch = scratch_root()
    vroot = vertex_root(scratch)
    if not vroot.is_dir():
        print(f"missing {vroot}", file=sys.stderr)
        return 1

    doomed = doomed_default_points()
    print(f"scratch={scratch}", flush=True)
    print(f"vertex_root={vroot}", flush=True)
    print(f"doomed (p0,T) count={len(doomed)}", flush=True)
    print("scanning default-threshold ...", flush=True)

    default_hits = collect_default(vroot, doomed)
    print(f"default hits={len(default_hits)}", flush=True)
    print("scanning t1Scan ...", flush=True)
    t1_hits = collect_t1(vroot)
    print(f"t1 hits={len(t1_hits)}", flush=True)
    # unique by path
    by_path: dict[Path, tuple[int, str]] = {}
    for path, sz, reason in default_hits + t1_hits:
        by_path[path.resolve()] = (sz, reason)

    items = sorted(by_path.items(), key=lambda kv: str(kv[0]))
    n_def = sum(1 for p, _ in items if "t1Scan" not in str(p))
    n_t1 = len(items) - n_def
    bytes_def = sum(sz for p, (sz, _) in items if "t1Scan" not in str(p))
    bytes_t1 = sum(sz for p, (sz, _) in items if "t1Scan" in str(p))
    bytes_all = bytes_def + bytes_t1

    manifest = Path("/tmp/cleanup_vertex_storage_manifest.tsv")
    with manifest.open("w") as f:
        f.write("path\tsize_bytes\treason\n")
        for path, (sz, reason) in items:
            f.write(f"{path}\t{sz}\t{reason}\n")

    print(f"default-threshold files: {n_def}  {gb(bytes_def)}")
    print(f"t1Scan extra files:      {n_t1}  {gb(bytes_t1)}")
    print(f"total to delete:         {len(items)}  {gb(bytes_all)}")
    print(f"manifest: {manifest}")

    if args.dry_run:
        print("dry-run: no unlinks")
        return 0

    deleted = 0
    failed = 0
    for path, (sz, reason) in items:
        assert_vertex_file(path, vroot)
        try:
            path.unlink()
            deleted += 1
        except OSError as e:
            failed += 1
            print(f"unlink failed {path}: {e}", file=sys.stderr)
    print(f"unlinked {deleted} files, failed {failed}")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
