#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-10-21.
Frustrated cells in KA=1 quenched vertex production snapshots.

Physics (A0=1, N=4096, periodic box L=64):
  Driver vertexProductionQuenchCells repeats the own-p0 quench of
  vertexProductionRigidQuench (FIRE, T1s on, E = sum_i (A_i-1)^2 + (P_i-p0)^2)
  on the last 3 frames of idx 0..9 and writes z, dA = A-1, dP = P-p0 per cell.
  A cell is at its target shape if |P - p0| <= EPS and |A - (1 + s)| <= EPS;
  otherwise it is frustrated.
  s is the area offset shared by all cells that reach P = p0: sum_i A_i = L^2
  is fixed, so the area a square or pentagon gives up is spread evenly over
  the rest (one square at p0=3.85: dA = -0.0596 on the square, +1.46e-5 on
  each of the other 4095). Measured from A = 1 instead, a single square would
  make every cell "frustrated". s = median dA over cells with |dP| <= EPS.
  EPS = 1e-5: a single cell off by EPS has E = 1e-10, the rigid cut on the
  snapshot energy, so a snapshot is rigid about when it has a frustrated cell.
  Floppy snapshots stop at E < 1e-14, so their cells sit below ~4e-8. In
  quenches that converge (max force < 1e-12) the per-cell deviation has a gap
  from 1e-10 to 1e-5 and EPS sits in it. Quenches stopped by the plateau rule
  or the 1e6-step cap fill the gap in, so there the count depends on EPS and
  on how far FIRE got; the sensitivity columns redo it with EPS = 1e-6 and
  1e-4 (the band in the figure) and with the literal |A - 1| <= 1e-3.
  tau_kww is the round-2 production centroid CRSISF KWW time (q=6.7).

Output (vertexModel_quenchFrustrated/):
  quench_frustrated_snapshots.csv   one row per snapshot
  quench_frustrated_states.csv      per-(p0,T) mean frustrated fraction
  quench_frustrated_vs_tau.png      frustrated fraction vs tau_alpha, per p0
  quench_frustrated_snapshots.png   every snapshot, one panel per p0
  quench_frustrated_threshold.png   per-cell deviation histogram with EPS

Usage:
  python3 plot_vertex_quench_frustrated.py
Reads quenchCells/*.csv; snapshots of running jobs are used once their
summary row is written.
"""

from __future__ import annotations

import io
import math
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.ticker import FixedFormatter, FixedLocator

from plot_vertex_rigid_quench import (
    FS_LABEL,
    FS_LEGEND,
    FS_NOTE,
    FS_TITLE,
    INK,
    INK2,
    MUTED,
    N,
    P0_COLOR,
    P0_MARKER,
    P0_ORDER,
    load_quenches,
    load_tau,
    p0_key,
    scratch_root,
    style_axis,
    write_csv,
)

HERE = Path(__file__).resolve().parent
OUTDIR = HERE / "vertexModel_quenchFrustrated"
KA = 1.0
EPS = 1e-5  # per-cell tolerance on |P - p0| and |A - (1 + s)|
EPS_SCAN = (1e-6, 1e-4)  # sensitivity of the count to EPS
EPS_A_LITERAL = 1e-3  # literal |A - 1| tolerance (must sit above s)
E_RIGID = 1e-10  # snapshot rigid cut, as in the rigid-quench runs
HIST_BINS = np.arange(-14.0, 0.01, 0.2)  # log10 of the per-cell deviation; lower values go in the first bin
Y_ZERO = 3.2e-6  # row for states with no frustrated cell, below an axis break
SNAP_GRAY = "#898781"  # floppy-snapshot cells (neutral)
SNAP_ORANGE = "#eb6834"  # rigid snapshots, converged (categorical slots 2-3, not p0 colors)
SNAP_GREEN = "#1baf7a"  # rigid snapshots, stopped by the plateau rule or the step cap


def cells_dir() -> Path:
    return scratch_root() / f"N{N}" / "vertex" / "productionRuns" / "quenchCells"


def read_csv_clean(path: Path, **kw) -> pd.DataFrame:
    """Read a driver CSV; scratch I/O errors can leave NUL bytes or cut rows."""
    data = path.read_bytes()
    if b"\0" in data:
        data = data.replace(b"\0", b"")
    df = pd.read_csv(io.BytesIO(data), on_bad_lines="skip", **kw)
    for col in df.columns:
        if col != "status":
            df[col] = pd.to_numeric(df[col], errors="coerce")
    return df.dropna()


def count_frustrated(dA: np.ndarray, dP: np.ndarray, eps: float) -> tuple[np.ndarray, float]:
    """Frustrated mask at tolerance eps, and the shared area offset s."""
    ok = np.abs(dP) <= eps
    if not ok.any():
        return np.ones(dA.size, dtype=bool), math.nan
    s = float(np.median(dA[ok]))
    return ~ok | (np.abs(dA - s) > eps), s


def snapshot_rows(hist: dict[str, np.ndarray]) -> list[dict]:
    """One row per completed snapshot; fills the per-cell deviation histograms."""
    rows: list[dict] = []
    for sum_path in sorted(cells_dir().glob(f"quenchCellsSummary_N{N}_p*_T*_KA{KA:.4f}_idx*.csv")):
        cell_path = sum_path.with_name(sum_path.name.replace("quenchCellsSummary_", "quenchCells_"))
        if not cell_path.is_file():
            continue
        summ = read_csv_clean(sum_path)
        cells = read_csv_clean(cell_path, usecols=["idx", "rec", "cell", "z", "dA", "dP"])
        groups = {k: g for k, g in cells.groupby(["idx", "rec"], sort=False)}
        for r in summ.itertuples(index=False):
            g = groups.get((r.idx, r.rec))
            if g is None or len(g) != N or g["cell"].nunique() != N:
                continue  # cut by an I/O error
            dA = g["dA"].to_numpy()
            dP = g["dP"].to_numpy()
            z = g["z"].to_numpy().astype(int)
            fr, s = count_frustrated(dA, dP, EPS)
            dev = np.abs(dP) if math.isnan(s) else np.maximum(np.abs(dP), np.abs(dA - s))
            key = "floppy" if r.E <= E_RIGID else ("conv" if r.status == "conv" else "stopped")
            hist[key] += np.histogram(np.clip(np.log10(np.maximum(dev, 1e-300)), HIST_BINS[0], 0.0),
                                      bins=HIST_BINS)[0]
            row = {
                "p0": p0_key(float(r.p0)),
                "T": round(float(r.T), 8),
                "idx": int(r.idx),
                "rec": int(r.rec),
                "E": float(r.E),
                "status": r.status,
                "rigid": int(r.E > E_RIGID),
                "s": s,
                "n_frustrated": int(fr.sum()),
                "f_frustrated": float(fr.mean()),
            }
            for eps in EPS_SCAN:
                row[f"f_frustrated_eps{eps:.0e}"] = float(count_frustrated(dA, dP, eps)[0].mean())
            row["f_frustrated_literalA"] = float(
                ((np.abs(dP) > EPS) | (np.abs(dA) > EPS_A_LITERAL)).mean())
            for zz, lab in ((4, "z4"), (5, "z5"), (6, "z6")):
                row[f"n_{lab}"] = int((z == zz).sum())
                row[f"n_frustrated_{lab}"] = int((fr & (z == zz)).sum())
            row["n_z7plus"] = int((z >= 7).sum())
            row["n_frustrated_z7plus"] = int((fr & (z >= 7)).sum())
            rows.append(row)
    rows.sort(key=lambda s: (P0_ORDER.index(s["p0"]), -s["T"], s["idx"], s["rec"]))
    return rows


def check_energies(snaps: list[dict]) -> None:
    """The quench is the own-p0 quench of the rigid-quench runs: E must match."""
    old = {(r["p0"], r["T"], r["idx"], r["rec"]): r["E"] for r in load_quenches(KA) if r["stage"] == "own"}
    rel = [abs(s["E"] - old[k]) / max(old[k], 1e-12)
           for s in snaps if (k := (s["p0"], s["T"], s["idx"], s["rec"])) in old]
    if rel:
        print(f"E vs rigidQuench own quench: {len(rel)} matched, max rel diff {max(rel):.2e}, "
              f"{sum(x > 1e-6 for x in rel)} differ by > 1e-6")


def summarize(snaps: list[dict], tau: dict) -> list[dict]:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for s in snaps:
        groups[(s["p0"], s["T"])].append(s)
    out: list[dict] = []
    for (p0, T), g in groups.items():
        f = np.array([s["f_frustrated"] for s in g])
        row = {
            "p0": p0,
            "T": T,
            "tau_kww": tau.get((p0, T), math.nan),
            "n_snap": len(g),
            "f_rigid": float(np.mean([s["rigid"] for s in g])),
            "f_frustrated_mean": float(f.mean()),
            "f_frustrated_sem": float(f.std(ddof=1) / math.sqrt(len(f))) if len(f) > 1 else math.nan,
            "f_frustrated_median": float(np.median(f)),
            "n_frustrated_mean": float(np.mean([s["n_frustrated"] for s in g])),
            "n_frustrated_max": int(max(s["n_frustrated"] for s in g)),
        }
        for eps in EPS_SCAN:
            row[f"f_frustrated_eps{eps:.0e}_mean"] = float(np.mean([s[f"f_frustrated_eps{eps:.0e}"] for s in g]))
        row["f_frustrated_literalA_mean"] = float(np.mean([s["f_frustrated_literalA"] for s in g]))
        for lab in ("z4", "z5", "z6", "z7plus"):
            row[f"n_{lab}_mean"] = float(np.mean([s[f"n_{lab}"] for s in g]))
            row[f"n_frustrated_{lab}_mean"] = float(np.mean([s[f"n_frustrated_{lab}"] for s in g]))
        out.append(row)
    out.sort(key=lambda z: (P0_ORDER.index(z["p0"]), -z["T"]))
    return out


def fraction_axis(ax, labels: bool = True) -> None:
    """Log x and log y with a "0" row below a break, plus all-cells / one-cell guides."""
    for y, lab, xt, ha in ((1.0, "all cells", 0.99, "right"), (1.0 / N, "one cell per snapshot", 0.01, "left")):
        ax.axhline(y, color=MUTED, lw=1.0, ls=":", zorder=1)
        if labels:
            ax.text(xt, y, lab, transform=ax.get_yaxis_transform(), ha=ha, va="bottom",
                    fontsize=FS_NOTE, color=INK2)
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_ylim(2.4e-6, 2.0)
    major = [Y_ZERO] + [10.0**k for k in range(-5, 1)]
    ax.yaxis.set_major_locator(FixedLocator(major))
    ax.yaxis.set_major_formatter(FixedFormatter(["0"] + [rf"$10^{{{k}}}$" for k in range(-5, 1)]))
    ax.yaxis.set_minor_locator(FixedLocator([m * 10.0**k for k in range(-5, 0) for m in range(2, 10)]))
    br = ax.get_yaxis_transform()
    for yb in (4.6e-6, 5.4e-6):
        ax.plot([-0.012, 0.012], [yb / 1.08, yb * 1.08], transform=br, color=INK2, lw=1.0, clip_on=False)


def plot_snapshots(snaps: list[dict], states: list[dict], path: Path) -> None:
    """Every snapshot, one panel per p0: shows whether the fraction jumps."""
    rng = np.random.default_rng(0)
    fig, axes = plt.subplots(2, 3, figsize=(14.0, 8.0), sharex=True, sharey=True)
    for ax, p0 in zip(axes.ravel(), P0_ORDER):
        st = sorted((s for s in states if s["p0"] == p0 and math.isfinite(s["tau_kww"])),
                    key=lambda s: s["tau_kww"])
        for s in st:
            f = np.array([z["f_frustrated"] for z in snaps if z["p0"] == p0 and z["T"] == s["T"]])
            x = s["tau_kww"] * 10.0 ** rng.uniform(-0.05, 0.05, f.size)
            ax.scatter(x, np.where(f > 0, f, Y_ZERO), s=16, color=P0_COLOR[p0], alpha=0.55,
                       edgecolors="none", zorder=3, clip_on=False)
        on = [s for s in st if s["f_frustrated_mean"] > 0]
        ax.plot([s["tau_kww"] for s in on], [s["f_frustrated_mean"] for s in on], color=INK, lw=1.3,
                zorder=4, label="mean over snapshots")
        fraction_axis(ax, labels=ax is axes[0, 0])
        ax.set_title(rf"$p_0={p0:.3f}$", fontsize=FS_TITLE, color=INK)
        style_axis(ax)
    for ax in axes[1]:
        ax.set_xlabel(r"$\tau_\alpha$ of the parent state", fontsize=FS_LABEL, color=INK)
    for ax in axes[:, 0]:
        ax.set_ylabel("frustrated fraction", fontsize=FS_LABEL, color=INK)
    axes[0, 0].legend(fontsize=FS_LEGEND, frameon=False, loc="center left")
    fig.text(0.01, 0.005, r"dots: single snapshots (30 per state, small $\tau_\alpha$ jitter);"
             r" 0 row: no frustrated cell; tolerance $10^{-5}$", fontsize=FS_NOTE - 1, color=INK2)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    fig.savefig(path, dpi=180)
    plt.close(fig)


def plot_vs_tau(states: list[dict], path: Path) -> None:
    fig, ax = plt.subplots(figsize=(9.0, 5.6))
    for p0 in P0_ORDER:
        st = sorted((s for s in states if s["p0"] == p0 and math.isfinite(s["tau_kww"])),
                    key=lambda s: s["tau_kww"])
        if not st:
            continue
        c = P0_COLOR[p0]
        on = [s for s in st if s["f_frustrated_mean"] > 0]
        off = [s for s in st if s["f_frustrated_mean"] == 0]
        if on:
            x = np.array([s["tau_kww"] for s in on])
            y = np.array([s["f_frustrated_mean"] for s in on])
            e = np.nan_to_num(np.array([s["f_frustrated_sem"] for s in on]))
            lo = np.array([s[f"f_frustrated_eps{EPS_SCAN[1]:.0e}_mean"] for s in on])
            hi = np.array([s[f"f_frustrated_eps{EPS_SCAN[0]:.0e}_mean"] for s in on])
            ax.fill_between(x, np.maximum(lo, 0.5 * Y_ZERO), hi, color=c, alpha=0.15, lw=0, zorder=2)
            ax.errorbar(x, y, yerr=[np.minimum(e, 0.95 * y), e], color=c, marker=P0_MARKER[p0], ms=8,
                        lw=2, capsize=3, mec="white", mew=1.0, label=rf"$p_0={p0:.3f}$", zorder=3)
        if off:
            ax.plot([s["tau_kww"] for s in off], [Y_ZERO] * len(off), ls="none", marker=P0_MARKER[p0],
                    ms=8, mfc="white", mec=c, mew=1.6, zorder=3, clip_on=False,
                    label=None if on else rf"$p_0={p0:.3f}$")
    fraction_axis(ax)
    ax.set_xlabel(r"$\tau_\alpha$ of the parent state", fontsize=FS_LABEL, color=INK)
    ax.set_ylabel("fraction of frustrated cells", fontsize=FS_LABEL, color=INK)
    ax.set_title(rf"$K_A=1$ quench at own $p_0$ (tolerance $10^{{{int(math.log10(EPS))}}}$)",
                 fontsize=FS_TITLE, color=INK)
    style_axis(ax)
    ax.legend(fontsize=FS_LEGEND, frameon=False, loc="upper left", bbox_to_anchor=(1.01, 1.0))
    fig.text(0.01, 0.005, "mean over 30 snapshots, error bars s.e.m.; band: tolerance $10^{-6}$ (top) to"
             " $10^{-4}$ (bottom)\nhollow on the 0 row: no frustrated cell in any snapshot",
             fontsize=FS_NOTE - 1, color=INK2)
    fig.tight_layout(rect=(0, 0.06, 1, 1))
    fig.savefig(path, dpi=180)
    plt.close(fig)


def plot_threshold(hist: dict[str, np.ndarray], path: Path) -> None:
    fig, ax = plt.subplots(figsize=(8.4, 5.0))
    mid = 0.5 * (HIST_BINS[:-1] + HIST_BINS[1:])
    for key, col, lab in (("floppy", SNAP_GRAY, r"floppy snapshots ($E\leq10^{-10}$)"),
                          ("conv", SNAP_ORANGE, r"rigid, converged (max force $<10^{-12}$)"),
                          ("stopped", SNAP_GREEN, r"rigid, stopped by plateau rule or $10^6$ steps")):
        h = hist[key].astype(float)
        if h.sum() == 0:
            continue
        ax.step(mid, np.where(h > 0, h, np.nan), where="mid", color=col, lw=2, label=lab)
    ax.axvline(math.log10(EPS), color=INK, lw=1.4, ls="--")
    ax.text(math.log10(EPS), 0.97, r"  tolerance $10^{-5}$", transform=ax.get_xaxis_transform(),
            ha="left", va="top", fontsize=FS_NOTE, color=INK)
    ax.set_yscale("log")
    ax.set_xlim(HIST_BINS[0], HIST_BINS[-1])
    ax.set_xlabel(r"$\log_{10}\max(|P-p_0|,\ |A-1-s|)$ per cell (first bin: $\leq10^{-14}$)",
                  fontsize=FS_LABEL, color=INK)
    ax.set_ylabel("number of cells", fontsize=FS_LABEL, color=INK)
    ax.set_title(r"$K_A=1$ quenched cells, all states", fontsize=FS_TITLE, color=INK)
    ax.set_ylim(top=max(h.max() for h in hist.values()) * 300)  # room for the legend above the data
    style_axis(ax)
    ax.legend(fontsize=FS_LEGEND, frameon=False, loc="upper left", ncol=1)
    fig.tight_layout()
    fig.savefig(path, dpi=180)
    plt.close(fig)


def main() -> None:
    OUTDIR.mkdir(parents=True, exist_ok=True)
    hist = {k: np.zeros(HIST_BINS.size - 1, dtype=np.int64) for k in ("floppy", "conv", "stopped")}
    snaps = snapshot_rows(hist)
    print(f"snapshots = {len(snaps)} from {cells_dir()}")
    if not snaps:
        return
    check_energies(snaps)
    for eps_key, lab in (("n_frustrated", "1e-05"),):
        a = sum(1 for s in snaps if s["rigid"] and s[eps_key] == 0)
        b = sum(1 for s in snaps if not s["rigid"] and s[eps_key] > 0)
        print(f"EPS={lab}: rigid snapshots with no frustrated cell = {a}, floppy ones with one = {b}")
    states = summarize(snaps, load_tau())
    write_csv(OUTDIR / "quench_frustrated_snapshots.csv", snaps)
    write_csv(OUTDIR / "quench_frustrated_states.csv", states)
    for k, h in hist.items():
        print(f"{k:6s} cells per log10 bin [{HIST_BINS[0]:.0f}, 0):", " ".join(str(int(v)) for v in h))
    for s in states:
        print(f"p0={s['p0']:.3f} T={s['T']:.6g} tau={s['tau_kww']:.4g} n={s['n_snap']} "
              f"rigid={s['f_rigid']:.2f} frustrated={s['f_frustrated_mean']:.3g} "
              f"(eps 1e-6: {s['f_frustrated_eps1e-06_mean']:.3g}, 1e-4: {s['f_frustrated_eps1e-04_mean']:.3g}, "
              f"literal A: {s['f_frustrated_literalA_mean']:.3g}) n_fr={s['n_frustrated_mean']:.1f} "
              f"[sq {s['n_frustrated_z4_mean']:.1f} pent {s['n_frustrated_z5_mean']:.1f} "
              f"hex {s['n_frustrated_z6_mean']:.1f} 7+ {s['n_frustrated_z7plus_mean']:.1f}]")
    plot_vs_tau(states, OUTDIR / "quench_frustrated_vs_tau.png")
    plot_snapshots(snaps, states, OUTDIR / "quench_frustrated_snapshots.png")
    plot_threshold(hist, OUTDIR / "quench_frustrated_threshold.png")


if __name__ == "__main__":
    main()
