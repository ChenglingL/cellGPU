#!/usr/bin/env python3
"""
Generated by Cursor. 2026-09-16.
Replica mean and std of production stress autocorrelation C_sigma(dt).

Physics:
  C_sigma(dt) = <sigma_xy(t) sigma_xy(t+dt)> from the Ramirez multi-tau
  correlator (evaluate(false); not mean-subtracted). Instantaneous sigma_xy
  is the area-normalized virial (getSigmaXY). Production samples SAC every
  dt=0.01 after 10 tau_block of NVT eq, for 10 tau_block.

  Per (p0, T): arithmetic mean and sample std (ddof=1) over idx=0..9 on the
  native correlator lag grid (same grid for all replicas of one state).
  SEM = std / sqrt(n_idx). Units: reduced time, reduced stress^2.
  Green-Kubo G(t) factor is C_sigma/T (no extra volume prefactor).

Usage:
  python3 combine_vertex_production_sac.py
  CELLGPU_SCRATCH=... python3 combine_vertex_production_sac.py
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import LogNorm

from plot_vertex_production_sigma import (
    IDX_MAX,
    N,
    P0_ORDER,
    load_states,
    read_two_values,
    scratch_prod,
)

HERE = Path(__file__).resolve().parent
OUTDIR = HERE / "vertexModel_productionSAC"
CSV_OUT = OUTDIR / "SAC_combined_mean.csv"
FIG_OUT = OUTDIR / "SAC_vs_t_all_p0.png"

FS_TITLE = 17
FS_LABEL = 16
FS_TICK = 14


def sac_path(p0: float, T: float, idx: int) -> Path | None:
    folder = scratch_prod() / f"p{p0:.3f}"
    hits = sorted(
        folder.glob(f"SACtime_N{N}_p{p0:.4f}_T{T:.8f}_waitingTime*_idx{idx}.nc")
    )
    return hits[0] if hits else None


def load_replicas(p0: float, T: float) -> list[tuple[np.ndarray, np.ndarray]]:
    curves = []
    for idx in range(IDX_MAX + 1):
        path = sac_path(p0, T, idx)
        if path is None:
            continue
        c_sig, dt = read_two_values(path)
        order = np.argsort(dt)
        curves.append((dt[order], c_sig[order]))
    return curves


def mean_std_native(
    curves: list[tuple[np.ndarray, np.ndarray]],
) -> tuple[np.ndarray, np.ndarray, np.ndarray, int]:
    """Mean/std on replica-0 lags if all grids match; else interpolate."""
    n_idx = len(curves)
    if n_idx == 0:
        empty = np.array([])
        return empty, empty, empty, 0
    dt0, _ = curves[0]
    same = all(
        c[0].size == dt0.size and np.allclose(c[0], dt0, rtol=0, atol=1e-12)
        for c in curves
    )
    if same:
        stacked = np.vstack([c[1] for c in curves])
        tgrid = dt0.astype(float)
    else:
        tmin = max(c[0][0] for c in curves)
        tmax = min(c[0][-1] for c in curves)
        n = max(min(c[0].size for c in curves), 32)
        if not (tmax > tmin):
            stacked = np.vstack(
                [np.interp(dt0, c[0], c[1]) for c in curves]
            )
            tgrid = dt0.astype(float)
        else:
            # Keep dt=0 if every replica has it.
            has0 = all(c[0][0] == 0.0 for c in curves)
            tpos = np.geomspace(max(tmin, 1e-12), tmax, n)
            tgrid = np.concatenate(([0.0], tpos)) if has0 else tpos
            stacked = np.vstack(
                [np.interp(tgrid, c[0], c[1]) for c in curves]
            )
    mean = stacked.mean(axis=0)
    if n_idx == 1:
        std = np.zeros_like(mean)
    else:
        std = stacked.std(axis=0, ddof=1)
    return tgrid, mean, std, n_idx


def plot_sac(by_p0: dict[float, list[tuple[float, np.ndarray, np.ndarray, np.ndarray]]]):
    fig = plt.figure(figsize=(13.6, 8.0))
    gs = fig.add_gridspec(
        2, 3, left=0.07, right=0.98, top=0.93, bottom=0.09, wspace=0.26, hspace=0.32
    )
    cmap = plt.get_cmap("coolwarm")
    for i, p0 in enumerate(P0_ORDER):
        row, col = divmod(i, 3)
        ax = fig.add_subplot(gs[row, col])
        ax.set_title(rf"$p_0={p0:.3f}$", fontsize=FS_TITLE, pad=4)
        ax.tick_params(labelsize=FS_TICK)
        ax.set_xscale("log")
        ax.set_yscale("log")
        pts = sorted(by_p0[p0], key=lambda z: z[0])
        if not pts:
            continue
        Ts = np.array([z[0] for z in pts])
        norm = LogNorm(vmin=Ts.min(), vmax=Ts.max())
        for T, dt, mean, _std in pts:
            y = mean / T
            pos = (dt > 0) & (y > 0)
            if not np.any(pos):
                continue
            ax.plot(dt[pos], y[pos], color=cmap(norm(T)), lw=1.1)
        if i >= 3:
            ax.set_xlabel(r"$\Delta t$", fontsize=FS_LABEL)
        if i % 3 == 0:
            ax.set_ylabel(r"$C_\sigma(\Delta t)/T$", fontsize=FS_LABEL)
    fig.suptitle(
        r"Production $\langle C_\sigma\rangle/T$ (idx=0..9)",
        fontsize=FS_TITLE,
    )
    fig.savefig(FIG_OUT, dpi=200)
    fig.savefig(FIG_OUT.with_suffix(".pdf"))
    plt.close(fig)
    print(f"wrote {FIG_OUT}")


def main() -> None:
    OUTDIR.mkdir(parents=True, exist_ok=True)
    states = load_states()
    print(f"state points={len(states)}  scratch={scratch_prod()}")
    rows = []
    missing = []
    by_p0: dict[float, list[tuple[float, np.ndarray, np.ndarray, np.ndarray]]] = {
        p: [] for p in P0_ORDER
    }
    for st in states:
        p0, T = st["p0"], st["T"]
        curves = load_replicas(p0, T)
        if not curves:
            missing.append((p0, T))
            continue
        dt, mean, std, n_idx = mean_std_native(curves)
        if dt.size == 0:
            missing.append((p0, T))
            continue
        sem = std / math.sqrt(n_idx)
        pkey = min(P0_ORDER, key=lambda p: abs(p - p0))
        by_p0[pkey].append((T, dt, mean, std))
        for t, y, s, e in zip(dt, mean, std, sem):
            rows.append(
                {
                    "p0": f"{p0:.3f}",
                    "T": f"{T:.8g}",
                    "batch": st["batch"],
                    "tauBlock": f"{st['tauBlock']:.8g}",
                    "dt": f"{float(t):.8g}",
                    "C_mean": f"{float(y):.8g}",
                    "C_std": f"{float(s):.8g}",
                    "C_sem": f"{float(e):.8g}",
                    "nReplica": n_idx,
                }
            )
    with CSV_OUT.open("w", newline="") as f:
        w = csv.DictWriter(
            f,
            fieldnames=[
                "p0",
                "T",
                "batch",
                "tauBlock",
                "dt",
                "C_mean",
                "C_std",
                "C_sem",
                "nReplica",
            ],
        )
        w.writeheader()
        w.writerows(rows)
    n_state = len({(r["p0"], r["T"]) for r in rows})
    print(f"wrote {CSV_OUT} ({len(rows)} rows, {n_state} state points)")
    if missing:
        print(f"missing {len(missing)} (p0, T):")
        for p0, T in missing:
            print(f"  p0={p0:.3f} T={T:.8g}")
        raise SystemExit(1)
    plot_sac(by_p0)


if __name__ == "__main__":
    main()
