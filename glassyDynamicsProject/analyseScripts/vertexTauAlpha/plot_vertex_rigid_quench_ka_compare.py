#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-10-21.
Rigid-quench onset p0* of the same production snapshots at KA=0 and KA=1.

Physics (A0=1, N=4096):
  KA=1 is the production energy. A floppy (E=0) state then needs A_i=1 and
  P_i=p0q in every cell, so a z-sided cell needs p0q >= sqrt(4 z tan(pi/z)):
  3.812 for a pentagon, 4.000 for a square. This holds for any KA>0, so
  KA=1 stands for all of them. KA=0 only needs P_i=p0q. Areas then trade off
  between cells, and the bound is the honeycomb sqrt(8 sqrt 3) = 3.722 (see
  plot_vertex_rigid_quench.py). KA=0 is a singular limit, not the small-KA end
  of the KA>0 family.

Snapshots come from plot_vertex_rigid_quench (partial files are fine). They
are paired by (p0, T, idx, rec) where the p0* bracket is closed at both KA.
n_eff = N dPrms^2 / dPmax^2 at the highest rigid p0q of a snapshot (just below
p0*) counts the cells that carry the residual P_i - p0q. It is ~1 when one
cell is frustrated and ~N when the whole network is.

Output (vertexModel_rigidQuench_KA1/):
  rigid_quench_ka_pairs.csv      one row per paired snapshot
  rigid_quench_ka_scatter.png    p0*(KA=1) against p0*(KA=0), per snapshot
  rigid_quench_ka_vs_tau.png     per-state median p0* vs tau_alpha, one panel per p0

Usage:
  python3 plot_vertex_rigid_quench_ka_compare.py
"""

from __future__ import annotations

import csv
import math
from collections import defaultdict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

import plot_vertex_rigid_quench as rq

Q_PENT = math.sqrt(20.0 * math.tan(math.pi / 5.0))  # ~3.8119
Q_SQUARE = 4.0
KA_STYLE = {0.0: dict(mfc="white", ls="--", label=r"$K_A=0$"), 1.0: dict(ls="-", label=r"$K_A=1$")}


def snapshots(ka: float) -> dict[tuple, dict]:
    return {(s["p0"], s["T"], s["idx"], s["rec"]): s for s in rq.reduce_snapshots(rq.load_quenches(ka))}


def frustrated_cells(ka: float) -> dict[tuple, float]:
    """n_eff of the rigid quench with the largest p0q, per snapshot."""
    top: dict[tuple, tuple[float, float]] = {}
    for path in rq.quench_dir().glob(f"rigidQuench_N{rq.N}_p*_T*_KA{ka:.4f}_idx*_bisect.csv"):
        with path.open() as f:
            # same NUL handling as rq.load_quenches (scratch I/O errors)
            for r in csv.DictReader(ln.replace("\0", "") for ln in f):
                try:
                    if int(r["rigid"]) != 1 or float(r["dPmax"]) <= 0:
                        continue
                    key = (rq.p0_key(float(r["p0"])), round(float(r["T"]), 8), int(r["idx"]), int(r["rec"]))
                    p0q = float(r["p0q"])
                    n_eff = rq.N * (float(r["dPrms"]) / float(r["dPmax"])) ** 2
                except (KeyError, ValueError, TypeError):
                    continue  # a row cut by a running job
                if key not in top or p0q > top[key][0]:
                    top[key] = (p0q, n_eff)
    return {k: v[1] for k, v in top.items()}


def pair(s0: dict, s1: dict, tau: dict, n0: dict, n1: dict) -> list[dict]:
    pairs: list[dict] = []
    for key in s0.keys() & s1.keys():
        a, b = s0[key], s1[key]
        if not (math.isfinite(a["p0star"]) and math.isfinite(b["p0star"])):
            continue
        p0, T, idx, rec = key
        pairs.append(
            {
                "p0": p0,
                "T": T,
                "idx": idx,
                "rec": rec,
                "tau_kww": tau.get((p0, T), math.nan),
                "p6_0": a["p6_0"],
                "p0star_KA0": a["p0star"],
                "p0star_KA1": b["p0star"],
                "own_rigid_KA0": a["own_rigid"],
                "own_rigid_KA1": b["own_rigid"],
                "own_p6_KA0": a["own_p6"],
                "own_p6_KA1": b["own_p6"],
                "n_eff_KA0": n0.get(key, math.nan),
                "n_eff_KA1": n1.get(key, math.nan),
            }
        )
    pairs.sort(key=lambda r: (rq.P0_ORDER.index(r["p0"]), -r["T"], r["idx"], r["rec"]))
    return pairs


def state_quantiles(snaps: dict[tuple, dict], tau: dict) -> list[dict]:
    """Median and quartiles of p0* per (p0, T); KA=1 is bimodal (square vs pentagon bound)."""
    groups: dict[tuple, list[float]] = defaultdict(list)
    for s in snaps.values():
        if math.isfinite(s["p0star"]):
            groups[(s["p0"], s["T"])].append(s["p0star"])
    out: list[dict] = []
    for (p0, T), v in groups.items():
        q25, q50, q75 = np.percentile(v, [25, 50, 75])
        out.append({"p0": p0, "T": T, "tau_kww": tau.get((p0, T), math.nan), "n": len(v),
                    "q25": q25, "median": q50, "q75": q75})
    return out


def plot_scatter(pairs: list[dict], path) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 6.0))
    for p0 in rq.P0_ORDER:
        g = [r for r in pairs if r["p0"] == p0]
        if g:
            ax.scatter([r["p0star_KA0"] for r in g], [r["p0star_KA1"] for r in g], s=30,
                       color=rq.P0_COLOR[p0], marker=rq.P0_MARKER[p0], edgecolors="white",
                       linewidths=0.6, label=rf"$p_0={p0:.3f}$", zorder=3)
    x = np.array([r["p0star_KA0"] for r in pairs])
    y = np.array([r["p0star_KA1"] for r in pairs])
    xlim = (min(rq.Q_HEX, x.min()) - 0.005, x.max() + 0.01)
    ylim = (min(Q_PENT, y.min()) - 0.02, max(Q_SQUARE, y.max()) + 0.03)
    for yy, name in ((Q_PENT, "pentagon"), (Q_SQUARE, "square")):
        ax.axhline(yy, color=rq.INK2, lw=1.0, ls="--", zorder=1)
        ax.text(1.0, yy, f"{name} {yy:.3f}  ", color=rq.INK2, fontsize=rq.FS_NOTE, va="bottom",
                ha="right", transform=ax.get_yaxis_transform())
    ax.axvline(rq.Q_HEX, color=rq.INK2, lw=1.0, ls="--", zorder=1)
    ax.text(rq.Q_HEX, 0.5, " honeycomb 3.722", rotation=90, color=rq.INK2, fontsize=rq.FS_NOTE,
            va="center", ha="left", transform=ax.get_xaxis_transform())
    ax.set_xlim(*xlim)
    ax.set_ylim(*ylim)
    ax.set_xlabel(r"onset $p_0^*$ at $K_A=0$", fontsize=rq.FS_LABEL, color=rq.INK)
    ax.set_ylabel(r"onset $p_0^*$ at $K_A=1$", fontsize=rq.FS_LABEL, color=rq.INK)
    ax.set_title(f"Same snapshot, both $K_A$ ({len(pairs)} snapshots)", fontsize=rq.FS_TITLE,
                 color=rq.INK)
    rq.style_axis(ax)
    ax.legend(fontsize=rq.FS_LEGEND, frameon=False, loc="center right")
    fig.tight_layout()
    fig.savefig(path, dpi=180)
    plt.close(fig)


def plot_vs_tau(by_ka: dict[float, list[dict]], path) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(14.0, 8.0), sharex=True, sharey=True)
    for ax, p0 in zip(axes.ravel(), rq.P0_ORDER):
        c = rq.P0_COLOR[p0]
        for ka, states in by_ka.items():
            st = sorted((s for s in states if s["p0"] == p0 and math.isfinite(s["tau_kww"])),
                        key=lambda s: s["tau_kww"])
            if st:
                med = np.array([s["median"] for s in st])
                err = [med - np.array([s["q25"] for s in st]), np.array([s["q75"] for s in st]) - med]
                ax.errorbar([s["tau_kww"] for s in st], med, yerr=err, color=c, marker=rq.P0_MARKER[p0],
                            ms=7, lw=2, capsize=3, mec=c, mew=1.2, zorder=3, **KA_STYLE[ka])
        ax.axhline(p0, color=c, lw=3, xmin=0.97, xmax=1.0, zorder=2)
        for y in (rq.Q_HEX, Q_PENT, Q_SQUARE):
            ax.axhline(y, color=rq.INK2, lw=1.0, ls="--", zorder=1)
        ax.set_xscale("log")
        ax.set_title(rf"$p_0={p0:.3f}$", fontsize=rq.FS_TITLE, color=rq.INK)
        rq.style_axis(ax)
    for ax in axes[1]:
        ax.set_xlabel(r"$\tau_\alpha$ of the parent state", fontsize=rq.FS_LABEL, color=rq.INK)
    for ax in axes[:, 0]:
        ax.set_ylabel(r"onset $p_0^*$ (median, quartiles)", fontsize=rq.FS_LABEL, color=rq.INK)
    axes[0, 2].legend(fontsize=rq.FS_LEGEND, frameon=False, loc="center right")
    fig.text(0.01, 0.005, "dashed: honeycomb 3.722 (KA=0 bound), pentagon 3.812 and square 4.000 "
             "(one-cell bounds at KA>0).  Right-edge tick: production $p_0$.",
             fontsize=rq.FS_NOTE, color=rq.INK2)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    fig.savefig(path, dpi=180)
    plt.close(fig)


def main() -> None:
    outdir = rq.outdir_for(1.0)
    outdir.mkdir(parents=True, exist_ok=True)
    tau = rq.load_tau()
    snaps = {ka: snapshots(ka) for ka in (0.0, 1.0)}
    for ka, s in snaps.items():
        n_ok = sum(math.isfinite(z["p0star"]) for z in s.values())
        n_open = sum(z["open"] for z in s.values())
        print(f"KA = {ka:g}: snapshots = {len(s)}, closed = {n_ok}, open (hi rigid) = {n_open}")
    pairs = pair(snaps[0.0], snaps[1.0], tau, frustrated_cells(0.0), frustrated_cells(1.0))
    print(f"paired snapshots = {len(pairs)}")
    if not pairs:
        return
    rq.write_csv(outdir / "rigid_quench_ka_pairs.csv", pairs)
    for p0 in rq.P0_ORDER:
        g = [r for r in pairs if r["p0"] == p0]
        if not g:
            continue
        d = np.array([r["p0star_KA1"] - r["p0star_KA0"] for r in g])
        print(f"p0={p0:.3f} n={len(g)} p0*(KA=0)={np.mean([r['p0star_KA0'] for r in g]):.4f} "
              f"p0*(KA=1)={np.mean([r['p0star_KA1'] for r in g]):.4f} shift={d.mean():.4f} "
              f"[{d.min():.4f},{d.max():.4f}] rigid@own KA0={sum(r['own_rigid_KA0'] for r in g)}/{len(g)} "
              f"KA1={sum(r['own_rigid_KA1'] for r in g)}/{len(g)} "
              f"median n_eff KA0={np.nanmedian([r['n_eff_KA0'] for r in g]):.0f} "
              f"KA1={np.nanmedian([r['n_eff_KA1'] for r in g]):.1f}")
    plot_scatter(pairs, outdir / "rigid_quench_ka_scatter.png")
    by_ka = {ka: state_quantiles(s, tau) for ka, s in snaps.items()}
    plot_vs_tau(by_ka, outdir / "rigid_quench_ka_vs_tau.png")


if __name__ == "__main__":
    main()
