def cage_matrix(vn: np.ndarray) -> sparse.csr_matrix:
    """Row j averages the displacements of the 1-hop and 2-hop mesh neighbours of j."""
    vn = vn.reshape(NV, 3)
    if vn.min() < 0 or vn.max() >= NV:
        raise ValueError("vertex neighbour index out of range")
    cand = np.sort(np.concatenate([vn, vn[vn].reshape(NV, 9)], axis=1), axis=1)
    keep = cand != np.arange(NV)[:, None]
    keep[:, 1:] &= cand[:, 1:] != cand[:, :-1]
    rows = np.broadcast_to(np.arange(NV)[:, None], cand.shape)[keep]
    cols = cand[keep]
    counts = np.bincount(rows, minlength=NV).astype(float)
    return sparse.csr_matrix((1.0 / counts[rows], (rows, cols)), shape=(NV, NV))


def min_image(d: np.ndarray) -> np.ndarray:
    return d - L_BOX * np.round(d / L_BOX)


def fs_of(r: np.ndarray) -> np.ndarray:
    """mean_j J0(q r_j) for every q of Q_GRID."""
    return j0(np.outer(Q_GRID, r)).mean(axis=1)


def sq_grid():
    """Wavevector grid (n_x >= 0 half plane) and the C++ annulus bin of every vector."""
    nmax = int(math.ceil(SQ_QMAX / DK)) + 1
    nx = np.arange(0, nmax + 1)
    ny = np.arange(-nmax, nmax + 1)
    s = np.sqrt(nx[:, None] ** 2 + ny[None, :] ** 2)  # |k| / DK
    # bin m holds 0.75 + m/2 < s < 1.25 + m/2, centred on (1 + m/2) DK
    m = np.floor(2.0 * s - 1.5).astype(int)
    ok = (s > 0.75) & (s * DK <= SQ_QMAX)
    quad = ok & (ny[None, :] >= 0)
    half = ok & ((nx[:, None] > 0) | (ny[None, :] > 0))
    nb = int(m[ok].max()) + 1
    centres = DK * (1.0 + 0.5 * np.arange(nb))
    return nx * DK, ny * DK, m, quad, half, nb, centres


SQ_KX, SQ_KY, SQ_M, SQ_QUAD, SQ_HALF, SQ_NB, SQ_CENTRES = sq_grid()


def sq_frame(xy: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    ex = np.exp(1j * np.outer(SQ_KX, xy[:, 0]))
    ey = np.exp(1j * np.outer(SQ_KY, xy[:, 1]))
    rho = ex @ ey.T
    s = (rho.real ** 2 + rho.imag ** 2) / xy.shape[0]
    out = []
    for mask in (SQ_QUAD, SQ_HALF):
        tot = np.bincount(SQ_M[mask], weights=s[mask], minlength=SQ_NB)
        cnt = np.bincount(SQ_M[mask], minlength=SQ_NB)
        with np.errstate(invalid="ignore", divide="ignore"):
            out.append(np.where(cnt > 0, tot / np.maximum(cnt, 1), np.nan))
    return out[0], out[1]


