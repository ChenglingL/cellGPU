#!/usr/bin/env python3
"""
Generated by Claude Code. 2026-11-02.
Vertex-position CRSISF on a grid of q and from several time origins, plus vertex S(q),
for every production trajectory (the 70 production states and the 11 vtx states).
Tests whether the cold vertex-position tau_alpha depends on the fixed q=6.7 (versus the
S(q) peak k_max of each state), on the age of the time origin, and on how a vertex is
followed in time (array label versus cell-triplet junction).

Physics (N=4096 cells, N_v=8192 vertices, square periodic box L=64):
  F_s^CR(q, t0, dt) = (1/N_v) sum_j J_0(q |dr_j^CR|),
  dr_j = r_j(t0+dt) - r_j(t0) (minimum image), dr_j^CR = dr_j - <dr_k>_{k in cage_j}.
  Cage of j: its 1-hop mesh neighbours (Vneighs at t0) and their neighbours, without j and
  without repeats (as vertexPositionFs.cpp; 9 vertices on a 3-valent foam).
  Label (fs_cr, as vertexPositionFs.cpp): r_j is the position of array label j.
  Junction (fs_jn): r_j(t0+dt) is the position of the label that holds j's t0 cell triplet
  at t0+dt. A T1 always turns the edge v1 -> v2 (v1 < v2) by +90 deg, so a T1 and its
  reverse turn it by 180 deg: the cells are as before but the two labels have traded
  junctions. The junction F_s does not see that; it uses the label position when the
  triplet no longer exists (a T1 that was not undone).
  t0 = first record (the C++ CRSISF) and the records nearest t0 = f * window, f = ORIGIN_FRAC.
  Plain SISF (no cage subtraction, label), <|dr^CR|^2> and <|dr^CR|^4> from the first record.
  Two-time F_s^CR(t_k -> t_j) at q = Q_PAIR for every pair of records j >= k (aging test;
  the records are log-spaced from the start of the window, 20 per decade).
  S(q) = |sum_j exp(i k.r_j)|^2 / N_v averaged on annuli of width pi/L centred on
  k = (1 + m/2) 2 pi/L, as structuralFeatures::computeStructureFactor (intKMax, dk=0.5).
  "quad": k = 2 pi (n_x, n_y)/L with n_x, n_y >= 0 (the C++ grid);
  "half": every k with n_x > 0, or n_x = 0 and n_y > 0 (all directions once).
  S(q) of the last N_SQ_LAST records (as vertexPositionSq.out -s 10) and of each origin.

Output, one file per state:
  $CELLGPU_SCRATCH/N4096/vertex/productionRuns/vertexPositionFsKScan/kscan_N4096_p<p0>_T<T>.npz
  q (nq), idx (nrep), t (nrec, time since the first record), origin_frac, origin_rec (no),
  fs_cr, fs_jn (nrep, no, nrec, nq; NaN before the origin), fs_plain (nrep, nrec, nq),
  sq_q (nb), sq_last_quad, sq_last_half (nrep, nb), sq_origin_quad, sq_origin_half (nrep, no, nb),
  q_pair, fs_pair, fs_pair_jn, swapped_pair, dead_pair (nrep, nrec, nrec; [k, j], NaN for
  j < k; fraction of t_k junctions held by another label / gone at t_j),
  msd_cr, m4_cr (nrep, 2, nrec; [:, 0] label, [:, 1] junction), waiting_time, kind.

Usage (64 workers on a CPU node, a few minutes; see local/submit/vertexFsKScan.sbatch):
  python3 vertex_position_fs_kscan.py --workers 64
  python3 vertex_position_fs_kscan.py --state 3.750,0.0113 --workers 10
Existing state files are kept unless --overwrite.
"""

from __future__ import annotations

import os

for _v in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

import argparse
import math
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
from scipy import sparse
from scipy.io import netcdf_file
from scipy.special import j0

from plot_vertex_position_fs import CSV_VTX
from plot_vertex_production_fs import load_state_points, match_p0

N = 4096
NV = 2 * N
L_BOX = 64.0
DK = 2.0 * math.pi / L_BOX
# q grid: S(q) bin centres n*pi/L from 5.40 to 7.12, plus the CRSISF q=6.7 used so far.
Q_GRID = np.array(sorted(set([round(n * math.pi / L_BOX, 12) for n in range(110, 146)] + [6.7])))
ORIGIN_FRAC = (0.0, 0.125, 0.25, 0.5)
Q_PAIR = 6.7  # q of the all-origins two-time F_s (aging test)
N_SQ_LAST = 10
SQ_QMAX = 8.6  # S(q) only up to the first peak region
OUT_SUBDIR = "vertexPositionFsKScan"


def scratch_root() -> Path:
    env = os.environ.get("CELLGPU_SCRATCH")
    return Path(env) if env else Path("/scratch/bbtm/cli6/glassyDynamics/data")


def state_stem(p0: float, T: float) -> str:
    return f"N{N}_p{p0:.4f}_T{T:.8f}"


def vertex_states() -> list[tuple[float, float, str]]:
    """Production states (cells equilibrated), then the vertex-position-only vtx states."""
    prod = load_state_points()
    out = [(match_p0(p0), T, "production") for p0, T in prod]
    for p0, T in load_state_points((CSV_VTX,))[len(prod):]:
        out.append((match_p0(p0), T, "vtx"))
    return [s for s in out if s[0] is not None]


def vertex_paths(p0: float, T: float) -> list[tuple[int, Path]]:
    d = scratch_root() / f"N{N}" / "vertex" / "productionRuns" / f"p{p0:.3f}"
    out = []
    for p in d.glob(f"glassyDynamics_{state_stem(p0, T)}_waitingTime*_idx*.nc"):
        out.append((int(p.stem.rsplit("_idx", 1)[1]), p))
    return sorted(out)


def out_dir() -> Path:
    return scratch_root() / f"N{N}" / "vertex" / "productionRuns" / OUT_SUBDIR


def out_path(p0: float, T: float) -> Path:
    return out_dir() / f"kscan_{state_stem(p0, T)}.npz"


