def read_traj(path: Path):
    with netcdf_file(str(path), "r", mmap=False) as f:
        t = np.array(f.variables["time"][:], dtype=float).ravel()
        pos = np.array(f.variables["pos"][:], dtype=float)
        vn = np.array(f.variables["Vneighs"][:], dtype=np.int64)
        vc = np.array(f.variables["VertexCellNeighbors"][:], dtype=np.int64)
        box = np.array(f.variables["BoxMatrix"][:], dtype=float)
    nrec = t.size
    # a record after the first with time 0 marks the end of a cut file (as the C++ loop)
    zero = np.flatnonzero((np.arange(nrec) > 10) & (t < 1e-12))
    if zero.size:
        nrec = int(zero[0])
    b = box[:nrec]
    if not (np.allclose(b[:, 0], L_BOX) and np.allclose(b[:, 3], L_BOX)
            and np.allclose(b[:, 1], 0.0) and np.allclose(b[:, 2], 0.0)):
        raise ValueError(f"{path.name}: box is not the square L={L_BOX}")
    return t[:nrec], pos[:nrec].reshape(nrec, NV, 2), vn[:nrec], vc[:nrec]


def origin_records(t: np.ndarray) -> np.ndarray:
    tt = t - t[0]
    win = tt[-1]
    return np.array([int(np.argmin(np.abs(tt - f * win))) for f in ORIGIN_FRAC])


def triplet_keys(vc: np.ndarray) -> np.ndarray:
    """One int64 per vertex for its (sorted) three cells: the junction's identity."""
    s = np.sort(vc.reshape(NV, 3), axis=1).astype(np.int64)
    return (s[:, 0] * N + s[:, 1]) * N + s[:, 2]


def junction_source(keys0: np.ndarray, sorted_j: tuple[np.ndarray, np.ndarray]):
    """Label that holds each t0 junction at t; the label itself where the junction is gone."""
    ks, order = sorted_j
    loc = np.minimum(np.searchsorted(ks, keys0), NV - 1)
    alive = ks[loc] == keys0
    own = np.arange(NV)
    src = np.where(alive, order[loc], own)
    return src, alive & (src != own), ~alive


def one_trajectory(path: Path):
    t, pos, vn, vc = read_traj(path)
    nrec = t.size
    orec = origin_records(t)
    no, nq = len(ORIGIN_FRAC), Q_GRID.size
    keys = [triplet_keys(vc[j]) for j in range(nrec)]
    if any(np.unique(k).size != NV for k in keys):
        raise ValueError(f"{path.name}: two vertices share a cell triplet")
    sorted_keys = []
    for k in keys:
        o = np.argsort(k)
        sorted_keys.append((k[o], o))
    # label: displacement of the vertex label; junction: of the label that holds the t0
    # cell triplet at t (undoes the label swaps of T1 + reverse T1), the label if it is gone
    fs_cr = np.full((no, nrec, nq), np.nan)
    fs_jn = np.full((no, nrec, nq), np.nan)
    fs_plain = np.full((nrec, nq), np.nan)
    # every record as origin at q = Q_PAIR: pair[k, j] = F_s^CR(t_k -> t_j), j >= k,
    # with the fraction of t_k junctions held by another label (swapped) or gone (dead) at t_j
    pair = np.full((nrec, nrec), np.nan)
    pair_jn = np.full((nrec, nrec), np.nan)
    swapped = np.full((nrec, nrec), np.nan)
    dead = np.full((nrec, nrec), np.nan)
    # cage-relative <dr^2> and <dr^4> from the first record (label and junction)
    m2 = np.full((2, nrec), np.nan)
    m4 = np.full((2, nrec), np.nan)
    sq_o_quad = np.full((no, SQ_NB), np.nan)
    sq_o_half = np.full((no, SQ_NB), np.nan)
    for k0 in range(nrec):
        cage = cage_matrix(vn[k0])
        io_list = np.flatnonzero(orec == k0)
        for j in range(k0, nrec):
            src, sw, gone = junction_source(keys[k0], sorted_keys[j])
            swapped[k0, j] = sw.mean()
            dead[k0, j] = gone.mean()
            for which, d in enumerate((min_image(pos[j] - pos[k0]),
                                       min_image(pos[j][src] - pos[k0]))):
                dcr = d - cage @ d
                r2 = dcr[:, 0] ** 2 + dcr[:, 1] ** 2
                r = np.sqrt(r2)
                (pair, pair_jn)[which][k0, j] = j0(Q_PAIR * r).mean()
                if io_list.size:
                    fs = fs_of(r)
                    for io in io_list:
                        (fs_cr, fs_jn)[which][io, j] = fs
                if k0 == 0:
                    m2[which, j] = r2.mean()
                    m4[which, j] = (r2 * r2).mean()
                    if which == 0:
                        fs_plain[j] = fs_of(np.hypot(d[:, 0], d[:, 1]))
        for io in io_list:
            sq_o_quad[io], sq_o_half[io] = sq_frame(pos[k0])
    acc_q = np.zeros(SQ_NB)
    acc_h = np.zeros(SQ_NB)
    last = range(max(0, nrec - N_SQ_LAST), nrec)
    for j in last:
        a, b = sq_frame(pos[j])
        acc_q += a
        acc_h += b
    return dict(t=t - t[0], origin_rec=orec, fs_cr=fs_cr, fs_jn=fs_jn, fs_plain=fs_plain,
                sq_last_quad=acc_q / len(last), sq_last_half=acc_h / len(last),
                sq_origin_quad=sq_o_quad, sq_origin_half=sq_o_half,
                fs_pair=pair, fs_pair_jn=pair_jn, swapped_pair=swapped, dead_pair=dead,
                msd_cr=m2, m4_cr=m4)


def work(task):
    key, idx, path = task
    t0 = time.time()
    try:
        res = one_trajectory(path)
    except Exception as exc:  # report and leave the replica out
        return key, idx, None, f"{path.name}: {type(exc).__name__}: {exc}"
    return key, idx, res, f"{path.name} {time.time() - t0:.1f}s"


def waiting_time(path: Path) -> float:
    return float(path.name.split("_waitingTime", 1)[1].split("_idx", 1)[0])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--state", action="append", default=[], help="p0,T (repeatable)")
    ap.add_argument("--overwrite", action="store_true")
    args = ap.parse_args()

    states = vertex_states()
    if args.state:
        want = [tuple(float(x) for x in s.split(",")) for s in args.state]
        states = [s for s in states
                  if any(abs(s[0] - p) < 1e-6 and abs(s[1] - T) / T < 1e-6 for p, T in want)]
    out_dir().mkdir(parents=True, exist_ok=True)

    tasks, meta = [], {}
    for p0, T, kind in states:
        if out_path(p0, T).exists() and not args.overwrite:
            continue
        paths = vertex_paths(p0, T)
        if not paths:
            print(f"no trajectories for p0={p0:.3f} T={T:.8f}")
            continue
        meta[(p0, T)] = (kind, waiting_time(paths[0][1]), len(paths))
        tasks += [((p0, T), idx, p) for idx, p in paths]
    print(f"{len(meta)} states, {len(tasks)} trajectories, {args.workers} workers, "
          f"nq={Q_GRID.size}, origins={ORIGIN_FRAC}")

    results: dict = {k: {} for k in meta}
    done = {k: 0 for k in meta}
    t_start = time.time()
    with Pool(args.workers) as pool:
        for key, idx, res, msg in pool.imap_unordered(work, tasks, chunksize=1):
            done[key] += 1
            if res is None:
                print("FAILED", msg, flush=True)
            else:
                results[key][idx] = res
            if done[key] == meta[key][2]:
                write_state(key, meta[key], results.pop(key))
                print(f"wrote p0={key[0]:.3f} T={key[1]:.8f} "
                      f"({time.time() - t_start:.0f}s elapsed)", flush=True)


def write_state(key, meta, reps: dict) -> None:
    p0, T = key
    kind, tw, _n = meta
    if not reps:
        print(f"no replica of p0={p0:.3f} T={T:.8f} succeeded")
        return
    idxs = sorted(reps)
    nrecs = {reps[i]["t"].size for i in idxs}
    if len(nrecs) != 1:
        raise SystemExit(f"p0={p0} T={T}: replicas have different record counts {sorted(nrecs)}")
    t_ref = reps[idxs[0]]["t"]
    for i in idxs:
        dt = np.max(np.abs(reps[i]["t"] - t_ref) / np.maximum(t_ref, 1.0))
        if dt > 1e-6:
            raise SystemExit(f"p0={p0} T={T} idx={i}: record times differ ({dt:.2e})")
    orec = reps[idxs[0]]["origin_rec"]
    if any(not np.array_equal(reps[i]["origin_rec"], orec) for i in idxs):
        raise SystemExit(f"p0={p0} T={T}: origin records differ between replicas")
    per_rep = {name: np.stack([reps[i][name] for i in idxs])
               for name in reps[idxs[0]] if name not in ("t", "origin_rec")}
    np.savez_compressed(
        out_path(p0, T),
        p0=p0, T=T, kind=kind, waiting_time=tw, q=Q_GRID, idx=np.array(idxs),
        t=t_ref, origin_frac=np.array(ORIGIN_FRAC), origin_rec=orec,
        sq_q=SQ_CENTRES, q_pair=Q_PAIR, **per_rep,
    )


if __name__ == "__main__":
    main()
