#!/usr/bin/env python3
"""
Generated by Cursor. 2026-08-26.
Fourth-batch T grid from combined longest-crossed CRSISF 1/e tau_alpha.

Physics:
  Measured tau_alpha(T) is the longest waiting time whose CRSISF still
  crosses 1/e. Anchors: first batch + batch 2 + batch 3 (later batch
  overrides the same T). Rerun a target tau_k = 10**(1+k/3) if the
  current-best run (batch 3 if that tau_k was retargeted, else batch 2)
  never crossed or differs from tau_k by a factor >= 1.5.
  Invert on batch-2+3 anchors (same tau_block protocol). Batch 1 is plotted
  but not used for inversion: those t_w are shorter (Voronoi tau_block).
  New T: walk log tau vs 1/T along T-sorted segments (hot end: log T).

Usage:
  python3 propose_vertex_tau_alpha_batch4.py
"""

from __future__ import annotations

import csv
import math
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
CURVE_B1 = HERE / "vertexModel_tauAlpha_test" / "vertexModel_tauAlpha_test_per_curve.csv"
CURVE_B2 = HERE / "vertexModel_tauAlpha_batch2" / "vertexModel_tauAlpha_batch2_per_curve.csv"
CURVE_B3 = HERE / "vertexModel_tauAlpha_batch3" / "vertexModel_tauAlpha_batch3_per_curve.csv"
B2_STATE = HERE / "vertexModel_tauAlpha_batch2" / "state_points.csv"
B3_STATE = HERE / "vertexModel_tauAlpha_batch3" / "state_points.csv"
OUTDIR = HERE / "vertexModel_tauAlpha_batch4"

P0_ORDER = (3.750, 3.775, 3.800, 3.815, 3.825, 3.850)
TAU_TARGETS = [10.0 ** (1.0 + k / 3.0) for k in range(10)]
RATIO_CUT = 1.5


def load_curves(path: Path):
    rows = []
    with path.open() as f:
        for r in csv.DictReader(f):
            tau_s = (r.get("tauAlpha") or "").strip()
            tau = float(tau_s) if tau_s else math.nan
            est_s = (r.get("tauAlphaEst") or "").strip()
            rows.append(
                {
                    "p0": float(r["p0"]),
                    "T": float(r["T"]),
                    "waitingTime": float(r["waitingTime"]),
                    "tauAlphaEst": float(est_s) if est_s else math.nan,
                    "tauAlpha": tau,
                    "crossed": int(r["crossed"]),
                }
            )
    return rows


def load_state(path: Path):
    pts = []
    with path.open() as f:
        for r in csv.DictReader(f):
            pts.append((float(r["p0"]), float(r["T"]), float(r["tauAlphaEst"])))
    return pts


def longest_crossed_tw_rows(rows, batch):
    """Longest t_w that still crossed 1/e; else longest t_w (uncrossed)."""
    groups = defaultdict(list)
    for r in rows:
        groups[(r["p0"], r["T"])].append(r)
    out = []
    for (p0, T), grp in sorted(groups.items()):
        crossed = [
            z
            for z in grp
            if z["crossed"] == 1 and math.isfinite(z["tauAlpha"]) and z["tauAlpha"] > 0
        ]
        best = max(crossed, key=lambda z: z["waitingTime"]) if crossed else max(
            grp, key=lambda z: z["waitingTime"]
        )
        out.append(
            {
                "p0": p0,
                "T": T,
                "waitingTime": best["waitingTime"],
                "tauAlphaEst": best["tauAlphaEst"],
                "tauAlpha": best["tauAlpha"],
                "crossed": 1 if crossed else 0,
                "batch": batch,
            }
        )
    return out


def merge_anchors(*lists):
    """Later lists override the same (p0, T)."""
    by_key = {}
    for lst in lists:
        for a in lst:
            hit = None
            for k, old in by_key.items():
                if abs(old["p0"] - a["p0"]) < 1e-4 and abs(a["T"] - old["T"]) / max(
                    abs(old["T"]), 1e-30
                ) < 1e-5:
                    hit = k
                    break
            if hit is None:
                by_key[(a["p0"], a["T"], a["batch"])] = dict(a)
            else:
                by_key[hit] = dict(a)
    return sorted(by_key.values(), key=lambda z: (z["p0"], -z["T"]))


def match_anchor(p0, T, anchors, rel=1e-5):
    for a in anchors:
        if abs(a["p0"] - p0) < 1e-4 and abs(a["T"] - T) / max(abs(T), 1e-30) < rel:
            return a
    return None


def find_state_T(state_pts, p0, tau_k):
    for sp0, sT, stau in state_pts:
        if abs(sp0 - p0) < 1e-4 and abs(stau - tau_k) / tau_k < 1e-4:
            return sT
    return None


def meas_table(anchors, p0):
    """(T, tau) hot to cold, longest crossed only; unique T."""
    tab = []
    for a in anchors:
        if abs(a["p0"] - p0) > 1e-4:
            continue
        if a["crossed"] != 1 or not math.isfinite(a["tauAlpha"]) or a["tauAlpha"] <= 0:
            continue
        tab.append((a["T"], a["tauAlpha"]))
    tab.sort(key=lambda x: -x[0])
    return tab


def invT_logtau(table):
    x = np.array([1.0 / T for T, _ in table], dtype=float)
    y = np.array([math.log(tau) for _, tau in table], dtype=float)
    order = np.argsort(x)
    return x[order], y[order]


def invert_T_loglog_hot(table, tau_target):
    T0, tau0 = table[0]
    T1, tau1 = table[1]
    lx0, ly0 = math.log(T0), math.log(tau0)
    lx1, ly1 = math.log(T1), math.log(tau1)
    slope = (ly1 - ly0) / (lx1 - lx0)
    if slope == 0:
        raise ValueError("flat measured tau (log T)")
    lx = lx0 + (math.log(tau_target) - ly0) / slope
    return math.exp(lx)


def invert_T_for_tau_meas(table, tau_target):
    """Walk hot-to-cold segments so a non-monotonic tau(T) still interpolates."""
    yt = math.log(tau_target)
    tau_hot = table[0][1]
    tau_cold = table[-1][1]
    if tau_target <= tau_hot:
        return invert_T_loglog_hot(table, tau_target), "logT"
    for i in range(len(table) - 1):
        T0, tau0 = table[i]
        T1, tau1 = table[i + 1]
        lo, hi = min(tau0, tau1), max(tau0, tau1)
        if lo <= tau_target <= hi:
            if tau0 == tau1:
                return T0, "1/T"
            y0, y1 = math.log(tau0), math.log(tau1)
            x0, x1 = 1.0 / T0, 1.0 / T1
            inv_T = x0 + (yt - y0) * (x1 - x0) / (y1 - y0)
            if inv_T <= 0:
                raise ValueError(f"non-positive 1/T for tau={tau_target}")
            return 1.0 / inv_T, "1/T"
    if tau_target >= tau_cold:
        x = [1.0 / T for T, _ in table]
        y = [math.log(tau) for _, tau in table]
        slope = (y[-1] - y[-2]) / (x[-1] - x[-2])
        if slope == 0:
            raise ValueError("flat measured tau")
        inv_T = x[-1] + (yt - y[-1]) / slope
        if inv_T <= 0:
            raise ValueError(f"non-positive 1/T for tau={tau_target}")
        return 1.0 / inv_T, "1/T"
    raise ValueError(f"could not invert tau={tau_target}")


def tau_meas_of_T(table, T):
    x, y = invT_logtau(table)
    inv_T = 1.0 / T
    if inv_T <= x[0]:
        slope = (y[1] - y[0]) / (x[1] - x[0])
        return math.exp(y[0] + slope * (inv_T - x[0]))
    if inv_T >= x[-1]:
        slope = (y[-1] - y[-2]) / (x[-1] - x[-2])
        return math.exp(y[-1] + slope * (inv_T - x[-1]))
    return math.exp(float(np.interp(inv_T, x, y)))


def fold_ratio(meas, est):
    if not (meas > 0 and est > 0 and math.isfinite(meas) and math.isfinite(est)):
        return math.nan
    return max(meas / est, est / meas)


def write_csv(path: Path, fieldnames, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in rows:
            w.writerow(r)
    print(f"wrote {path} ({len(rows)} rows)")


def plot_grid(anchors, points, outpath: Path):
    fig, axes = plt.subplots(2, 3, figsize=(11.0, 7.2), sharex=False, sharey=True)
    batch_style = {
        1: dict(c="0.55", s=22, zorder=3, label="batch-1 longest crossed"),
        2: dict(c="C1", s=28, zorder=4, label="batch-2 longest crossed"),
        3: dict(c="C3", s=36, zorder=5, label="batch-3 longest crossed"),
    }
    for i, p0 in enumerate(P0_ORDER):
        ax = axes.ravel()[i]
        tab = meas_table([a for a in anchors if a["batch"] >= 2], p0)
        aa = [a for a in anchors if abs(a["p0"] - p0) < 1e-4]
        for b, sty in batch_style.items():
            crossed = [
                a
                for a in aa
                if a["batch"] == b and a["crossed"] == 1 and math.isfinite(a["tauAlpha"])
            ]
            if not crossed:
                continue
            ax.scatter(
                [a["T"] for a in crossed],
                [a["tauAlpha"] for a in crossed],
                c=sty["c"],
                s=sty["s"],
                zorder=sty["zorder"],
                label=sty["label"],
            )
        if len(tab) >= 2:
            Ts = np.geomspace(min(T for T, _ in tab) * 0.6, max(T for T, _ in tab) * 1.3, 80)
            ax.plot(Ts, [tau_meas_of_T(tab, T) for T in Ts], "C0-", lw=1.1, label=r"interp $\tau(T)$")
        pp = [p for p in points if abs(float(p["p0"]) - p0) < 1e-4]
        if pp:
            ax.scatter(
                [float(p["T"]) for p in pp],
                [float(p["tauAlphaEst"]) for p in pp],
                facecolors="none",
                edgecolors="C2",
                s=52,
                zorder=6,
                label="batch-4 $T$",
            )
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_title(rf"$p_0={p0:.3f}$")
        ax.set_xlabel(r"$T$")
        ax.set_ylabel(r"$\tau_\alpha$")
        ax.legend(loc="best", fontsize=6, frameon=False)
    fig.suptitle(r"batch 4: $T$ from combined longest-crossed $\tau_\alpha$", y=1.01)
    fig.tight_layout()
    fig.savefig(outpath, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {outpath}")


def main():
    a1 = longest_crossed_tw_rows(load_curves(CURVE_B1), 1)
    a2 = longest_crossed_tw_rows(load_curves(CURVE_B2), 2)
    a3 = longest_crossed_tw_rows(load_curves(CURVE_B3), 3)
    anchors_all = merge_anchors(a1, a2, a3)
    anchors_inv = merge_anchors(a2, a3)
    b2 = load_state(B2_STATE)
    b3 = load_state(B3_STATE)

    print("current-best (batch 3 else batch 2) longest crossed:")
    points = []
    print("batch-4 reruns:")
    for p0 in P0_ORDER:
        tab = meas_table(anchors_inv, p0)
        if len(tab) < 2:
            raise SystemExit(f"need >=2 measured anchors for p0={p0}")
        for tau_k in TAU_TARGETS:
            T3 = find_state_T(b3, p0, tau_k)
            T2 = find_state_T(b2, p0, tau_k)
            if T3 is not None:
                T_old, src_run = T3, "b3"
                pool = a3
            else:
                T_old, src_run = T2, "b2"
                pool = a2
            anc = match_anchor(p0, T_old, pool) if T_old is not None else None
            meas = anc["tauAlpha"] if anc and anc["crossed"] == 1 else math.nan
            rat = fold_ratio(meas, tau_k)
            never = not math.isfinite(meas)
            off = math.isfinite(rat) and rat >= RATIO_CUT
            print(
                f"  p0={p0:.3f} tau_k={tau_k:.6g} {src_run} T={T_old if T_old else math.nan:.6g} "
                f"meas={meas:.4g} ratio={rat:.3g}"
            )
            if not (never or off):
                continue
            T, how = invert_T_for_tau_meas(tab, tau_k)
            src = "meas_inverted_logT" if how == "logT" else "meas_inverted"
            reason = "never_crossed" if never else "ratio>=1.5"
            print(
                f"    -> T_new={T:.6g} {reason} {src}"
            )
            points.append(
                {
                    "p0": f"{p0:.3f}",
                    "T": f"{T:.8g}",
                    "tauAlphaEst": f"{tau_k:.6g}",
                    "T_old": "" if T_old is None else f"{T_old:.8g}",
                    "tauMeasUsed": "" if not math.isfinite(meas) else f"{meas:.8g}",
                    "ratio": "" if not math.isfinite(rat) else f"{rat:.6g}",
                    "reason": reason,
                    "source": src,
                    "fromBatch": src_run,
                }
            )

    OUTDIR.mkdir(parents=True, exist_ok=True)
    write_csv(
        OUTDIR / "anchors.csv",
        ["p0", "T", "waitingTime", "tauAlphaEst", "tauAlpha", "crossed", "batch"],
        [
            {
                "p0": f"{a['p0']:.3f}",
                "T": f"{a['T']:.8g}",
                "waitingTime": f"{a['waitingTime']:.8g}",
                "tauAlphaEst": "" if not math.isfinite(a["tauAlphaEst"]) else f"{a['tauAlphaEst']:.8g}",
                "tauAlpha": "" if not math.isfinite(a["tauAlpha"]) else f"{a['tauAlpha']:.8g}",
                "crossed": a["crossed"],
                "batch": a["batch"],
            }
            for a in anchors_all
        ],
    )
    write_csv(
        OUTDIR / "state_points.csv",
        [
            "p0",
            "T",
            "tauAlphaEst",
            "T_old",
            "tauMeasUsed",
            "ratio",
            "reason",
            "source",
            "fromBatch",
        ],
        points,
    )
    plot_grid(anchors_all, points, OUTDIR / "vertexModel_tauAlpha_batch4_tau_vs_T.png")
    print(f"n_jobs={len(points)}")


if __name__ == "__main__":
    main()
