def fmt_tau(x: float) -> str:
    return format(x, ".16g")


def rows_from_notebook() -> list[dict]:
    out = []
    for p0, Ts, taus in zip(P0, TEMPERATURE, TAU_ALPHA):
        if len(Ts) != len(taus):
            raise ValueError(f"length mismatch for p0={p0}: {len(Ts)} T vs {len(taus)} tau")
        for T, tau in zip(Ts, taus):
            out.append(
                {
                    "p0": p0,
                    "T": T,
                    "tauAlpha": tau,
                    "source": "data_subArrhenius_2026_06_05.nb",
                }
            )
    return out


def rows_from_additional() -> list[dict]:
    return [
        {
            "p0": p0,
            "T": T,
            "tauAlpha": tau,
            "source": "additionalTauAlpha_2026_06_06.csv",
        }
        for p0, T, tau in ADDITIONAL
    ]


def write_csv_g(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["p0", "T", "tauAlpha", "source"])
        w.writeheader()
        for r in rows:
            w.writerow(
                {
                    "p0": r["p0"],
                    "T": r["T"],
                    "tauAlpha": fmt_tau(r["tauAlpha"]),
                    "source": r["source"],
                }
            )


def sort_key(r: dict):
    return (-Decimal(r["p0"]), -Decimal(r["T"]))


def main() -> None:
    here = Path(__file__).resolve().parent
    outdir = here / "data_2DVoronoi"

    nb = rows_from_notebook()
    add = rows_from_additional()
    all_rows = sorted(nb + add, key=sort_key)

    write_csv_g(outdir / "tauAlpha_2DVoronoi_all.csv", all_rows)

    by_p = {}
    for r in all_rows:
        by_p.setdefault(r["p0"], []).append(r)
    for p0 in sorted(by_p, key=Decimal, reverse=True):
        rows = sorted(by_p[p0], key=lambda r: -Decimal(r["T"]))
        write_csv_g(outdir / f"tauAlpha_2DVoronoi_p{p0}.csv", rows)

    print(f"wrote {len(all_rows)} rows ({len(nb)} notebook + {len(add)} additional)")
    print(f"p0 values: {sorted(by_p, key=Decimal, reverse=True)}")
    print(f"outdir: {outdir}")


if __name__ == "__main__":
    main()
